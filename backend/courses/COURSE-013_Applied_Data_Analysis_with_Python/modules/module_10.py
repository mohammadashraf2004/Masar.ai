            "## 17. Choosing K with the elbow method\n"
            "\n"
            "K-Means requires K in advance.\n"
            "\n"
            "The elbow method fits several values:\n"
            "\n"
            "```python\n"
            "k_range = range(\n"
            "    1,\n"
            "    11\n"
            ")\n"
            "```\n"
            "\n"
            "For each K:\n"
            "\n"
            "```text\n"
            "fit K-Means\n"
            "record inertia\n"
            "```\n"
            "\n"
            "Then plot:\n"
            "\n"
            "```text\n"
            "K\n"
            "versus\n"
            "inertia\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 17.1 Why inertia always decreases\n"
            "\n"
            "As K grows, clusters can become smaller.\n"
            "\n"
            "At the extreme:\n"
            "\n"
            "```text\n"
            "one cluster per point\n"
            "→ near-zero within-cluster distance\n"
            "```\n"
            "\n"
            "So the question is not:\n"
            "\n"
            "> Where is inertia smallest?\n"
            "\n"
            "It is:\n"
            "\n"
            "> Where does additional K stop giving a large improvement?\n"
            "\n"
            "The source calls this the:\n"
            "\n"
            "```text\n"
            "elbow\n"
            "```\n"
            "\n"
            "and interprets the shown dataset's elbow as:\n"
            "\n"
            "```text\n"
            "K = 2\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 17.2 Important lesson\n"
            "\n"
            "The elbow is a heuristic.\n"
            "\n"
            "You should combine it with:\n"
            "\n"
            "- clustering metrics,\n"
            "- interpretability,\n"
            "- business usefulness.\n"
            "\n"
            "[[IMAGE_NEEDED: Elbow method | Inertia curve from K=1 to K=10 with strong drop then flattening and elbow at K=2 | Learner should see diminishing returns rather than simply choosing maximum K]]\n"
            "\n"
            "---\n"
