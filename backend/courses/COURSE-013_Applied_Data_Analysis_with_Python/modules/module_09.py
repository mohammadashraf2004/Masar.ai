            "## 28. Why model evaluation matters\n"
            "\n"
            "The chapter then moves from modeling to the question:\n"
            "\n"
            "> Is this model actually useful?\n"
            "\n"
            "Evaluation quantifies performance.\n"
            "\n"
            "But the correct metric depends on the prediction problem.\n"
            "\n"
            "```text\n"
            "Regression\n"
            "→ numeric prediction error\n"
            "\n"
            "Classification\n"
            "→ class-decision quality\n"
            "```\n"
            "\n"
            "The chapter first demonstrates metrics on model outputs, then later explains why evaluation should happen on unseen data rather than the same training observations.\n"
            "\n"
            "That later correction is essential.\n"
            "\n"
            "---\n"
            "\n"
            "## 29. Regression metric: MAE\n"
            "\n"
            "Mean Absolute Error:\n"
            "\n"
            "```text\n"
            "MAE\n"
            "=\n"
            "average(\n"
            "    |actual - predicted|\n"
            ")\n"
            "```\n"
            "\n"
            "Source example:\n"
            "\n"
            "```text\n"
            "MAE ≈ 3167.80\n"
            "```\n"
            "\n"
            "Interpretation:\n"
            "\n"
            "> Predictions differ from actual salary by about 3,168 units on average.\n"
            "\n"
            "Advantages emphasized by the source:\n"
            "\n"
            "- same unit as target,\n"
            "- intuitive,\n"
            "- less sensitive to extreme errors than squared-error metrics.\n"
            "\n"
            "---\n"
            "\n"
            "## 30. Regression metrics: MSE and RMSE\n"
            "\n"
            "---\n"
            "\n"
            "### 30.1 MSE\n"
            "\n"
            "Mean Squared Error:\n"
            "\n"
            "```text\n"
            "MSE\n"
            "=\n"
            "average(\n"
            "    (actual - predicted)²\n"
            ")\n"
            "```\n"
            "\n"
            "The chapter uses squared errors to penalize large misses.\n"
            "\n"
            "Source example:\n"
            "\n"
            "```text\n"
            "MSE ≈ 15,634,705.79\n"
            "```\n"
            "\n"
            "Because the error is squared, the unit is squared and less intuitive.\n"
            "\n"
            "---\n"
            "\n"
            "### 30.2 RMSE\n"
            "\n"
            "Root Mean Squared Error:\n"
            "\n"
            "```text\n"
            "RMSE\n"
            "=\n"
            "sqrt(MSE)\n"
            "```\n"
            "\n"
            "Source:\n"
            "\n"
            "```text\n"
            "RMSE ≈ 3954.07\n"
            "```\n"
            "\n"
            "This returns error to the target's original unit.\n"
            "\n"
            "The source says RMSE still penalizes large errors more strongly than MAE.\n"
            "\n"
            "---\n"
            "\n"
            "### 30.3 Compare MAE and RMSE\n"
            "\n"
            "If:\n"
            "\n"
            "```text\n"
            "RMSE\n"
            ">>\n"
            "MAE\n"
            "```\n"
            "\n"
            "there may be some relatively large prediction errors.\n"
            "\n"
            "If they are close:\n"
            "\n"
            "```text\n"
            "error sizes may be more uniform\n"
            "```\n"
            "\n"
            "This comparison gives more insight than either metric alone.\n"
            "\n"
            "---\n"
            "\n"
