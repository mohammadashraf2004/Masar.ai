            "## 13. What is clustering?\n"
            "\n"
            "Clustering groups similar observations without known labels.\n"
            "\n"
            "The core question is:\n"
            "\n"
            "> Which observations naturally belong together?\n"
            "\n"
            "The source connects clustering with:\n"
            "\n"
            "- market segmentation,\n"
            "- document clustering,\n"
            "- social-network analysis.\n"
            "\n"
            "A clustering model produces inferred group labels.\n"
            "\n"
            "These labels are created from structure in the feature space, not from a pre-existing target.\n"
            "\n"
            "---\n"
            "\n"
            "## 14. K-Means\n"
            "\n"
            "K-Means partitions observations into:\n"
            "\n"
            "```text\n"
            "K clusters\n"
            "```\n"
            "\n"
            "Every observation belongs to one cluster.\n"
            "\n"
            "Each cluster has a:\n"
            "\n"
            "```text\n"
            "centroid\n"
            "```\n"
            "\n"
            "which is the mean position of its assigned points.\n"
            "\n"
            "The chapter describes the goal as:\n"
            "\n"
            "```text\n"
            "small within-cluster variation\n"
            "large separation between clusters\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "## 15. How K-Means works\n"
            "\n"
            "### Step 1 — Initialize K centroids\n"
            "\n"
            "The source discusses random initialization and later uses:\n"
            "\n"
            "```text\n"
            "K-Means++\n"
            "```\n"
            "\n"
            "for better-separated starting centroids.\n"
            "\n"
            "---\n"
            "\n"
            "### Step 2 — Assign points\n"
            "\n"
            "Each point is assigned to the nearest centroid.\n"
            "\n"
            "The commonly used distance in the source is:\n"
            "\n"
            "```text\n"
            "Euclidean distance\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### Step 3 — Update centroids\n"
            "\n"
            "For every cluster:\n"
            "\n"
            "```text\n"
            "new centroid\n"
            "=\n"
            "mean of assigned points\n"
            "```\n"
            "\n"
            "The centroid moves to the cluster center.\n"
            "\n"
            "---\n"
            "\n"
            "### Step 4 — Calculate inertia\n"
            "\n"
            "Inertia measures total within-cluster squared distance.\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "Inertia\n"
            "=\n"
            "sum of squared distances\n"
            "from points\n"
            "to their assigned centroid\n"
            "```\n"
            "\n"
            "Lower inertia means tighter clusters.\n"
            "\n"
            "---\n"
            "\n"
            "### Step 5 — Repeat until convergence\n"
            "\n"
            "The chapter lists convergence conditions such as:\n"
            "\n"
            "- centroids stop moving,\n"
            "- assignments stop changing,\n"
            "- inertia improvement becomes very small,\n"
            "- maximum iterations reached.\n"
            "\n"
            "[[IMAGE_NEEDED: K-Means iterative process | Four frames showing initial random centroids, point assignment, centroid movement, and converged clusters | Learner should understand assignment-update repetition]]\n"
            "\n"
            "---\n"
            "\n"
            "## 16. K-Means with Python\n"
            "\n"
            "The source standardizes before clustering:\n"
            "\n"
            "```python\n"
            "from sklearn.cluster import KMeans\n"
            "\n"
            "scaler = StandardScaler()\n"
            "\n"
            "X_scaled = scaler.fit_transform(\n"
            "    customer_behavior\n"
