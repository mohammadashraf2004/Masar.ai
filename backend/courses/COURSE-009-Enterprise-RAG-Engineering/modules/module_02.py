                       '## 13. Chunking: why a document cannot remain one giant string\n'
                       '\n'
                       'After parsing, the system may still have segments that are far too large '
                       'or too broad for effective retrieval. **Chunking** breaks larger text into '
                       'smaller pieces that can be embedded, searched, and selectively passed to '
                       'the generator.\n'
                       '\n'
                       'Chunking exists for three different reasons:\n'
                       '\n'
                       '1. **Capacity:** LLM and embedding-model context windows are finite.\n'
                       '2. **Efficiency:** processing unnecessarily long contexts increases '
                       'latency and cost.\n'
                       '3. **Quality:** smaller coherent chunks often represent one topic more '
                       'clearly and reduce irrelevant material presented to both retriever and '
                       'generator.\n'
                       '\n'
                       'Suppose you have many earnings-call transcripts but the user asks only '
                       'about head-count growth. Sending entire transcripts wastes context on '
                       'revenue, product launches, and other topics. Chunking allows retrieval to '
                       'select only passages about the requested subject.\n'
                       '\n'
                       'The goal is not to create the smallest possible pieces. The goal is to '
                       'create **retrieval units that are small enough to be focused yet large '
                       'enough to preserve the context needed to understand them**.\n'
                       '\n'
                       '{{exercise:M01.L02.EX06}}\n'
                       '\n'
