                       '\n'
                       '## 44. RAG prompt engineering\n'
                       '\n'
                       'Prompt engineering in RAG is the process of arranging instructions, the '
                       'original user request, and retrieved evidence so the model knows how to '
                       'use the context.\n'
                       '\n'
                       'A minimal pattern is:\n'
                       '\n'
                       '```text\n'
                       'You are a helpful information-processing assistant.\n'
                       '\n'
                       '<query>\n'
                       '{original_query}\n'
                       '</query>\n'
                       '\n'
                       '<context>\n'
                       '{retrieved_chunks}\n'
                       '</context>\n'
                       '\n'
                       'Answer the query using the provided context.\n'
                       '```\n'
                       '\n'
                       'The chapter makes several useful points.\n'
                       '\n'
                       'First, the generation prompt can use the **original query**, even if a '
                       'rewritten query was used for retrieval. The original query preserves the '
                       "user's intended task.\n"
                       '\n'
                       'Second, placement can matter. The source notes that many models may '
                       'respond better when the query appears before the context.\n'
                       '\n'
                       'Third, prompt instructions can explicitly constrain unsupported answers:\n'
                       '\n'
                       '```text\n'
                       'If the answer cannot reasonably be inferred from the context,\n'
                       'say that you do not know.\n'
                       '```\n'
                       '\n'
                       'Fourth, prompts can be task-specific. A question-answering prompt need not '
                       'look identical to a summarization prompt.\n'
                       '\n'
                       'Finally, XML-style tags can make prompt sections visually and structurally '
                       'distinct.\n'
                       '\n'
                       'The overall rule is not “use one universal prompt.” It is **design, '
                       'evaluate, and version prompts as part of the RAG system**.\n'
                       '\n'
                       '---\n'
                       '\n'
                       '## 45. Evaluating LLMs and prompt templates\n'
                       '\n'
                       'To choose a generator and prompt, start with evaluation queries that '
                       'resemble real user requests. If real traffic exists, sample from it. '
                       'Otherwise, construct representative test cases based on the data and '
                       'expected usage.\n'
                       '\n'
                       'The chapter highlights two core answer dimensions:\n'
                       '\n'
                       '- **Relevance:** does the answer actually address the query?\n'
                       '- **Faithfulness:** is the answer supported by the retrieved documents?\n'
                       '\n'
                       'Three evaluation approaches are discussed.\n'
                       '\n'
                       '### LLM-as-a-judge\n'
                       'A model is prompted to score or critique outputs. This is convenient and '
                       'flexible, but can be expensive, slow, inconsistent, and itself capable of '
                       'faulty reasoning.\n'
                       '\n'
                       '### Dedicated NLG evaluation models\n'
                       'Smaller models trained for specific evaluation dimensions can be cheaper, '
                       'faster, and more stable for targeted tasks such as faithfulness '
                       'detection.\n'
                       '\n'
                       '### Human evaluation\n'
                       'Humans can provide the most nuanced judgment but are expensive and '
                       'time-consuming. The chapter treats human evaluation as the high-quality '
                       'reference, often used for smaller final checks.\n'
                       '\n'
                       'The practical workflow is:\n'
                       '\n'
                       '```text\n'
                       'evaluation queries\n'
                       '→ run candidate RAG configurations\n'
                       '→ collect answers\n'
                       '→ score relevance / faithfulness / other criteria\n'
                       '→ compare configurations\n'
                       '→ select the best trade-off\n'
                       '```\n'
