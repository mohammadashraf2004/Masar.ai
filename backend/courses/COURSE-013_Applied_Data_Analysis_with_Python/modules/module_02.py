            "Result conceptually:\n"
            "\n"
            "```text\n"
            "Timestamp('1970-01-01 00:00:00')\n"
            "```\n"
            "\n"
            "Convert a known format:\n"
            "\n"
            "```python\n"
            "pd.to_datetime(\n"
            "    ['20200101', '20200102'],\n"
            "    format='%Y%m%d'\n"
            ")\n"
            "```\n"
            "\n"
            "Specifying a format tells Pandas how to interpret the string.\n"
            "\n"
            "---\n"
            "\n"
            "### 17.3 Handling invalid dates\n"
            "\n"
            "Suppose:\n"
            "\n"
            "```python\n"
            "pd.to_datetime([\n"
            "    '20200101',\n"
            "    'not a date'\n"
            "])\n"
            "```\n"
            "\n"
            "The invalid value can raise an error.\n"
            "\n"
            "The chapter shows:\n"
            "\n"
            "```python\n"
            "pd.to_datetime(\n"
            "    ['20200101', 'not a date'],\n"
            "    errors='coerce'\n"
            ")\n"
