            "\n"
            "```text\n"
            "bias ↓\n"
            "variance ↑\n"
            "```\n"
            "\n"
            "Increasing regularization often:\n"
            "\n"
            "```text\n"
            "variance ↓\n"
            "bias ↑\n"
            "```\n"
            "\n"
            "The goal is not:\n"
            "\n"
            "```text\n"
            "minimum bias at any cost\n"
            "```\n"
            "\n"
            "or:\n"
            "\n"
            "```text\n"
            "minimum variance at any cost\n"
            "```\n"
            "\n"
            "It is to find a useful balance.\n"
            "\n"
            "The source uses:\n"
            "\n"
            "```text\n"
            "linear regression\n"
            "versus\n"
            "high-degree polynomial regression\n"
            "```\n"
            "\n"
            "as intuition.\n"
            "\n"
            "---\n"
            "\n"
            "### 3.1 Underfitting\n"
            "\n"
            "```text\n"
            "too simple\n"
            "→ misses real pattern\n"
            "→ high bias\n"
            "```\n"
            "\n"
            "### 3.2 Overfitting\n"
            "\n"
            "```text\n"
            "too flexible\n"
            "→ follows noise\n"
            "→ high variance\n"
            "```\n"
            "\n"
            "### 3.3 Ensemble motivation\n"
            "\n"
            "Ensembles can reduce one or both problems by combining multiple learners.\n"
            "\n"
            "Bagging is especially associated with reducing variance.\n"
            "\n"
            "Boosting is especially associated with sequentially correcting remaining error and reducing bias, while regularization controls variance.\n"
