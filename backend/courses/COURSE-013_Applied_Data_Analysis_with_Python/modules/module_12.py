            "## 11. Softmax\n"
            "\n"
            "Softmax is commonly used for multiclass output.\n"
            "\n"
            "For logits:\n"
            "\n"
            "```text\n"
            "z₁, z₂, ..., zₙ\n"
            "```\n"
            "\n"
            "softmax converts them into values that satisfy:\n"
            "\n"
            "```text\n"
            "0 ≤ pᵢ ≤ 1\n"
            "\n"
            "Σpᵢ = 1\n"
            "```\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "softmax(zᵢ)\n"
            "=\n"
            "e^(zᵢ)\n"
            "/\n"
            "Σ e^(zⱼ)\n"
            "```\n"
            "\n"
            "This creates a probability distribution over mutually exclusive classes.\n"
            "\n"
            "Example:\n"
            "\n"
            "```text\n"
            "Airplane → 0.05\n"
            "Cat      → 0.75\n"
            "Dog      → 0.10\n"
            "Ship     → 0.10\n"
            "```\n"
            "\n"
            "Prediction:\n"
            "\n"
            "```text\n"
            "Cat\n"
            "```\n"
            "\n"
            "because it has the largest probability.\n"
            "\n"
