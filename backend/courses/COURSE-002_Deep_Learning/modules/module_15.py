            "## 4. Mixed Precision and Quantization\n"
            "\n"
            "Another major way to speed up deep learning is to make individual "
            "numerical operations cheaper.\n"
            "\n"
            "This leads us to numerical precision.\n"
            "\n"
            "### What is numerical precision?\n"
            "\n"
            "Computers represent numbers with a finite number of bits.\n"
            "\n"
            "Common floating-point types include:\n"
            "\n"
            "```text\n"
            "float16 → 16 bits\n"
            "float32 → 32 bits\n"
            "float64 → 64 bits\n"
            "```\n"
            "\n"
            "More bits provide finer numerical resolution but require more "
            "memory and computation.\n"
            "\n"
            "Think of numerical precision like image resolution:\n"
            "\n"
            "```text\n"
            "more bits\n"
            "→ finer detail\n"
            "→ greater cost\n"
            "\n"
            "fewer bits\n"
            "→ less detail\n"
            "→ lower cost\n"
            "```\n"
            "\n"
            "### Why low precision can be faster\n"
            "\n"
            "Modern GPUs and TPUs contain hardware optimized for lower-precision "
            "matrix operations.\n"
            "\n"
            "Benefits can include:\n"
            "\n"
            "```text\n"
            "less memory use\n"
            "higher throughput\n"
            "faster matrix multiplication\n"
            "larger possible batch sizes\n"
            "```\n"
            "\n"
            "### Float16 inference\n"
            "\n"
            "For inference, lower precision is often straightforward.\n"
            "\n"
            "The source demonstrates:\n"
            "\n"
            "```python\n"
            "keras.config.set_dtype_policy(\"float16\")\n"
            "```\n"
            "\n"
            "This should be configured before creating the model.\n"
            "\n"
            "The chapter notes that suitable GPU or TPU hardware may approach "
            "roughly a 2× inference speedup.\n"
            "\n"
            "### bfloat16\n"
            "\n"
            "`bfloat16` also uses 16 bits but distributes those bits differently.\n"
            "\n"
            "Compared with float16:\n"
            "\n"
            "```text\n"
            "float16\n"
            "→ more mantissa precision\n"
            "→ smaller exponent range\n"
            "\n"
            "bfloat16\n"
            "→ less mantissa precision\n"
            "→ larger exponent range\n"
            "```\n"
            "\n"
            "Some hardware is better optimized for bfloat16.\n"
            "\n"
            "### Why not train everything directly in float16?\n"
            "\n"
            "Training introduces a problem that inference does not have:\n"
            "\n"
            "```text\n"
            "gradients can become extremely small\n"
            "```\n"
            "\n"
            "For example:\n"
            "\n"
            "```text\n"
            "1e-5\n"
            "1e-6\n"
            "```\n"
            "\n"
            "Low precision may not represent these updates accurately enough.\n"
            "\n"
            "A tiny gradient may even round to zero.\n"
            "\n"
            "Then learning stops for that parameter.\n"
            "\n"
            "### Mixed-precision training\n"
            "\n"
            "The solution is to use different precisions for different parts "
            "of training.\n"
            "\n"
            "The basic idea is:\n"
            "\n"
            "```text\n"
            "forward computation\n"
            "→ mostly float16\n"
            "\n"
            "model variables\n"
            "→ float32\n"
            "\n"
            "sensitive updates\n"
            "→ float32\n"
            "```\n"
            "\n"
            "In Keras:\n"
            "\n"
            "```python\n"
            "keras.config.set_dtype_policy(\"mixed_float16\")\n"
            "```\n"
            "\n"
            "This aims to keep much of the speed advantage of half-precision "
            "computation while preserving stable optimization.\n"
            "\n"
            "### Compute dtype versus variable dtype\n"
            "\n"
            "A Keras layer can conceptually have:\n"
            "\n"
            "```text\n"
            "compute_dtype\n"
            "→ precision used for operations\n"
            "\n"
            "variable_dtype\n"
            "→ precision used to store weights\n"
            "```\n"
            "\n"
            "Under mixed precision:\n"
            "\n"
            "```text\n"
            "compute_dtype  ≈ float16\n"
            "variable_dtype = float32\n"
            "```\n"
            "\n"
            "This lets the model use fast low-precision matrix operations while "
            "keeping parameter updates accurate.\n"
            "\n"
            "### Some operations need float32\n"
            "\n"
            "Certain operations can be numerically unstable in float16.\n"
            "\n"
            "The source specifically mentions operations such as:\n"
            "\n"
            "```text\n"
            "softmax\n"
            "crossentropy\n"
            "```\n"
            "\n"
            "A layer can opt out of mixed precision:\n"
            "\n"
            "```python\n"
            "layers.Dense(..., dtype=\"float32\")\n"
            "```\n"
            "\n"
            "### Gradient underflow\n"
            "\n"
            "Imagine a gradient:\n"
            "\n"
            "```text\n"
            "0.000001\n"
            "```\n"
            "\n"
            "If float16 cannot represent it accurately, it could effectively "
            "become:\n"
            "\n"
            "```text\n"
            "0\n"
            "```\n"
            "\n"
            "This is called **underflow**.\n"
            "\n"
            "### Loss scaling\n"
            "\n"
            "Gradients are proportional to the loss.\n"
            "\n"
            "If we temporarily make the loss larger, gradients become larger too.\n"
            "\n"
            "Suppose:\n"
            "\n"
            "```text\n"
            "original gradient = 0.000001\n"
            "```\n"
            "\n"
            "If loss is scaled by 1,000:\n"
            "\n"
            "```text\n"
            "scaled gradient ≈ 0.001\n"
            "```\n"
            "\n"
            "This larger number is easier to represent in float16.\n"
            "\n"
            "Afterward the scaling can be accounted for correctly during the "
            "optimizer update.\n"
            "\n"
            "The source demonstrates automatic loss scaling:\n"
            "\n"
            "```python\n"
            "optimizer = keras.optimizers.LossScaleOptimizer(\n"
            "    keras.optimizers.Adam(learning_rate=1e-3)\n"
            ")\n"
            "```\n"
            "\n"
            "Automatic scaling is useful because an appropriate scale can change "
            "during training.\n"
            "\n"
            "### What about float8?\n"
            "\n"
            "Going from float32 to float16 often works with relatively little "
            "special handling.\n"
            "\n"
            "Going to float8 is much harder because considerably more numerical "
            "information is lost.\n"
            "\n"
            "The source explains that special rescaling logic is required and "
            "that the overhead is generally worthwhile only for very large models "
            "and suitable modern hardware.\n"
            "\n"
            "So:\n"
            "\n"
            "```text\n"
            "float16 mixed precision\n"
            "→ broadly practical\n"
            "\n"
            "float8 training\n"
            "→ specialized large-scale optimization\n"
            "```\n"
            "\n"
            "### Quantization\n"
            "\n"
            "Mixed precision focuses mainly on computation during training and "
            "inference.\n"
            "\n"
            "**Quantization** takes an already trained model and represents "
            "certain values using a smaller numerical format.\n"
            "\n"
            "A common example is:\n"
            "\n"
            "```text\n"
            "float32 weights\n"
            "→ int8 weights\n"
            "```\n"
            "\n"
            "### Why int8?\n"
            "\n"
            "`int8` uses only eight bits.\n"
            "\n"
            "Its signed range is approximately:\n"
            "\n"
            "```text\n"
            "-127 to 127\n"
            "```\n"
            "\n"
            "Using int8 can provide:\n"
            "\n"
            "```text\n"
            "smaller model size\n"
            "less memory bandwidth\n"
            "faster supported matrix operations\n"
            "faster inference\n"
            "```\n"
            "\n"
            "### Why not simply cast floats to integers?\n"
            "\n"
            "Suppose:\n"
            "\n"
            "```text\n"
            "0.1\n"
            "0.9\n"
            "-0.8\n"
            "```\n"
            "\n"
            "A naive integer conversion could destroy most information:\n"
            "\n"
            "```text\n"
            "0.1 → 0\n"
            "0.9 → 0\n"
            "-0.8 → 0\n"
            "```\n"
            "\n"
            "Instead, values are **scaled** to use the available int8 range.\n"
            "\n"
            "### Abs-max scaling intuition\n"
            "\n"
            "Suppose the largest absolute value in a tensor is:\n"
            "\n"
            "```text\n"
            "1.2\n"
            "```\n"
            "\n"
            "We want that value to map near:\n"
            "\n"
            "```text\n"
            "127\n"
            "```\n"
            "\n"
            "So:\n"
            "\n"
            "```text\n"
            "scale ≈ 127 / 1.2\n"
            "```\n"
            "\n"
            "Then:\n"
            "\n"
            "```text\n"
            "floating values\n"
            "   ↓ scale\n"
            "larger numerical values\n"
            "   ↓ round\n"
            "integers\n"
            "   ↓ cast\n"
            "int8\n"
            "```\n"
            "\n"
            "After int8 matrix multiplication, the result is converted back and "
            "unscaled.\n"
            "\n"
            "The result is not perfectly identical to float32 because rounding "
            "loses some information, but it can remain very close.\n"
            "\n"
            "### Keras quantization\n"
            "\n"
            "The source demonstrates the high-level workflow:\n"
            "\n"
            "```python\n"
            "model = ...\n"
            "model.quantize(\"int8\")\n"
            "predictions = model.predict(...)\n"
            "```\n"
            "\n"
            "Supported layers can then use int8 computation during inference.\n"
            "\n"
            "### Mixed precision versus quantization\n"
            "\n"
            "Keep these concepts separate:\n"
            "\n"
            "| Technique | Main goal | Typical use |\n"
            "|---|---|---|\n"
            "| float16 inference | Faster forward pass | Inference |\n"
            "| mixed precision | Fast compute + stable weight updates | Training |\n"
            "| loss scaling | Prevent tiny low-precision gradients from disappearing | Mixed-precision training |\n"
            "| int8 quantization | Smaller/faster numerical representation | Inference |\n"
            "\n"
            "### The real-world optimization stack\n"
            "\n"
            "You can now see several independent ways to improve a system:\n"
            "\n"
            "```text\n"
            "BETTER MODEL QUALITY\n"
            "→ hyperparameter tuning\n"
            "→ model ensembling\n"
            "\n"
            "FASTER TRAINING\n"
            "→ multi-GPU\n"
            "→ TPU\n"
            "→ data parallelism\n"
            "→ model parallelism\n"
            "→ mixed precision\n"
            "\n"
            "FASTER / SMALLER INFERENCE\n"
            "→ float16\n"
            "→ int8 quantization\n"
            "```\n"
