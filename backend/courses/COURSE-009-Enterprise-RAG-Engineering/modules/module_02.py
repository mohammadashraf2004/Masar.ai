                       '\n'
                       'The key mistake is to reason like this:\n'
                       '\n'
                       '> “My model supports a huge context window, therefore I do not need '
                       'retrieval or chunking.”\n'
                       '\n'
                       'A context window is a limit for one request, not a scalable storage '
                       'system. Even if many documents technically fit, sending everything has '
                       'other costs:\n'
                       '\n'
                       '- more input tokens,\n'
                       '- longer time to first token,\n'
                       '- more irrelevant evidence competing for attention,\n'
                       '- greater monetary or hardware cost,\n'
                       '- lower practical retrieval quality inside very long contexts.\n'
                       '\n'
                       'Chunking therefore remains useful even when models support long inputs. '
                       'RAG is not only a workaround for small context windows; it is also a '
                       'strategy for **selecting the right evidence**.\n'
