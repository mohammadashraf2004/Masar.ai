            "## 4. Scatter plots and line plots\n"
            "\n"
            "These two plots can contain similar x/y values but answer different questions.\n"
            "\n"
            "---\n"
            "\n"
            "### 4.1 Scatter plot\n"
            "\n"
            "A scatter plot displays individual points without connecting them.\n"
            "\n"
            "Use it when the main question is:\n"
            "\n"
            "> How are two numeric variables related?\n"
            "\n"
            "Example:\n"
            "\n"
            "```python\n"
            "x = [1, 3, 5, 7, 9, 11]\n"
            "y = [10, 25, 35, 33, 41, 59]\n"
            "\n"
            "plt.scatter(\n"
            "    x,\n"
            "    y,\n"
            "    c='red',\n"
            "    marker='o',\n"
            "    s=80,\n"
            "    alpha=0.7,\n"
            "    label='Data Points'\n"
            ")\n"
            "```\n"
            "\n"
            "The chapter customizes:\n"
            "\n"
            "```text\n"
            "c      → color\n"
            "marker → marker shape\n"
            "s      → marker size\n"
            "alpha  → transparency\n"
            "label  → legend label\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 4.2 Annotation\n"
            "\n"
            "The source labels each point:\n"
            "\n"
            "```python\n"
            "for i in range(len(x)):\n"
            "    plt.annotate(\n"
            "        f\"({x[i]}, {y[i]})\",\n"
            "        (x[i], y[i]),\n"
            "        textcoords=\"offset points\",\n"
            "        xytext=(5, 5)\n"
            "    )\n"
            "```\n"
            "\n"
            "Annotations make exact observations identifiable.\n"
            "\n"
            "This can be useful when the dataset is small and individual points matter.\n"
            "\n"
            "---\n"
            "\n"
