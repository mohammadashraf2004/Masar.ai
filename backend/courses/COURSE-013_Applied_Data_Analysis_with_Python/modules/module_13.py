            "\n"
            "To recover the masked term, the model must learn patterns involving:\n"
            "\n"
            "- grammar,\n"
            "- semantics,\n"
            "- local context,\n"
            "- longer-range relationships.\n"
            "\n"
            "The chapter associates MLM with models such as:\n"
            "\n"
            "- BERT,\n"
            "- DistilBERT.\n"
            "\n"
            "The learned representations can then support downstream tasks such as:\n"
            "\n"
            "- sentiment classification,\n"
            "- question answering,\n"
            "- other language-understanding tasks.\n"
            "\n"
