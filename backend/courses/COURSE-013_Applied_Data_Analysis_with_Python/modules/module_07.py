            "\n"
            "---\n"
            "\n"
            "### 4.1 MCAR — Missing Completely at Random\n"
            "\n"
            "MCAR means the missingness is unrelated to:\n"
            "\n"
            "- observed data,\n"
            "- unobserved data.\n"
            "\n"
            "Source example:\n"
            "\n"
            "```text\n"
            "temperature-recording failure\n"
            "caused by random technical glitch\n"
            "```\n"
            "\n"
            "The missingness is purely random.\n"
            "\n"
            "The chapter says MCAR may reduce statistical power because data is lost, but it introduces less systematic bias than other missingness mechanisms.\n"
            "\n"
            "---\n"
            "\n"
            "### 4.2 MAR — Missing at Random\n"
            "\n"
            "MAR means missingness is related to observed data but not to the missing value itself.\n"
            "\n"
            "Source example:\n"
            "\n"
            "```text\n"
            "older respondents\n"
            "→ more likely to skip salary question\n"
            "```\n"
            "\n"
            "Here:\n"
            "\n"
            "```text\n"
            "Age is observed.\n"
            "Salary is missing.\n"
            "Missingness is associated with Age.\n"
            "```\n"
            "\n"
            "The chapter emphasizes that MAR is assumption-driven.\n"
            "\n"
            "You need domain knowledge before claiming that missingness is MAR.\n"
            "\n"
            "---\n"
            "\n"
            "### 4.3 MNAR — Missing Not at Random\n"
            "\n"
            "MNAR means missingness is related to:\n"
            "\n"
            "- the missing value itself,\n"
            "- or unrecorded factors.\n"
            "\n"
            "Source example:\n"
            "\n"
            "```text\n"
            "household has very large debt\n"
            "→ household avoids reporting debt\n"
            "```\n"
            "\n"
            "The probability of missingness depends on the unreported debt itself.\n"
            "\n"
            "This can create serious bias because the missing mechanism is tied to the hidden value.\n"
            "\n"
            "---\n"
            "\n"
