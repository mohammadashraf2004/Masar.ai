            "## 2. Training an Image Classifier with a Small Dataset\n"
            "\n"
            "A common real-world problem is having only a few thousand labeled "
            "images rather than millions.\n"
            "\n"
            "The chapter uses dogs-versus-cats classification to demonstrate "
            "the problem.\n"
            "\n"
            "The smaller working dataset contains:\n"
            "\n"
            "```text\n"
            "Training   → 2,000 images\n"
            "Validation → 1,000 images\n"
            "Test       → 2,000 images\n"
            "```\n"
            "\n"
            "Both classes are evenly represented.\n"
            "\n"
            "### Building a ConvNet from scratch\n"
            "\n"
            "A basic model uses alternating convolution and pooling stages:\n"
            "\n"
            "```python\n"
            "inputs = keras.Input(shape=(180, 180, 3))\n"
            "\n"
            "x = layers.Rescaling(1.0 / 255)(inputs)\n"
            "\n"
            "x = layers.Conv2D(32, 3, activation=\"relu\")(x)\n"
            "x = layers.MaxPooling2D(2)(x)\n"
            "\n"
            "x = layers.Conv2D(64, 3, activation=\"relu\")(x)\n"
            "x = layers.MaxPooling2D(2)(x)\n"
            "\n"
            "x = layers.Conv2D(128, 3, activation=\"relu\")(x)\n"
            "x = layers.MaxPooling2D(2)(x)\n"
            "\n"
            "x = layers.Conv2D(256, 3, activation=\"relu\")(x)\n"
            "x = layers.MaxPooling2D(2)(x)\n"
            "\n"
            "x = layers.Conv2D(512, 3, activation=\"relu\")(x)\n"
            "x = layers.GlobalAveragePooling2D()(x)\n"
            "\n"
            "outputs = layers.Dense(1, activation=\"sigmoid\")(x)\n"
            "\n"
            "model = keras.Model(inputs, outputs)\n"
            "```\n"
            "\n"
            "Notice the architecture pattern:\n"
            "\n"
            "```text\n"
            "feature-map width / height ↓\n"
            "number of channels         ↑\n"
            "```\n"
            "\n"
            "Because this is binary classification, the final layer is:\n"
            "\n"
            "```python\n"
            "Dense(1, activation=\"sigmoid\")\n"
            "```\n"
            "\n"
            "and the loss is:\n"
            "\n"
            "```text\n"
            "binary_crossentropy\n"
            "```\n"
            "\n"
            "### Image preprocessing pipeline\n"
            "\n"
            "Images on disk begin as files such as JPEGs.\n"
            "\n"
            "Before a neural network can train on them, the pipeline needs to:\n"
            "\n"
            "```text\n"
            "read image file\n"
            "    ↓\n"
            "decode JPEG\n"
            "    ↓\n"
            "convert to pixel tensor\n"
            "    ↓\n"
            "resize to shared dimensions\n"
            "    ↓\n"
            "group into batches\n"
            "    ↓\n"
            "feed model\n"
            "```\n"
            "\n"
            "Keras can create this pipeline directly from class directories:\n"
            "\n"
            "```python\n"
            "from keras.utils import image_dataset_from_directory\n"
            "\n"
            "train_dataset = image_dataset_from_directory(\n"
            "    train_dir,\n"
            "    image_size=(180, 180),\n"
            "    batch_size=64,\n"
            ")\n"
            "```\n"
            "\n"
            "A batch might therefore have shape:\n"
            "\n"
            "```text\n"
            "images → (64, 180, 180, 3)\n"
            "labels → (64,)\n"
            "```\n"
            "\n"
            "### Saving the best model\n"
            "\n"
            "When training for many epochs, the best model is not always the "
            "model from the final epoch.\n"
            "\n"
            "A checkpoint can save the model whenever validation loss improves:\n"
            "\n"
            "```python\n"
            "keras.callbacks.ModelCheckpoint(\n"
            "    filepath=\"best_model.keras\",\n"
            "    save_best_only=True,\n"
            "    monitor=\"val_loss\",\n"
            ")\n"
            "```\n"
            "\n"
            "This becomes especially important when overfitting begins.\n"
            "\n"
            "### Small datasets and overfitting\n"
            "\n"
            "Training a large neural network on only a few thousand images "
            "creates a major risk:\n"
            "\n"
            "```text\n"
            "training accuracy → keeps increasing\n"
            "validation accuracy → stops improving\n"
            "training loss → keeps decreasing\n"
            "validation loss → begins increasing\n"
            "```\n"
            "\n"
            "The model is learning details specific to the training images "
            "instead of learning patterns that generalize.\n"
            "\n"
            "In the chapter's initial dogs-versus-cats experiment, the "
            "training accuracy approaches 100%, while validation performance "
            "levels off much earlier.\n"
            "\n"
            "This is classic overfitting.\n"
            "\n"
            "### Data augmentation\n"
            "\n"
            "One of the most important regularization techniques for image "
            "models is **data augmentation**.\n"
            "\n"
            "Instead of showing the exact same image every epoch, randomly "
            "transform it in believable ways.\n"
            "\n"
            "Examples include:\n"
            "\n"
            "```text\n"
            "horizontal flipping\n"
            "small rotations\n"
            "small zoom changes\n"
            "```\n"
            "\n"
            "For example:\n"
            "\n"
            "```python\n"
            "data_augmentation_layers = [\n"
            "    layers.RandomFlip(\"horizontal\"),\n"
            "    layers.RandomRotation(0.1),\n"
            "    layers.RandomZoom(0.2),\n"
            "]\n"
            "```\n"
            "\n"
            "The model may see different variations of the same original image:\n"
            "\n"
            "```text\n"
            "original dog\n"
            "   ↓\n"
            "slightly rotated dog\n"
            "flipped dog\n"
            "zoomed dog\n"
            "```\n"
            "\n"
            "The class does not change, but the visual presentation does.\n"
            "\n"
            "This encourages the model to focus on robust patterns rather "
            "than memorizing exact pixel arrangements.\n"
            "\n"
            "### Augmentation does not create truly new information\n"
            "\n"
            "This distinction is important.\n"
            "\n"
            "Data augmentation creates new **variations**, but all variations "
            "still come from the same limited set of original images.\n"
            "\n"
            "So augmentation reduces overfitting, but it cannot fully replace "
            "collecting genuinely new training examples.\n"
            "\n"
            "### Combining augmentation and dropout\n"
            "\n"
            "The chapter also adds dropout before the classifier:\n"
            "\n"
            "```python\n"
            "x = layers.GlobalAveragePooling2D()(x)\n"
            "x = layers.Dropout(0.25)(x)\n"
            "outputs = layers.Dense(1, activation=\"sigmoid\")(x)\n"
            "```\n"
            "\n"
            "Together:\n"
            "\n"
            "```text\n"
            "data augmentation\n"
            "+\n"
            "dropout\n"
            "      ↓\n"
            "slower overfitting\n"
            "      ↓\n"
            "better validation performance\n"
            "```\n"
            "\n"
            "Data augmentation is used during training, not when evaluating "
            "the unchanged validation or test images.\n"
            "\n"

