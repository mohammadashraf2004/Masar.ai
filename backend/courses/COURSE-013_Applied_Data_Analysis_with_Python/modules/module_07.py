            "### Key idea\n"
            "\n"
            "The chapter states there is no perfect universal missing-data treatment.\n"
            "\n"
            "Your treatment depends on:\n"
            "\n"
            "- assumptions,\n"
            "- domain knowledge,\n"
            "- analytical goal.\n"
            "\n"
