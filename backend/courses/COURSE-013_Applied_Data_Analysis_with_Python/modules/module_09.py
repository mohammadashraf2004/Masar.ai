            "---\n"
            "\n"
            "### 24.2 Information gain\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "Information Gain\n"
            "=\n"
            "Parent Entropy\n"
            "-\n"
            "Weighted Child Entropy\n"
            "```\n"
            "\n"
            "A strong split greatly reduces uncertainty.\n"
            "\n"
            "The chapter chooses the split with:\n"
            "\n"
            "```text\n"
