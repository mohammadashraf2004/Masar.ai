                       '## 33. Exact search versus approximate nearest neighbors\n'
                       '\n'
                       'The simplest way to retrieve the nearest vector is brute force:\n'
                       '\n'
                       '```text\n'
                       'for every stored vector:\n'
                       '    compute similarity(query, vector)\n'
                       'return the best k\n'
                       '```\n'
                       '\n'
                       'This is exact and has roughly `O(n)` comparison cost for `n` stored '
                       'vectors.\n'
                       '\n'
                       'For small datasets, exact search can be entirely reasonable. You might '
                       'even keep all vectors in memory.\n'
                       '\n'
                       'At millions or billions of chunks, comparing the query against every '
                       'vector becomes too expensive. **Approximate nearest neighbor (ANN)** '
                       'algorithms trade a small amount of exactness for dramatically faster '
                       'search.\n'
                       '\n'
                       'This is a core production trade-off:\n'
                       '\n'
                       '```text\n'
                       'exact nearest neighbor\n'
                       '→ maximum exactness\n'
                       '→ more work\n'
                       '\n'
                       'approximate nearest neighbor\n'
                       '→ much less work\n'
                       '→ may occasionally miss the mathematical nearest point\n'
                       '```\n'
                       '\n'
                       'The retrieval goal is usually not mathematical perfection at any cost; it '
                       'is to retrieve evidence accurately enough within latency and resource '
                       'constraints.\n'
                       '\n'
