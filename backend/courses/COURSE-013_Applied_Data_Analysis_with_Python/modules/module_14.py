            "## 43. Contrast\n"
            "\n"
            "Contrast scales distance from a pivot.\n"
            "\n"
            "Source:\n"
            "\n"
            "```python\n"
            "def adjust_contrast(\n"
            "    img,\n"
            "    alpha=1.30,\n"
            "    pivot=0.5\n"
            "):\n"
            "    out = (\n"
            "        (img - pivot)\n"
            "        * alpha\n"
            "        + pivot\n"
            "    )\n"
            "\n"
            "    return np.clip(\n"
            "        out,\n"
            "        0.0,\n"
            "        1.0\n"
            "    )\n"
            "```\n"
            "\n"
            "Pixels:\n"
            "\n"
            "```text\n"
            "below pivot\n"
            "→ pushed darker\n"
            "\n"
            "above pivot\n"
            "→ pushed brighter\n"
            "```\n"
            "\n"
            "with the pivot staying fixed before clipping.\n"
            "\n"
