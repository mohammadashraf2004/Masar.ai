                       '## 37. Choosing k and embedding dimensions\n'
                       '\n'
                       'Two apparently simple parameters can strongly affect system behavior.\n'
                       '\n'
                       '### Number of retrieved results: `k`\n'
                       '\n'
                       'If `k` is too small, the chunk containing the answer may be ranked just '
                       'outside the returned set.\n'
                       '\n'
                       'If `k` is too large:\n'
                       '\n'
                       '- irrelevant chunks enter the prompt,\n'
                       '- redundant evidence consumes tokens,\n'
                       '- latency and generation cost increase,\n'
                       '- the prompt may approach the context limit,\n'
                       '- useful evidence may be diluted.\n'
                       '\n'
                       '### Embedding dimensionality\n'
                       '\n'
                       'Reducing dimensions can lower index size and speed retrieval. Reducing '
                       'them too aggressively can discard semantic information.\n'
                       '\n'
                       'Neither parameter has a universally correct value. Tune them against a '
                       'representative evaluation set and observe both retrieval metrics and '
                       'downstream answer quality.\n'
                       '\n'
                       'A useful principle is:\n'
                       '\n'
                       '> **Increase retrieval breadth only when the additional candidates improve '
                       'the chance of useful evidence enough to justify the extra noise and '
                       'cost.**\n'
                       '\n'
                       '---\n'
                       '\n'
                       '## 38. pgvector: storing embeddings in PostgreSQL\n'
                       '\n'
                       'The chapter demonstrates how PostgreSQL can store and index embeddings '
                       'through the `pgvector` extension.\n'
                       '\n'
                       'First, enable the extension and create a vector column whose '
                       'dimensionality matches the embedding model:\n'
                       '\n'
                       '```sql\n'
                       'CREATE EXTENSION IF NOT EXISTS vector;\n'
                       '\n'
                       'CREATE TABLE sentence_embeddings (\n'
                       '    sentence TEXT,\n'
                       '    embedding VECTOR(384)\n'
                       ');\n'
                       '```\n'
                       '\n'
                       'Then create an HNSW index:\n'
                       '\n'
                       '```sql\n'
                       'CREATE INDEX\n'
                       'ON sentence_embeddings\n'
                       'USING hnsw (embedding vector_l2_ops)\n'
                       'WITH (m = 16, ef_construction = 64);\n'
                       '```\n'
                       '\n'
                       'The important relationship is:\n'
                       '\n'
                       '```text\n'
                       'embedding model output dimension\n'
                       '=\n'
                       'database vector-column dimension\n'
                       '```\n'
                       '\n'
                       'If your model emits 384 values, the storage schema must be compatible with '
                       '384-dimensional vectors.\n'
                       '\n'
                       'This example also demonstrates a broader architectural option: a RAG '
                       'application does not always require a separate specialized vector '
                       'database. Existing database infrastructure may provide adequate vector '
                       'capabilities, depending on scale and requirements.\n'
                       '\n'
                       '---\n'
                       '\n'
                       '## 39. pgvector: embedding and searching a query\n'
                       '\n'
                       'At query time, the text query is embedded using the same embedding model '
                       'used for stored sentences. The resulting vector is passed to PostgreSQL.\n'
                       '\n'
                       "An adapted form of the chapter's search is:\n"
                       '\n'
                       '```python\n'
                       'def vector_search(query, model, top_k):\n'
                       '    query_embedding = model.encode([query])[0].tolist()\n'
                       '\n'
                       '    cursor.execute(\n'
                       "        '''\n"
                       '        SELECT sentence,\n'
                       '               1 - (embedding <=> %s::vector) AS similarity\n'
                       '        FROM sentence_embeddings\n'
                       '        WHERE embedding IS NOT NULL\n'
                       '        ORDER BY embedding <=> %s::vector\n'
                       '        LIMIT %s\n'
                       "        ''',\n"
                       '        (query_embedding, query_embedding, top_k),\n'
                       '    )\n'
                       '\n'
                       '    return cursor.fetchall()\n'
                       '```\n'
                       '\n'
                       'In pgvector, `<=>` gives cosine distance. The query orders by increasing '
                       'distance to place nearer vectors first. `1 - distance` is used to display '
                       'a similarity-style value.\n'
                       '\n'
                       "With the chapter's sample sentences, a query such as “I am a smiling "
                       'person” ranks the happy/joyful sentences above pessimistic ones. A '
                       'future-oriented negative query ranks pessimistic content higher.\n'
                       '\n'
                       'The example closes the loop from **text → vector → database search → '
                       'semantically related text**.\n'
                       '\n'
                       '{{exercise:M01.L02.EX15}}\n'
                       '\n'
