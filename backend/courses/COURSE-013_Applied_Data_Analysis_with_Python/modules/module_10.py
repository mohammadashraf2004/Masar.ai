            "---\n"
            "\n"
            "## 41. Mass–Volume (MV) curve\n"
            "\n"
            "The source defines:\n"
            "\n"
            "### Mass\n"
            "\n"
            "Fraction of observations exceeding an anomaly-score threshold.\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "mass\n"
            "=\n"
            "high-score-point fraction\n"
            "```\n"
            "\n"
            "### Volume\n"
            "\n"
            "A measure of how much feature-space region is occupied by selected high-score observations.\n"
            "\n"
            "The source's conceptual goal is:\n"
            "\n"
            "```text\n"
            "high mass\n"
            "inside\n"
            "small volume\n"
            "```\n"
            "\n"
            "Meaning many strongly scored anomalies are concentrated in a compact region.\n"
            "\n"
            "---\n"
            "\n"
            "### 41.1 Desired curve\n"
            "\n"
            "The chapter says a stronger detector should rise sharply at low volume.\n"
            "\n"
            "Its demonstrated curve rises gradually.\n"
            "\n"
            "The source interprets that as:\n"
            "\n"
            "```text\n"
            "weak separation\n"
            "of anomalous high-score regions\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "## 42. Excess-Mass (EM) curve\n"
            "\n"
            "EM extends mass/volume reasoning with a penalty:\n"
            "\n"
            "```text\n"
            "lambda\n"
            "```\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "EM\n"
            "=\n"
            "mass\n"
            "-\n"
            "lambda × volume\n"
            "```\n"
            "\n"
            "The penalty discourages using very large regions simply to capture more points.\n"
            "\n"
            "The source interpretation:\n"
            "\n"
            "```text\n"
            "higher EM\n"
            "→ stronger compact anomaly region\n"
            "\n"
            "steep early decline\n"
            "→ weak anomaly separation\n"
            "```\n"
            "\n"
            "Its example declines approximately linearly and is interpreted as weak anomaly-detection power.\n"
