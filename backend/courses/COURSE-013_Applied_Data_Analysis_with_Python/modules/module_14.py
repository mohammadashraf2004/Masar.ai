            "\n"
            "An edge is a location where pixel intensity changes quickly over a small region.\n"
            "\n"
            "Edges often correspond to:\n"
            "\n"
            "- object boundaries,\n"
            "- lines,\n"
            "- internal markings.\n"
            "\n"
            "They are useful for:\n"
            "\n"
