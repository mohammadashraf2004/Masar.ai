            "## 44. Exposure\n"
            "\n"
            "Exposure in the source multiplies values by a gain:\n"
            "\n"
            "```python\n"
            "def adjust_exposure(\n"
            "    img,\n"
            "    factor=1.30\n"
            "):\n"
            "    return np.clip(\n"
            "        img * factor,\n"
            "        0.0,\n"
            "        1.0\n"
            "    )\n"
            "```\n"
            "\n"
            "Factor:\n"
            "\n"
            "```text\n"
            "> 1\n"
            "→ brighten\n"
            "\n"
            "< 1\n"
            "→ darken\n"
            "```\n"
            "\n"
            "Unlike additive brightness adjustment, multiplication affects larger pixel values more strongly.\n"
            "\n"
