            "\n"
            "A model predicting:\n"
            "\n"
            "```text\n"
            "Not Churn\n"
            "for everyone\n"
            "```\n"
            "\n"
            "would achieve:\n"
            "\n"
            "```text\n"
            "99% accuracy\n"
            "```\n"
            "\n"
            "while detecting:\n"
            "\n"
            "```text\n"
            "0% of churners\n"
            "```\n"
            "\n"
            "So high accuracy can hide failure on the minority class.\n"
            "\n"
            "---\n"
            "\n"
            "## 35. Precision\n"
            "\n"
            "Precision asks:\n"
            "\n"
            "> Of all observations predicted positive, how many were actually positive?\n"
            "\n"
            "```text\n"
            "Precision\n"
            "=\n"
            "TP\n"
            "/\n"
            "(TP + FP)\n"
            "```\n"
            "\n"
            "Source example:\n"
            "\n"
            "```text\n"
            "Precision = 1.0\n"
            "```\n"
            "\n"
            "Business meaning:\n"
            "\n"
            "> Every predicted churn case in that example was actually churn.\n"
            "\n"
            "Precision is useful when false positives are costly.\n"
            "\n"
            "Example:\n"
            "\n"
            "```text\n"
            "retention offer costs money\n"
            "→ avoid targeting loyal customers unnecessarily\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "## 36. Recall\n"
            "\n"
            "Recall asks:\n"
            "\n"
            "> Of all actual positive cases, how many did the model find?\n"
            "\n"
            "```text\n"
            "Recall\n"
            "=\n"
            "TP\n"
            "/\n"
            "(TP + FN)\n"
            "```\n"
            "\n"
            "Source example:\n"
            "\n"
            "```text\n"
            "Recall = 0.9\n"
            "```\n"
            "\n"
            "Meaning:\n"
            "\n"
            "> The model found 90% of the actual churners in that example.\n"
            "\n"
            "Recall matters when false negatives are costly.\n"
            "\n"
            "Example:\n"
            "\n"
            "```text\n"
            "missed churner\n"
            "→ customer leaves with no intervention\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "## 37. Precision-recall trade-off\n"
            "\n"
            "The chapter explains that business goals determine the preferred balance.\n"
            "\n"
            "### Favor recall\n"
            "\n"
            "Goal:\n"
            "\n"
            "```text\n"
            "catch nearly every churner\n"
            "```\n"
            "\n"
            "Trade-off:\n"
            "\n"
            "```text\n"
            "more false positives\n"
            "more retention spending\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### Favor precision\n"
            "\n"
            "Goal:\n"
            "\n"
            "```text\n"
            "only act on highly likely churners\n"
            "```\n"
            "\n"
            "Trade-off:\n"
            "\n"
            "```text\n"
            "some real churners may be missed\n"
            "```\n"
            "\n"
            "This means there is no universally best threshold.\n"
            "\n"
            "The decision depends on the relative cost of:\n"
            "\n"
            "```text\n"
            "FP\n"
            "versus\n"
            "FN\n"
            "```\n"
