            "## 5. Assignment, views, and copies\n"
            "\n"
            "This is one of the most important sections in the chapter because it affects whether modifying one array changes another.\n"
            "\n"
            "There are three different situations:\n"
            "\n"
            "1. assignment,\n"
            "2. view,\n"
            "3. copy.\n"
            "\n"
            "Start with:\n"
            "\n"
            "```python\n"
            "arr = np.arange(1, 5).reshape(2, 2)\n"
            "```\n"
            "\n"
            "Output:\n"
            "\n"
            "```text\n"
            "[[1 2]\n"
            " [3 4]]\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 5.1 Assignment\n"
            "\n"
            "```python\n"
            "arr_no_copy = arr\n"
            "```\n"
            "\n"
            "This does not create an independent array.\n"
            "\n"
            "Both names point to the same array object.\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "arr -----------┐\n"
            "               ├── same array object\n"
            "arr_no_copy ---┘\n"
            "```\n"
            "\n"
            "If the data changes through one name, the other sees the same object.\n"
            "\n"
            "---\n"
            "\n"
            "### 5.2 Copy\n"
            "\n"
            "```python\n"
            "arr_copy = arr.copy()\n"
            "```\n"
            "\n"
            "A copy owns its own data.\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "arr       → original data\n"
            "arr_copy  → independent duplicate\n"
            "```\n"
            "\n"
            "Changing the original does not automatically modify the copy.\n"
            "\n"
            "---\n"
            "\n"
            "### 5.3 View\n"
            "\n"
            "```python\n"
            "arr_view = arr.view()\n"
            "```\n"
            "\n"
            "A view is a separate array object that shares underlying data with the original.\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "arr object -----------\\\n"
            "                       > shared memory\n"
            "arr_view object ------/\n"
            "```\n"
            "\n"
            "The Python object identities can differ while the underlying data remains shared.\n"
            "\n"
            "---\n"
            "\n"
            "### 5.4 Observing the difference\n"
            "\n"
            "Suppose:\n"
            "\n"
            "```python\n"
            "arr[1] = [99, 89]\n"
            "```\n"
            "\n"
            "The original becomes:\n"
            "\n"
            "```text\n"
            "[[ 1  2]\n"
            " [99 89]]\n"
            "```\n"
            "\n"
            "The view reflects the modification:\n"
            "\n"
            "```text\n"
            "[[ 1  2]\n"
            " [99 89]]\n"
            "```\n"
            "\n"
            "The independent copy remains:\n"
            "\n"
            "```text\n"
            "[[1 2]\n"
            " [3 4]]\n"
            "```\n"
            "\n"
            "This is why views can be fast and memory efficient, but they require care.\n"
            "\n"
            "### Retain this distinction\n"
            "\n"
            "```text\n"
            "assignment → same object\n"
            "view       → different array object, shared data\n"
            "copy       → different object, independent data\n"
            "```\n"
            "\n"
            "[[IMAGE_NEEDED: NumPy assignment view copy memory model | Three small diagrams: assignment with two names pointing to one object, view with two objects sharing one data buffer, copy with separate buffers | Learner should notice why changing a view can affect the original but changing a copy does not]]\n"
            "\n"
            "---\n"
            "\n"
            "## 6. Slicing, Boolean indexing, and fancy indexing\n"
            "\n"
            "Indexing answers:\n"
            "\n"
            "> Which element do I want?\n"
            "\n"
            "Slicing answers:\n"
            "\n"
            "> Which range of elements do I want?\n"
            "\n"
            "Boolean indexing answers:\n"
            "\n"
            "> Which elements satisfy a condition?\n"
            "\n"
            "Fancy indexing answers:\n"
            "\n"
            "> Which elements or rows are identified by an explicit list/array of indices?\n"
            "\n"
            "---\n"
            "\n"
            "### 6.1 Basic slicing\n"
            "\n"
            "Create:\n"
            "\n"
            "```python\n"
            "arr = np.arange(0, 10)\n"
