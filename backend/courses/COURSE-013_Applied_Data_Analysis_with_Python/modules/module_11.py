            "## 7. Random Forest\n"
            "\n"
            "Random Forest is the chapter's main bagging algorithm.\n"
            "\n"
            "It combines:\n"
            "\n"
            "```text\n"
            "bootstrap sampling\n"
            "+\n"
            "random feature subsets\n"
            "+\n"
            "many decision trees\n"
            "+\n"
            "prediction aggregation\n"
            "```\n"
            "\n"
            "The important new ingredient beyond ordinary bagging is:\n"
            "\n"
            "```text\n"
            "feature subspacing\n"
            "```\n"
            "\n"
            "At each tree split, only a random subset of features is considered.\n"
            "\n"
            "---\n"
            "\n"
            "### 7.1 Why random feature subsets matter\n"
            "\n"
            "Suppose one predictor is extremely strong.\n"
            "\n"
            "Without feature subsetting:\n"
            "\n"
            "```text\n"
            "many trees\n"
            "→ repeatedly choose same predictor\n"
            "→ trees become more similar\n"
            "```\n"
            "\n"
            "If trees make very similar decisions:\n"
            "\n"
            "```text\n"
            "ensemble diversity ↓\n"
            "```\n"
            "\n"
            "Random feature selection forces trees to explore alternative splits.\n"
            "\n"
            "This decorrelates the trees and strengthens variance reduction.\n"
            "\n"
            "---\n"
            "\n"
            "## 8. How Random Forest works\n"
            "\n"
            "### Step 1 — Set forest/tree parameters\n"
            "\n"
            "Examples in the source include:\n"
            "\n"
            "- number of trees,\n"
            "- maximum depth,\n"
            "- minimum samples,\n"
            "- split criterion,\n"
            "- number of candidate features per split.\n"
            "\n"
            "---\n"
            "\n"
            "### Step 2 — Bootstrap data\n"
            "\n"
            "For each tree:\n"
            "\n"
            "```text\n"
            "sample rows with replacement\n"
            "```\n"
            "\n"
            "Some observations are repeated.\n"
            "\n"
            "Some are omitted.\n"
            "\n"
            "---\n"
            "\n"
            "### Step 3 — Grow each tree\n"
            "\n"
            "At every node:\n"
            "\n"
            "```text\n"
            "select random subset of features\n"
            "        ↓\n"
            "evaluate candidate splits\n"
            "        ↓\n"
            "choose best split\n"
            "```\n"
            "\n"
            "Continue until a stopping condition is met.\n"
            "\n"
            "---\n"
            "\n"
            "### Step 4 — Predict with each tree\n"
            "\n"
            "Classification:\n"
            "\n"
            "```text\n"
            "class / probability\n"
            "```\n"
            "\n"
            "Regression:\n"
            "\n"
            "```text\n"
            "numeric estimate\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### Step 5 — Aggregate forest output\n"
            "\n"
            "Classification:\n"
            "\n"
            "```text\n"
            "vote / average probabilities\n"
            "```\n"
            "\n"
            "Regression:\n"
            "\n"
            "```text\n"
            "average predictions\n"
            "```\n"
            "\n"
            "[[IMAGE_NEEDED: Random Forest workflow | Bootstrap samples feeding multiple trees; each tree shows random feature subset at splits; outputs aggregate into final class/probability | Learner should understand both row and feature randomness]]\n"
            "\n"
            "---\n"
            "\n"
            "## 9. Out-of-bag observations\n"
            "\n"
            "Because bootstrap samples omit some original rows, each tree has observations it did not train on.\n"
            "\n"
            "These are:\n"
            "\n"
            "```text\n"
            "out-of-bag\n"
            "OOB\n"
            "```\n"
            "\n"
            "The source's classifier enables:\n"
            "\n"
            "```python\n"
            "oob_score=True\n"
            "```\n"
            "\n"
            "This lets the Random Forest estimate performance using observations that were excluded from the relevant tree's bootstrap training sample.\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "for one row\n"
            "use predictions\n"
            "from trees\n"
            "that did not train on it\n"
            "```\n"
            "\n"
            "This gives a useful internal validation signal.\n"
            "\n"
            "It does not eliminate the need for careful external validation in real workflows, but it is a valuable property of bootstrap-based forests.\n"
            "\n"
            "---\n"
            "\n"
