            "### Create the test set before deep exploration\n"
            "\n"
            "This is one of the most important habits in the chapter.\n"
            "\n"
            "If you deeply inspect the full dataset before creating the test set, your own decisions may adapt to patterns that should have remained unseen.\n"
            "\n"
            "This is **data snooping bias**.\n"
            "\n"
            "A simple split is:\n"
            "\n"
            "```python\n"
            "from sklearn.model_selection import train_test_split\n"
            "\n"
            "train_set, test_set = train_test_split(\n"
            "    housing_full,\n"
            "    test_size=0.2,\n"
            "    random_state=42,\n"
            ")\n"
            "```\n"
            "\n"
            "The `random_state` makes the split reproducible.\n"
            "\n"
            "But reproducibility alone does not guarantee representativeness.\n"
            "\n"
            "### Why a stable split matters\n"
            "\n"
            "If a new random test set is created every time the program runs, then over repeated experimentation you may effectively expose yourself to most of the dataset.\n"
            "\n"
            "For datasets that evolve over time, a stable immutable identifier can be hashed to decide whether an instance belongs in the test set.\n"
            "\n"
            "The core idea is:\n"
            "\n"
            "```text\n"
            "same instance ID\n"
            "    ->\n"
            "same deterministic split decision\n"
