                       '\n'
                       '## 41. Semantic search, keyword search, hybrid search, and reranking\n'
                       '\n'
                       'The base stack focuses primarily on semantic retrieval, but the chapter '
                       'positions it relative to other methods.\n'
                       '\n'
                       '### Semantic / dense search\n'
                       'Embeds query and documents and matches them in vector space. Strong when '
                       'meaning is expressed with different words.\n'
                       '\n'
                       '### Keyword / sparse search\n'
                       'Matches lexical signals using methods such as TF-IDF or BM25. Strong for '
                       'exact names, rare tokens, identifiers, and other surface-form '
                       'constraints.\n'
                       '\n'
                       '### Hybrid search\n'
                       'Combines semantic and keyword signals. Chapter 3 develops this more '
                       'fully.\n'
                       '\n'
                       '### Reranking\n'
                       'A first-stage retriever may return too many redundant or imperfectly '
                       'ordered candidates. A reranker can reorder or select them before '
                       'generation.\n'
                       '\n'
                       'Maximum Marginal Relevance (MMR) is one approach that balances relevance '
                       'and diversity. Transformer rerankers go further by evaluating the query '
                       'and candidate together using cross-attention rather than embedding them '
                       'independently.\n'
                       '\n'
                       'This suggests a common retrieval pattern:\n'
                       '\n'
                       '```text\n'
                       'fast broad retrieval\n'
                       '→ candidate set\n'
                       '→ more expensive reranking\n'
                       '→ small high-quality context\n'
                       '```\n'
                       '\n'
                       '{{exercise:M01.L02.EX17}}\n'
                       '\n'
                       '---\n'
                       '\n'
                       '## 42. The generative LLM reads text, not embedding vectors\n'
                       '\n'
                       'After retrieval, the system has two things:\n'
                       '\n'
                       '1. the original user request,\n'
                       '2. the original text of the retrieved chunks.\n'
                       '\n'
                       'Those are assembled into a prompt for the generative LLM.\n'
                       '\n'
                       'A common misconception is that the LLM receives embedding vectors. It '
                       'normally does not. Embeddings are used by the retrieval layer to decide '
                       '**which text** to select. The generator receives that text.\n'
                       '\n'
                       '```text\n'
                       'query\n'
                       '→ query embedding\n'
                       '→ vector search\n'
                       '→ selected vector records\n'
                       '→ recover original chunk text\n'
                       '→ prompt\n'
                       '→ LLM\n'
                       '→ answer\n'
                       '```\n'
                       '\n'
                       'The generator then performs tasks such as question answering or '
                       'summarization over the retrieved evidence.\n'
                       '\n'
                       'This separation is useful for debugging: if retrieval selected the wrong '
                       'chunks, changing the generative model may not solve the problem.\n'
                       '\n'
                       '---\n'
                       '\n'
                       '## 43. Choosing the generative LLM: quality, latency, cost, and privacy\n'
                       '\n'
                       'The chapter describes several considerations when selecting the '
                       'generator.\n'
                       '\n'
                       '### Quality versus speed\n'
                       'Larger models often have more capacity for difficult tasks, but simple RAG '
                       'question answering may not benefit enough to justify extra cost and '
                       'latency. Evaluate on your workload rather than assuming larger is always '
                       'necessary.\n'
                       '\n'
                       '### Inference optimization\n'
                       'Techniques mentioned in the chapter include:\n'
                       '\n'
                       '- quantization to lower numerical precision,\n'
                       '- FlashAttention for more efficient attention computation,\n'
                       '- serving frameworks such as vLLM and Ollama.\n'
                       '\n'
                       '### Deployment and privacy\n'
                       'Some organizations require on-premises or air-gapped operation. In those '
                       'environments, sending private context to public model endpoints may be '
                       'prohibited. Model choice is therefore also a data-governance decision.\n'
                       '\n'
                       "The correct generator is the model that meets the application's **quality "
                       'target under its operational constraints**.\n'
                       '\n'
                       '{{exercise:M01.L02.EX18}}\n'
                       '\n'
