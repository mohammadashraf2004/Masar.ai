            "Read it as:\n"
            "\n"
            "```text\n"
            "posterior\n"
            "=\n"
            "likelihood × prior\n"
            "-----------\n"
            "evidence\n"
            "```\n"
            "\n"
            "Where:\n"
            "\n"
            "```text\n"
            "P(A)     → prior probability of A\n"
