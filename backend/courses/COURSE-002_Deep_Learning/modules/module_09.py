            '## 2. Understanding image segmentation\n'
            '\n'
            'Deep-learning segmentation assigns a category to pixels.\n'
            '\n'
            'There are three major forms.\n'
            '\n'
            '### Semantic segmentation\n'
            '\n'
            'Semantic segmentation assigns each pixel a semantic class.\n'
            '\n'
            'Example:\n'
            '\n'
            '```text\n'
            'cat pixels        -> cat\n'
            'dog pixels        -> dog\n'
            'background pixels -> background\n'
            '```\n'
            '\n'
            'If two cats appear in the image, both belong to the same class:\n'
            '\n'
            '```text\n'
            'cat\n'
            '```\n'
            '\n'
            'The model does not distinguish one cat from the other.\n'
            '\n'
            '### Instance segmentation\n'
            '\n'
            'Instance segmentation distinguishes individual objects.\n'
            '\n'
            'Two cats become:\n'
            '\n'
            '```text\n'
            'cat instance 1\n'
            'cat instance 2\n'
            '```\n'
            '\n'
            'This is important when you need to count or manipulate objects independently.\n'
            '\n'
            '### Panoptic segmentation\n'
            '\n'
            'Panoptic segmentation combines the two ideas.\n'
            '\n'
            'Each pixel receives:\n'
            '\n'
            '```text\n'
            'semantic category\n'
            '+\n'
            'instance identity\n'
            '```\n'
            '\n'
            'Conceptually:\n'
            '\n'
            '```text\n'
            'pixel -> ("cat", instance 2)\n'
            '```\n'
            '\n'
            'This gives both category and individual-object information.\n'
            '\n'
            '### Segmentation masks\n'
            '\n'
            'A segmentation dataset pairs:\n'
            '\n'
            '```text\n'
            'input image\n'
            '+\n'
            'target mask\n'
            '```\n'
            '\n'
            'The mask is usually the same height and width as the image.\n'
            '\n'
            'Instead of RGB color values, each pixel stores a class ID.\n'
            '\n'
