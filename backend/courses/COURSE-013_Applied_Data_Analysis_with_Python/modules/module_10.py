            "\n"
            "## Important misconceptions\n"
            "\n"
            "### Misconception 1\n"
            "\n"
            "> “Unsupervised learning has no learning objective.”\n"
            "\n"
            "It still has mathematical objectives such as:\n"
            "\n"
            "- maximize retained variance,\n"
            "- minimize within-cluster distance,\n"
            "- identify low-density observations.\n"
            "\n"
            "It simply does not rely on known target labels.\n"
            "\n"
            "---\n"
            "\n"
            "### Misconception 2\n"
            "\n"
            "> “PCA selects a subset of original columns.”\n"
            "\n"
            "PCA creates new linear combinations.\n"
            "\n"
            "The PCs are transformed features, not merely chosen originals.\n"
            "\n"
            "---\n"
            "\n"
            "### Misconception 3\n"
            "\n"
            "> “PC1 is the most important original feature.”\n"
            "\n"
            "PC1 is a weighted combination of original features.\n"
            "\n"
            "Loadings tell you which originals contribute strongly.\n"
            "\n"
            "---\n"
            "\n"
            "### Misconception 4\n"
            "\n"
            "> “A beautiful 2D PCA plot guarantees structure was preserved.”\n"
            "\n"
            "Reduction can distort neighborhoods or distances.\n"
            "\n"
            "That is why the chapter includes trustworthiness and Sammon stress.\n"
            "\n"
            "---\n"
            "\n"
            "### Misconception 5\n"
            "\n"
            "> “PCA should be refitted independently on every time window before comparing drift.”\n"
            "\n"
            "The practical example fits the reference transformation on Window A and applies it to B so both populations share the same coordinate system.\n"
            "\n"
            "---\n"
            "\n"
            "### Misconception 6\n"
            "\n"
            "> “K-Means automatically discovers the correct number of clusters.”\n"
            "\n"
            "You must specify K.\n"
            "\n"
            "The elbow method is one heuristic for choosing it.\n"
            "\n"
            "---\n"
            "\n"
            "### Misconception 7\n"
            "\n"
