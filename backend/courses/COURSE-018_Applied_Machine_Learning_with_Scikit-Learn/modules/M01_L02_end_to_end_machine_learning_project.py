            "\n"
            "```text\n"
            "test predictions\n"
            "      |\n"
            "resample prediction errors many times\n"
            "      |\n"
            "recompute RMSE\n"
            "      |\n"
            "estimate plausible range\n"
            "```\n"
            "\n"
