            "\n"
            "That allows the dataset to grow without constantly moving old training examples into the test set or vice versa.\n"
            "\n"
            "### Stratified sampling\n"
            "\n"
            "Purely random sampling can accidentally create a test set with distorted proportions, especially when the dataset is not extremely large.\n"
            "\n"
            "If domain knowledge says `median_income` is particularly important, the test set should represent the income distribution well.\n"
            "\n"
            "The chapter first creates income categories:\n"
            "\n"
            "```python\n"
            "import numpy as np\n"
            "import pandas as pd\n"
            "\n"
            "housing_full[\"income_cat\"] = pd.cut(\n"
            "    housing_full[\"median_income\"],\n"
            "    bins=[0.0, 1.5, 3.0, 4.5, 6.0, np.inf],\n"
            "    labels=[1, 2, 3, 4, 5],\n"
            ")\n"
            "```\n"
            "\n"
            "Then it performs a stratified split:\n"
            "\n"
            "```python\n"
            "strat_train_set, strat_test_set = train_test_split(\n"
            "    housing_full,\n"
            "    test_size=0.2,\n"
            "    stratify=housing_full[\"income_cat\"],\n"
            "    random_state=42,\n"
            ")\n"
