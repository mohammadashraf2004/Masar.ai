            "## 36. Local Outlier Factor (LOF)\n"
            "\n"
            "LOF detects anomalies through local density.\n"
            "\n"
            "Its question is:\n"
            "\n"
            "> Is this point much less dense than the neighborhood around it?\n"
            "\n"
            "The chapter presents LOF as useful for:\n"
            "\n"
            "- varying-density datasets,\n"
            "- contextual anomalies,\n"
            "- lower- to medium-dimensional spaces.\n"
            "\n"
            "It is less scalable than Isolation Forest but offers a local-density interpretation.\n"
            "\n"
            "---\n"
            "\n"
            "## 37. k-distance and reachability distance\n"
            "\n"
            "LOF begins with:\n"
            "\n"
            "```text\n"
            "k\n"
            "→ number of neighbors\n"
            "```\n"
            "\n"
            "If:\n"
            "\n"
            "```text\n"
            "k = 4\n"
            "```\n"
            "\n"
            "the k-distance is the distance to the fourth-nearest neighbor.\n"
            "\n"
            "---\n"
            "\n"
            "### 37.1 Reachability distance\n"
            "\n"
            "The source describes reachability distance as a stabilized local distance based on:\n"
            "\n"
            "```text\n"
            "max(\n"
            "    neighbor's k-distance,\n"
            "    direct distance\n"
            ")\n"
            "```\n"
            "\n"
            "This avoids making very small direct distances dominate local density calculations.\n"
            "\n"
            "[[IMAGE_NEEDED: LOF k-distance and reachability | Central point A, four nearest neighbors, circle to 4th neighbor, another point B with labels for direct distance and reachability distance | Learner should understand how local neighborhoods are defined]]\n"
            "\n"
            "---\n"
            "\n"
            "## 38. Local Reachability Density (LRD)\n"
            "\n"
            "For each point:\n"
            "\n"
            "```text\n"
            "average reachability distance\n"
            "→ calculate neighborhood spacing\n"
            "\n"
            "inverse of that average\n"
            "→ local reachability density\n"
            "```\n"
            "\n"
            "Therefore:\n"
            "\n"
            "```text\n"
            "large average distance\n"
            "→ low density\n"
            "\n"
            "small average distance\n"
            "→ high density\n"
            "```\n"
            "\n"
            "LOF compares the point's local density with the densities of its neighbors.\n"
            "\n"
            "---\n"
            "\n"
            "## 39. Interpreting LOF score\n"
            "\n"
            "The chapter gives this intuition:\n"
            "\n"
            "```text\n"
            "LOF ≈ 1\n"
            "→ density similar to neighbors\n"
            "→ likely normal\n"
            "\n"
            "LOF < 1\n"
            "→ denser than neighbors\n"
            "\n"
            "LOF > 1\n"
            "→ less dense than neighbors\n"
            "→ potential anomaly\n"
            "```\n"
            "\n"
            "Large LOF indicates stronger local isolation.\n"
            "\n"
            "---\n"
            "\n"
            "### 39.1 Source implementation\n"
            "\n"
            "```python\n"
            "from sklearn.neighbors import (\n"
            "    LocalOutlierFactor\n"
            ")\n"
            "\n"
            "lof = LocalOutlierFactor(\n"
            "    n_neighbors=4,\n"
            "    contamination='auto'\n"
            ")\n"
            "\n"
            "labels = lof.fit_predict(\n"
            "    X_scaled\n"
            ")\n"
            "```\n"
            "\n"
            "Again:\n"
            "\n"
            "```text\n"
            "1\n"
            "→ normal\n"
            "\n"
            "-1\n"
            "→ anomaly\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 39.2 Why LOF can disagree with visual distance\n"
            "\n"
