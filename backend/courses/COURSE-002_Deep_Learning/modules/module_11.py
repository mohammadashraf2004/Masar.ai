            "## 3. Sequence Models and Learned Word Embeddings\n"
            "\n"
            "N-grams preserve only limited local ordering.\n"
            "\n"
            "To model longer relationships, we can provide the complete ordered "
            "token sequence to the neural network.\n"
            "\n"
            "These are **sequence models**.\n"
            "\n"
            "Possible sequence architectures include:\n"
            "\n"
            "```text\n"
            "RNN / LSTM / GRU\n"
            "1D ConvNet\n"
            "Transformer\n"
            "```\n"
            "\n"
            "This chapter focuses on an LSTM-based classifier, while the next "
            "chapter builds toward Transformers.\n"
            "\n"
            "### Variable-length text creates a batching problem\n"
            "\n"
            "Movie reviews have different lengths.\n"
            "\n"
            "```text\n"
            "Review A → 80 tokens\n"
            "Review B → 240 tokens\n"
            "Review C → 510 tokens\n"
            "```\n"
            "\n"
            "GPU batch computations work most conveniently with rectangular "
            "tensors.\n"
            "\n"
            "We therefore use **padding** and **truncation**.\n"
            "\n"
            "### Truncation\n"
            "\n"
            "Suppose we choose:\n"
            "\n"
            "```text\n"
            "maximum sequence length = 600\n"
            "```\n"
            "\n"
            "Reviews longer than 600 tokens are shortened.\n"
            "\n"
            "### Padding\n"
            "\n"
            "Shorter reviews receive a special `[PAD]` token.\n"
            "\n"
            "Suppose the desired length is 8:\n"
            "\n"
            "```text\n"
            "\"the slow brown badger\"\n"
            "```\n"
            "\n"
            "becomes:\n"
            "\n"
            "```text\n"
            "[the, slow, brown, badger, PAD, PAD, PAD, PAD]\n"
            "```\n"
            "\n"
            "Now every sample in the batch has the same length.\n"
            "\n"
            "With batch size 32 and maximum length 600:\n"
            "\n"
            "```text\n"
            "batch shape = (32, 600)\n"
            "```\n"
            "\n"
            "Each value is a token ID.\n"
            "\n"
            "### First attempt: one-hot encoding each token\n"
            "\n"
            "One way to convert a token ID into a vector is one-hot encoding.\n"
            "\n"
            "Suppose the vocabulary has 30,000 terms.\n"
            "\n"
            "Token ID 4 becomes something like:\n"
            "\n"
            "```text\n"
            "[0, 0, 0, 0, 1, 0, 0, ..., 0]\n"
            "```\n"
            "\n"
            "This vector contains 30,000 dimensions.\n"
            "\n"
            "A 600-token review therefore becomes conceptually:\n"
            "\n"
            "```text\n"
            "(600, 30000)\n"
            "```\n"
            "\n"
            "That is:\n"
            "\n"
            "```text\n"
            "18,000,000 values\n"
            "```\n"
            "\n"
            "for one review.\n"
            "\n"
            "This is extremely inefficient.\n"
            "\n"
            "### Bidirectional LSTM classifier\n"
            "\n"
            "The chapter first uses one-hot token vectors with a bidirectional "
            "LSTM:\n"
            "\n"
            "```python\n"
            "inputs = keras.Input(shape=(600,), dtype=\"int32\")\n"
            "x = one_hot_encoding(inputs)\n"
            "x = layers.Bidirectional(layers.LSTM(64))(x)\n"
            "x = layers.Dropout(0.5)(x)\n"
            "outputs = layers.Dense(1, activation=\"sigmoid\")(x)\n"
            "```\n"
            "\n"
            "Why bidirectional?\n"
            "\n"
            "For sentiment classification, the entire review is already "
            "available before prediction.\n"
            "\n"
            "So the representation can benefit from processing relationships "
            "in both directions:\n"
            "\n"
            "```text\n"
            "left → right\n"
            "+\n"
            "right → left\n"
            "```\n"
            "\n"
            "This differs from causal forecasting, where future information "
            "must not be available when predicting the future.\n"
            "\n"
            "### Bigger does not automatically mean better\n"
            "\n"
            "The one-hot LSTM has around 15 million trainable parameters in the "
            "chapter experiment and is much slower than the linear bag-of-words "
            "classifier.\n"
            "\n"
            "Yet its test accuracy is only around 84%.\n"
            "\n"
            "The much smaller bigram model reaches about 90%.\n"
            "\n"
            "This demonstrates an important engineering lesson:\n"
            "\n"
            "> Architectural complexity is only useful when the data and "
            "training setup allow the model to exploit it.\n"
            "\n"
            "### Why one-hot word vectors are conceptually weak\n"
            "\n"
            "One-hot encoding treats all vocabulary terms as unrelated.\n"
            "\n"
            "For example:\n"
            "\n"
            "```text\n"
            "movie\n"
            "film\n"
            "```\n"
            "\n"
            "are semantically similar.\n"
            "\n"
            "But their one-hot vectors are completely separate and equally "
            "distant from one another as any unrelated words.\n"
            "\n"
            "This is not a natural representation of language.\n"
            "\n"
            "### Word embeddings\n"
            "\n"
            "A **word embedding** represents each token with a relatively small "
            "dense floating-point vector.\n"
            "\n"
            "Instead of:\n"
            "\n"
            "```text\n"
            "one-hot vector\n"
            "30,000 dimensions\n"
            "mostly zeros\n"
            "```\n"
            "\n"
            "we might use:\n"
            "\n"
            "```text\n"
            "embedding vector\n"
            "64 dimensions\n"
            "dense floating-point values\n"
            "```\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "movie → [ 0.18, -0.42, 0.73, ... ]\n"
            "film  → [ 0.21, -0.39, 0.70, ... ]\n"
            "```\n"
            "\n"
            "During learning, related words can develop related geometric "
            "representations.\n"
            "\n"
            "### Embedding as a learned lookup table\n"
            "\n"
            "An Embedding layer can be thought of as a table:\n"
            "\n"
            "```text\n"
            "token ID\n"
            "   ↓\n"
            "look up row\n"
            "   ↓\n"
            "dense vector\n"
            "```\n"
            "\n"
            "For example:\n"
            "\n"
            "```python\n"
            "layers.Embedding(\n"
            "    input_dim=30000,\n"
            "    output_dim=64,\n"
            ")\n"
            "```\n"
            "\n"
            "means:\n"
            "\n"
            "```text\n"
            "30,000 possible token IDs\n"
            "64 learned values per token\n"
            "```\n"
            "\n"
            "The embedding therefore contains:\n"
            "\n"
            "```text\n"
            "30000 × 64\n"
            "= 1,920,000 parameters\n"
            "```\n"
            "\n"
            "This is far smaller than the parameter cost induced by feeding "
            "30,000-dimensional one-hot tokens into the LSTM.\n"
            "\n"
            "### Embedding-based sequence classifier\n"
            "\n"
            "The model becomes:\n"
            "\n"
            "```python\n"
            "inputs = keras.Input(shape=(600,), dtype=\"int32\")\n"
            "\n"
            "x = layers.Embedding(\n"
            "    input_dim=30000,\n"
            "    output_dim=64,\n"
            "    mask_zero=True,\n"
            ")(inputs)\n"
            "\n"
            "x = layers.Bidirectional(layers.LSTM(64))(x)\n"
            "x = layers.Dropout(0.5)(x)\n"
            "outputs = layers.Dense(1, activation=\"sigmoid\")(x)\n"
            "```\n"
            "\n"
            "The model size drops dramatically compared with one-hot input.\n"
            "\n"
            "### Masking padding tokens\n"
            "\n"
            "Remember that many reviews end with padding:\n"
            "\n"
            "```text\n"
            "the movie was awful PAD PAD PAD PAD\n"
            "```\n"
            "\n"
            "We do not want the LSTM's final representation to reflect repeated "
            "processing of meaningless padding tokens.\n"
            "\n"
            "Using:\n"
            "\n"
            "```python\n"
            "mask_zero=True\n"
            "```\n"
            "\n"
            "tells Keras that token ID 0 represents padding.\n"
            "\n"
            "The mask is propagated to compatible layers such as the LSTM, "
            "allowing padded timesteps to be ignored.\n"
            "\n"
            "The useful final state then corresponds to real sequence content "
            "rather than repeated padding.\n"
            "\n"
            "### Why learned embeddings still do not solve everything\n"
            "\n"
            "The embedding-based LSTM is much more efficient than the one-hot "
            "version.\n"
            "\n"
            "But in the chapter experiment, its accuracy remains around 84%.\n"
            "\n"
            "The problem is not that embeddings are useless.\n"
