            "## 5. Pie, bar, histogram, and bubble plots\n"
            "\n"
            "---\n"
            "\n"
            "### 5.1 Pie plot\n"
            "\n"
            "A pie chart represents categories as portions of a whole.\n"
            "\n"
            "The chapter example uses subject scores:\n"
            "\n"
            "```python\n"
            "subjects = [\n"
