            "---\n"
            "\n"
            "## 10. Trustworthiness\n"
            "\n"
            "Trustworthiness measures whether local neighborhoods in the original high-dimensional data remain similar after reduction.\n"
            "\n"
            "Source:\n"
            "\n"
            "```python\n"
            "from sklearn.manifold import (\n"
            "    trustworthiness\n"
            ")\n"
            "\n"
            "trust = trustworthiness(\n"
            "    X_scaled,\n"
            "    X_pca,\n"
            "    n_neighbors=5\n"
            ")\n"
            "```\n"
            "\n"
            "The metric ranges approximately:\n"
            "\n"
            "```text\n"
            "0 to 1\n"
            "```\n"
            "\n"
            "Higher is better.\n"
            "\n"
            "Source example:\n"
            "\n"
            "```text\n"
            "Trustworthiness ≈ 0.8013\n"
            "```\n"
            "\n"
            "The chapter interprets that as substantial structural preservation.\n"
            "\n"
            "---\n"
            "\n"
            "### 10.1 Why this matters\n"
            "\n"
            "A 2D projection can look convincing but still distort neighborhoods.\n"
            "\n"
            "Trustworthiness helps ask:\n"
            "\n"
            "> Are points that appear close in the reduced space genuinely close in the original space?\n"
            "\n"
            "---\n"
            "\n"
            "## 11. Sammon stress\n"
            "\n"
            "The chapter also introduces a distance-preservation score called Sammon stress.\n"
            "\n"
            "Its practical interpretation in the source:\n"
            "\n"
