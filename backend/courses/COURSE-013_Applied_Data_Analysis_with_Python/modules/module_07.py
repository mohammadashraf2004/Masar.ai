            "## 10. What is an outlier?\n"
            "\n"
            "An outlier is an observation that is statistically different from the general pattern.\n"
            "\n"
            "Possible causes given by the chapter include:\n"
            "\n"
            "- measurement error,\n"
            "- data-entry error,\n"
            "- sampling error,\n"
            "- behavioral change,\n"
            "- natural occurrence.\n"
            "\n"
            "This leads to an important principle:\n"
            "\n"
            "> Outlier does not mean “bad value.”\n"
            "\n"
            "An outlier might indicate:\n"
            "\n"
            "```text\n"
            "error\n"
            "or\n"
            "new behavior\n"
            "or\n"
            "rare but valid event\n"
            "or\n"
            "important discovery\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "## 11. Univariate and multivariate outliers\n"
            "\n"
            "---\n"
            "\n"
            "### 11.1 Univariate outlier\n"
            "\n"
            "An observation is unusual within one feature.\n"
            "\n"
            "Example:\n"
            "\n"
            "```text\n"
            "most incomes:\n"
            "40k–200k\n"
            "\n"
            "one income:\n"
            "600k\n"
            "```\n"
            "\n"
            "That value may appear extreme in the income column alone.\n"
            "\n"
            "---\n"
            "\n"
            "### 11.2 Multivariate outlier\n"
            "\n"
            "A point may appear normal on every individual feature but unusual when variables are considered together.\n"
            "\n"
            "Source example concept:\n"
            "\n"
            "```text\n"
            "Math score\n"
            "Biology score\n"
            "```\n"
            "\n"
            "Each score can be normal individually.\n"
            "\n"
            "But a particular combination can be highly unusual.\n"
            "\n"
            "That is a multivariate outlier.\n"
            "\n"
            "---\n"
            "\n"
            "### 11.3 Why outliers matter\n"
            "\n"
            "The chapter lists three reasons:\n"
            "\n"
            "#### Distort statistics\n"
            "\n"
            "Mean and standard deviation can shift.\n"
            "\n"
            "#### Mislead machine-learning models\n"
            "\n"
            "Models may learn patterns driven by extreme observations.\n"
            "\n"
            "#### Represent a different phenomenon\n"
            "\n"
            "The outlier may contain meaningful information.\n"
            "\n"
            "So detection comes before treatment.\n"
            "\n"
            "---\n"
            "\n"
            "## 12. Z-score outlier detection\n"
            "\n"
            "The Z-score asks:\n"
            "\n"
            "> How many standard deviations is this observation away from the mean?\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "z =\n"
            "(value - mean)\n"
            "/\n"
            "standard deviation\n"
            "```\n"
            "\n"
            "The chapter uses the absolute value of Z-score for outlier detection.\n"
            "\n"
            "---\n"
            "\n"
            "### 12.1 Three-standard-deviation rule\n"
            "\n"
            "The source connects the threshold:\n"
            "\n"
            "```text\n"
            "|z| > 3\n"
            "```\n"
            "\n"
            "with the 68–95–99.7 rule for normally distributed data.\n"
            "\n"
            "Approximate intuition:\n"
            "\n"
            "```text\n"
            "±1σ → 68%\n"
            "±2σ → 95%\n"
            "±3σ → 99.7%\n"
            "```\n"
            "\n"
            "Therefore, points beyond 3 standard deviations are treated as unusual in the chapter example.\n"
            "\n"
            "---\n"
            "\n"
            "### 12.2 Python example\n"
            "\n"
            "Prepare income:\n"
            "\n"
            "```python\n"
            "from scipy import stats\n"
            "import numpy as np\n"
            "\n"
            "income_data = (\n"
            "    customers[\n"
            "        'Income ($)'\n"
            "    ]\n"
            "    .dropna()\n"
            "    .reset_index(\n"
            "        drop=True\n"
            "    )\n"
            ")\n"
            "```\n"
            "\n"
            "Add synthetic extremes:\n"
            "\n"
            "```python\n"
            "income_with_outliers = pd.concat([\n"
            "    income_data,\n"
            "    pd.Series([\n"
            "        350000,\n"
            "        -120000\n"
            "    ])\n"
            "], ignore_index=True)\n"
            "```\n"
            "\n"
            "Calculate:\n"
            "\n"
            "```python\n"
            "z_scores = np.abs(\n"
            "    stats.zscore(\n"
            "        income_with_outliers\n"
            "    )\n"
            ")\n"
            "\n"
            "threshold = 3\n"
            "```\n"
            "\n"
            "Select:\n"
            "\n"
            "```python\n"
            "outliers = (\n"
            "    income_with_outliers[\n"
            "        z_scores > threshold\n"
            "    ]\n"
            ")\n"
            "```\n"
            "\n"
            "Source output:\n"
            "\n"
            "```text\n"
            "350000\n"
            "-120000\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 12.3 Z-score limitation\n"
            "\n"
            "The chapter immediately points out a weakness.\n"
            "\n"
            "The outliers themselves affect:\n"
            "\n"
            "- mean,\n"
            "- standard deviation.\n"
            "\n"
            "That can reduce the robustness of the detection.\n"
            "\n"
            "The source also warns that Z-score logic is tied to a normal-distribution assumption.\n"
            "\n"
            "For skewed data, another method may be preferable.\n"
            "\n"
            "[[IMAGE_NEEDED: Z-score outlier intuition | Bell-shaped distribution with mean at center and ±1σ, ±2σ, ±3σ marked; two extreme points beyond ±3σ highlighted | Learner should understand the threshold as distance from the mean in standard-deviation units]]\n"
            "\n"
            "---\n"
            "\n"
            "## 13. IQR and box-plot outlier detection\n"
            "\n"
            "The chapter introduces IQR as a more robust alternative.\n"
            "\n"
            "Definitions:\n"
            "\n"
            "```text\n"
            "Q1 = 25th percentile\n"
            "Q3 = 75th percentile\n"
            "\n"
            "IQR = Q3 - Q1\n"
            "```\n"
            "\n"
            "The IQR describes the middle 50% of the data.\n"
            "\n"
            "---\n"
            "\n"
            "### 13.1 Outlier bounds\n"
            "\n"
            "The source code uses:\n"
            "\n"
            "```text\n"
            "Lower bound = Q1 - 1.5 × IQR\n"
            "\n"
            "Upper bound = Q3 + 1.5 × IQR\n"
            "```\n"
            "\n"
            "Values outside these bounds are treated as outliers.\n"
            "\n"
            "Python:\n"
            "\n"
            "```python\n"
            "Q1 = (\n"
            "    income_with_outliers\n"
            "    .quantile(0.25)\n"
            ")\n"
            "\n"
            "Q3 = (\n"
            "    income_with_outliers\n"
            "    .quantile(0.75)\n"
            ")\n"
            "\n"
            "IQR = Q3 - Q1\n"
            "\n"
            "lower_bound = (\n"
            "    Q1 - 1.5 * IQR\n"
            ")\n"
            "\n"
            "upper_bound = (\n"
            "    Q3 + 1.5 * IQR\n"
            ")\n"
            "```\n"
            "\n"
            "Select:\n"
            "\n"
            "```python\n"
            "outliers = (\n"
            "    income_with_outliers[\n"
            "        (\n"
            "            income_with_outliers\n"
            "            < lower_bound\n"
            "        )\n"
            "        |\n"
            "        (\n"
            "            income_with_outliers\n"
            "            > upper_bound\n"
            "        )\n"
            "    ]\n"
            ")\n"
            "```\n"
            "\n"
            "Source result again detects:\n"
            "\n"
            "```text\n"
            "350000\n"
            "-120000\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 13.2 Source result values\n"
            "\n"
            "The chapter reports:\n"
            "\n"
            "```text\n"
            "IQR:         105645.50\n"
            "Lower Bound: -101000.75\n"
            "Upper Bound: 321581.25\n"
            "```\n"
            "\n"
            "The synthetic values lie outside those limits.\n"
            "\n"
            "---\n"
            "\n"
            "### 13.3 Box plot\n"
            "\n"
            "The chapter visualizes:\n"
            "\n"
            "```python\n"
            "sns.boxplot(\n"
            "    x=income_with_outliers,\n"
            "    color='skyblue'\n"
            ")\n"
            "```\n"
            "\n"
            "The box plot shows:\n"
            "\n"
            "- central spread,\n"
            "- quartiles,\n"
            "- extreme points.\n"
            "\n"
            "The source describes distant dots as the detected outliers.\n"
            "\n"
            "[[IMAGE_NEEDED: Box plot anatomy and IQR rule | Horizontal box plot labeled Q1, median, Q3, IQR, lower/upper whisker bounds and two external outlier points | Learner should connect the visual box plot to the Q1 ± 1.5×IQR calculation]]\n"
            "\n"
