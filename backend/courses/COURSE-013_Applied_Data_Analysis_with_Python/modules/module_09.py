            "## 4. Simple linear regression\n"
            "\n"
            "Linear regression models a linear relationship between input and target.\n"
            "\n"
            "Conceptual equation:\n"
            "\n"
            "```text\n"
            "y = β₀ + β₁x + ε\n"
            "```\n"
            "\n"
            "Where:\n"
            "\n"
            "```text\n"
            "x\n"
            "→ independent variable\n"
            "\n"
            "y\n"
            "→ dependent variable\n"
            "\n"
            "β₀\n"
            "→ intercept\n"
            "\n"
            "β₁\n"
            "→ slope / coefficient\n"
            "\n"
            "ε\n"
            "→ error term\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 4.1 Intercept\n"
            "\n"
            "The intercept is the baseline predicted value of `y` when:\n"
            "\n"
            "```text\n"
            "x = 0\n"
            "```\n"
            "\n"
            "Whether this baseline has a useful real-world interpretation depends on whether `x=0` is meaningful.\n"
            "\n"
            "---\n"
            "\n"
            "### 4.2 Coefficient\n"
            "\n"
            "The coefficient represents the estimated average change in `y` when `x` increases by one unit.\n"
            "\n"
            "Example:\n"
            "\n"
            "```text\n"
            "β₁ = 5000\n"
            "```\n"
            "\n"
            "could mean:\n"
            "\n"
            "> Each additional year of experience is associated with about 5,000 additional salary units, holding other modeled conditions fixed.\n"
            "\n"
            "Important:\n"
            "\n"
            "> A regression coefficient shows association unless a valid causal design supports a causal claim.\n"
            "\n"
            "The source explicitly warns that a non-zero coefficient does not prove cause and effect.\n"
            "\n"
            "---\n"
            "\n"
            "### 4.3 Prediction and residual\n"
            "\n"
            "Suppose:\n"
            "\n"
            "```text\n"
            "actual salary    = 80,000\n"
            "predicted salary = 75,000\n"
            "```\n"
            "\n"
            "Then the residual is the difference between actual and predicted values.\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "residual\n"
            "=\n"
            "actual\n"
            "-\n"
            "predicted\n"
            "```\n"
            "\n"
            "Residuals are central to both model fitting and assumption checking.\n"
            "\n"
