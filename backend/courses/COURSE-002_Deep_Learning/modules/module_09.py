            '## 7. Object detection: labels plus bounding boxes\n'
            '\n'
            'Object detection identifies objects and estimates where they are.\n'
            '\n'
            'A detector typically returns several predictions:\n'
            '\n'
            '```text\n'
            'class\n'
            'bounding box\n'
            'confidence\n'
            '```\n'
            '\n'
            'Example:\n'
            '\n'
            '```text\n'
            'person\n'
            'box = [x, y, width, height]\n'
            'confidence = 0.93\n'
            '```\n'
            '\n'
            '### Why use detection when segmentation is richer?\n'
            '\n'
            'Because detection is often:\n'
            '\n'
            '- faster,\n'
            '- cheaper to annotate,\n'
            '- simpler to deploy,\n'
            '- sufficient for counting and tracking.\n'
            '\n'
            'Common uses include:\n'
            '\n'
            '#### Counting\n'
            '\n'
            '```text\n'
            'How many cars are in this frame?\n'
            '```\n'
            '\n'
            '#### Tracking\n'
            '\n'
            'Detect objects in each video frame, then associate detections over time.\n'
            '\n'
            '#### Cropping\n'
            '\n'
            'Find a region and send that crop to:\n'
            '\n'
            '- a high-resolution classifier,\n'
            '- OCR,\n'
            '- another specialized model.\n'
            '\n'
            '### Bounding-box labels are cheaper\n'
            '\n'
            'For detection, a human annotator draws:\n'
            '\n'
            '```text\n'
            'rectangle around object\n'
            '```\n'
            '\n'
            'For segmentation, the annotator must trace:\n'
            '\n'
            '```text\n'
            'pixel-accurate object boundary\n'
            '```\n'
            '\n'
            'This difference becomes enormous when datasets contain thousands or millions of objects.\n'
            '\n'
            '---\n'
            '\n'
            '## 8. Two-stage versus single-stage detectors\n'
            '\n'
            'Object detectors can be organized into two broad families.\n'
            '\n'
            '### Two-stage detectors\n'
            '\n'
            'R-CNN-style methods separate detection into two steps.\n'
            '\n'
            '#### Stage 1 — Region proposals\n'
            '\n'
            'The model proposes many areas that may contain objects.\n'
            '\n'
            '```text\n'
            'image\n'
            '  ↓\n'
            'candidate region A\n'
            'candidate region B\n'
            'candidate region C\n'
            '...\n'
            '```\n'
            '\n'
            '#### Stage 2 — Classification and refinement\n'
            '\n'
            'Each candidate is then:\n'
            '\n'
            '- classified,\n'
            '- scored,\n'
            '- refined,\n'
            '- filtered.\n'
            '\n'
            'Conceptually:\n'
            '\n'
            '```text\n'
            'image\n'
            '   ↓\n'
            'region proposals\n'
            '   ↓\n'
            'classify each region\n'
            '   ↓\n'
            'refine boxes\n'
            '   ↓\n'
            'final detections\n'
            '```\n'
            '\n'
            'Later R-CNN versions replaced hand-designed region proposal systems with learned proposal networks.\n'
            '\n'
            '### Strength of two-stage detection\n'
            '\n'
            'The approach can be accurate because it spends substantial computation examining candidate regions.\n'
            '\n'
            '### Cost of two-stage detection\n'
            '\n'
            'The same design can be expensive because many regions must be processed.\n'
            '\n'
            'This can be undesirable for:\n'
            '\n'
            '- real-time inference,\n'
            '- embedded systems,\n'
            '- latency-sensitive applications.\n'
            '\n'
            '### Single-stage detectors\n'
            '\n'
            'Single-stage detectors predict object information directly in one network pass.\n'
            '\n'
            'Examples include:\n'
            '\n'
            '```text\n'
            'YOLO\n'
            'RetinaNet\n'
            'SSD\n'
            '```\n'
            '\n'
            'The network jointly predicts:\n'
            '\n'
            '```text\n'
            'where the object is\n'
            '+\n'
            'what the object is\n'
            '```\n'
            '\n'
            'This is generally faster and more suitable for real-time use.\n'
            '\n'
            '### Main tradeoff\n'
            '\n'
            'A useful simplified comparison is:\n'
            '\n'
            '| Two-stage | Single-stage |\n'
            '|---|---|\n'
            '| Region proposals first | Direct prediction |\n'
            '| More processing steps | One main prediction pipeline |\n'
            '| Often computationally heavier | Usually faster |\n'
            '| Historically strong accuracy | Strong speed/accuracy balance |\n'
            '| R-CNN family | YOLO, RetinaNet, SSD |\n'
            '\n'
            '---\n'
            '\n'
            '## 9. Understanding a YOLO-style single-stage detector\n'
            '\n'
            'YOLO stands for:\n'
            '\n'
            '```text\n'
            'You Only Look Once\n'
            '```\n'
            '\n'
            'The core idea is to divide an image into a grid and make predictions at grid locations.\n'
            '\n'
            'Imagine a:\n'
            '\n'
            '```text\n'
            '6 × 6 grid\n'
            '```\n'
            '\n'
            'Each cell predicts information such as:\n'
            '\n'
            '```text\n'
            'box coordinates\n'
            'object confidence\n'
            'class probabilities\n'
            '```\n'
            '\n'
            '### One possible output per cell\n'
            '\n'
            'A simplified box prediction contains:\n'
            '\n'
            '```text\n'
            'x\n'
            'y\n'
            'width\n'
            'height\n'
            'confidence\n'
            '```\n'
            '\n'
            'The class head contains probabilities over all supported object categories.\n'
            '\n'
            'So a grid location produces:\n'
            '\n'
            '```text\n'
            'box output\n'
            '+\n'
            'class output\n'
            '```\n'
            '\n'
            '### Which grid cell owns an object?\n'
            '\n'
            'A common rule is:\n'
            '\n'
            '> The grid cell containing the center of the object becomes responsible for that object.\n'
            '\n'
            'Suppose a car spans several cells.\n'
            '\n'
            'The model does not need every covered cell to predict the box.\n'
            '\n'
            "The box can be assigned to the cell containing the object's center.\n"
            '\n'
            '### Relative coordinates\n'
            '\n'
            'Instead of storing all coordinates in raw pixels, it is convenient to normalize them.\n'
            '\n'
            'For example:\n'
            '\n'
            '```text\n'
            'x in [0, 1]\n'
            'y in [0, 1]\n'
            'width in [0, 1]\n'
            'height in [0, 1]\n'
            '```\n'
            '\n'
            'This makes box representation independent of the original image size.\n'
            '\n'
            'Within the YOLO grid, center coordinates can also be represented relative to the responsible cell.\n'
            '\n'
            '### ConvNet backbone\n'
            '\n'
            'A detector still needs visual features.\n'
            '\n'
            'A pretrained ConvNet can act as a **backbone**:\n'
            '\n'
            '```text\n'
            'image\n'
            '  ↓\n'
            'ResNet or another ConvNet\n'
            '  ↓\n'
            'high-level feature map\n'
            '  ↓\n'
            'detection head\n'
            '```\n'
            '\n'
            'The detection head converts learned visual features into:\n'
            '\n'
            '```text\n'
            'grid predictions\n'
            '```\n'
            '\n'
            '### Why spatial structure matters\n'
            '\n'
            'Object detection needs location.\n'
            '\n'
            'So, just like segmentation, the model should not carelessly destroy spatial information.\n'
            '\n'
            'This is one reason strided convolutions are useful in detection backbones.\n'
            '\n'
            '---\n'
            '\n'
            '## 10. Training a YOLO-style detector\n'
            '\n'
            'Detection training is more complicated than ordinary classification because several outputs must be learned together.\n'
            '\n'
            'The model needs to learn:\n'
            '\n'
            '```text\n'
            '1. object class\n'
            '2. box location\n'
            '3. box size\n'
            '4. object confidence\n'
            '```\n'
            '\n'
            '### Classification loss\n'
            '\n'
            'Class prediction can use a familiar classification loss such as:\n'
            '\n'
            '```text\n'
            'sparse categorical cross-entropy\n'
            '```\n'
            '\n'
            '### Bounding-box regression\n'
            '\n'
            'For grid cells containing objects, the model also needs to minimize errors in:\n'
            '\n'
            '```text\n'
            'x\n'
            'y\n'
            'width\n'
            'height\n'
            '```\n'
            '\n'
            'A simple approach uses squared error.\n'
            '\n'
            '### Confidence is not only "object exists"\n'
            '\n'
            "The chapter's simplified YOLO training gives confidence a richer target.\n"
            '\n'
            'If the grid cell is empty:\n'
            '\n'
            '```text\n'
            'confidence target = 0\n'
            '```\n'
            '\n'
            'If the grid cell contains an object:\n'
            '\n'
            '```text\n'
            'confidence target = IoU(predicted box, true box)\n'
            '```\n'
            '\n'
            'This means confidence reflects both:\n'
            '\n'
            '```text\n'
            'object presence\n'
            '+\n'
            'box quality\n'
            '```\n'
            '\n'
            'A model with a poorly placed box should not be highly confident.\n'
            '\n'
            '### Why IoU is such a useful bridge\n'
            '\n'
            'IoU appears in both chapters because it captures spatial quality.\n'
            '\n'
            'For segmentation:\n'
            '\n'
            '```text\n'
            'predicted mask vs. true mask\n'
            '```\n'
            '\n'
            'For detection:\n'
            '\n'
            '```text\n'
            'predicted box vs. true box\n'
            '```\n'
            '\n'
            'So IoU is a general tool for measuring overlap.\n'
            '\n'
            '### Balancing parts of the box loss\n'
            '\n'
            'Detection data is highly imbalanced.\n'
            '\n'
            'Most grid cells contain no object.\n'
            '\n'
            'If all cells contribute equally, empty locations can dominate training.\n'
            '\n'
            'A practical detector may therefore:\n'
            '\n'
            '- increase the weight of localization errors,\n'
            '- reduce the weight of confidence errors from empty cells,\n'
            '- transform width and height errors so large boxes do not dominate.\n'
            '\n'
            'The general engineering lesson is:\n'
            '\n'
            '> Multi-part losses often need careful balancing because not all prediction errors have equal importance or frequency.\n'
            '\n'
            '### Streaming large datasets\n'
            '\n'
            'Large detection datasets can be too big to load into memory as decoded image tensors.\n'
            '\n'
            'A streaming pipeline such as:\n'
            '\n'
            '```text\n'
            'tf.data\n'
            '```\n'
            '\n'
            'can:\n'
            '\n'
            '- load images batch by batch,\n'
            '- preprocess only what is needed,\n'
            '- release memory after use,\n'
            '- prefetch future batches.\n'
            '\n'
            'This is much more realistic for large image datasets than loading all image tensors at once.\n'
            '\n'
            '### Why training from scratch is difficult\n'
            '\n'
            'An accurate general-purpose detector requires:\n'
            '\n'
            '- a large dataset,\n'
            '- many training epochs,\n'
            '- careful augmentation,\n'
            '- tuned losses,\n'
            '- multiple boxes per location in modern systems,\n'
            '- substantial compute.\n'
            '\n'
            'A small from-scratch YOLO exercise is best viewed as a way to understand the mechanics.\n'
            '\n'
            'For real applications, pretrained detectors are often the better starting point.\n'
            '\n'
            '{{exercise:M11.L01.EX02}}\n'
            '\n'
            '---\n'
