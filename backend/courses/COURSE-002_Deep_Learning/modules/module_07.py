            "## 4. Modern ConvNet Architecture Patterns\n"
            "\n"
            "Understanding convolution is only the beginning.\n"
            "\n"
            "The way layers are arranged has a major effect on whether a "
            "network trains efficiently and generalizes well.\n"
            "\n"
            "This is **model architecture**.\n"
            "\n"
            "Architecture defines the search space within which gradient "
            "descent tries to find a useful solution.\n"
            "\n"
            "A good architecture makes that search easier.\n"
            "\n"
            "### Modularity, hierarchy, and reuse\n"
            "\n"
            "The chapter introduces a useful general design principle:\n"
            "\n"
            "```text\n"
            "Modularity\n"
            "+\n"
            "Hierarchy\n"
            "+\n"
            "Reuse\n"
            "```\n"
            "\n"
            "or **MHR**.\n"
            "\n"
            "#### Modularity\n"
            "\n"
            "Organize the model into reusable blocks rather than treating it "
            "as one long unstructured list of layers.\n"
            "\n"
            "For example:\n"
            "\n"
            "```text\n"
            "Block 1\n"
            "  Conv\n"
            "  Conv\n"
            "  Pool\n"
            "\n"
            "Block 2\n"
            "  Conv\n"
            "  Conv\n"
            "  Pool\n"
            "```\n"
            "\n"
            "#### Hierarchy\n"
            "\n"
            "Stack blocks so representations become progressively more abstract.\n"
            "\n"
            "```text\n"
            "local edges\n"
            "   ↓\n"
            "textures\n"
            "   ↓\n"
            "object parts\n"
            "   ↓\n"
            "high-level concepts\n"
            "```\n"
            "\n"
            "#### Reuse\n"
            "\n"
            "Use the same useful design pattern repeatedly.\n"
            "\n"
            "Convolution itself is an example of reuse because the same filter "
            "is applied across different spatial positions.\n"
            "\n"
            "### Feature pyramids\n"
            "\n"
            "A common modern ConvNet pattern is:\n"
            "\n"
            "```text\n"
            "early network\n"
            "large spatial maps\n"
            "few channels\n"
            "\n"
            "       ↓\n"
            "\n"
            "deep network\n"
            "small spatial maps\n"
            "many channels\n"
            "```\n"
            "\n"
            "For example:\n"
            "\n"
            "```text\n"
            "32 filters\n"
            "  ↓\n"
            "64 filters\n"
            "  ↓\n"
            "128 filters\n"
            "  ↓\n"
            "256 filters\n"
            "  ↓\n"
            "512 filters\n"
            "```\n"
            "\n"
            "while width and height decrease.\n"
            "\n"
            "### Deep and narrow versus shallow and broad\n"
            "\n"
            "Deep networks can build abstraction progressively and reuse "
            "features across many levels.\n"
            "\n"
            "The source therefore presents the general design preference:\n"
            "\n"
            "```text\n"
            "deeper hierarchy of narrower layers\n"
            "rather than\n"
            "a very shallow network with extremely broad layers\n"
            "```\n"
            "\n"
            "But increasing depth creates a new problem.\n"
            "\n"
            "### Vanishing gradients\n"
            "\n"
            "Training a deep network requires gradient information to travel "
            "backward through many transformations.\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "forward:\n"
            "x → f1 → f2 → f3 → f4 → prediction\n"
            "\n"
            "backward:\n"
            "loss → f4 → f3 → f2 → f1\n"
            "```\n"
            "\n"
            "When the chain becomes very deep, useful gradient information may "
            "become progressively weaker or noisier.\n"
            "\n"
            "This is the **vanishing-gradient problem**.\n"
            "\n"
            "### Residual connections\n"
            "\n"
            "A residual connection creates an information shortcut around a "
            "block.\n"
            "\n"
            "Instead of only computing:\n"
            "\n"
            "```text\n"
            "x → block → output\n"
            "```\n"
            "\n"
            "we also preserve the original input:\n"
            "\n"
            "```text\n"
            "       ┌───────────────┐\n"
            "       │               ↓\n"
            "x → processing block → + → output\n"
            "       │               ↑\n"
            "       └── shortcut ───┘\n"
            "```\n"
            "\n"
            "In pseudocode:\n"
            "\n"
            "```python\n"
            "residual = x\n"
            "x = block(x)\n"
            "x = layers.add([x, residual])\n"
            "```\n"
            "\n"
            "The shortcut preserves a clean path for information and gradient "
            "flow through deep networks.\n"
            "\n"
            "### Shape matching in residual connections\n"
            "\n"
            "The tensors being added must have compatible shapes.\n"
            "\n"
            "Suppose the processing block changes:\n"
            "\n"
            "```text\n"
            "32 channels\n"
            "→ 64 channels\n"
            "```\n"
            "\n"
            "The residual path must also be transformed.\n"
            "\n"
            "A 1 × 1 convolution can project it to the required channel count:\n"
            "\n"
            "```python\n"
            "residual = layers.Conv2D(64, 1)(residual)\n"
            "```\n"
            "\n"
            "If the main path also downsamples spatially, a stride can be used "
            "on the residual projection to match the new dimensions.\n"
            "\n"
            "### Batch normalization\n"
            "\n"
            "You already know about normalizing raw input data.\n"
            "\n"
            "But activations inside a neural network also change as data moves "
            "through layers.\n"
            "\n"
            "`BatchNormalization` normalizes intermediate activations "
            "adaptively during training.\n"
            "\n"
            "A common pattern is:\n"
            "\n"
            "```python\n"
            "x = layers.Conv2D(\n"
            "    32,\n"
            "    3,\n"
            "    use_bias=False,\n"
            ")(x)\n"
            "\n"
            "x = layers.BatchNormalization()(x)\n"
            "x = layers.Activation(\"relu\")(x)\n"
            "```\n"
            "\n"
            "The source recommends the ordering:\n"
            "\n"
            "```text\n"
            "convolution\n"
            "    ↓\n"
            "batch normalization\n"
            "    ↓\n"
            "activation\n"
            "```\n"
            "\n"
            "Batch normalization commonly helps gradient propagation and makes "
            "deep networks easier to train.\n"
            "\n"
            "During training, batch statistics are used.\n"
            "\n"
            "During inference, stored moving statistics collected during "
            "training are used instead.\n"
            "\n"
            "### Why remove the convolution bias before BatchNorm?\n"
            "\n"
            "A convolution normally computes something conceptually like:\n"
            "\n"
            "```text\n"
            "conv(x, kernel) + bias\n"
            "```\n"
            "\n"
            "But BatchNormalization performs a centering operation afterward.\n"
            "\n"
            "So when BatchNorm immediately follows a convolution, the "
            "convolution's bias is usually unnecessary:\n"
            "\n"
            "```python\n"
            "Conv2D(..., use_bias=False)\n"
            "```\n"
            "\n"
            "### Depthwise separable convolution\n"
            "\n"
            "A normal convolution learns spatial patterns and channel mixing "
            "together.\n"
            "\n"
            "A depthwise separable convolution separates these two jobs.\n"
            "\n"
            "```text\n"
            "Input feature map\n"
            "      ↓\n"
            "Depthwise convolution\n"
            "process spatial patterns within each channel\n"
            "      ↓\n"
            "1 × 1 pointwise convolution\n"
            "mix information across channels\n"
            "      ↓\n"
            "Output feature map\n"
            "```\n"
            "\n"
            "In Keras:\n"
            "\n"
            "```python\n"
            "layers.SeparableConv2D(...)\n"
            "```\n"
            "\n"
            "### Why separable convolution can be efficient\n"
            "\n"
            "Consider a regular 3 × 3 convolution with:\n"
            "\n"
            "```text\n"
            "64 input channels\n"
            "64 output channels\n"
            "```\n"
            "\n"
            "Its parameter count is proportional to:\n"
            "\n"
            "```text\n"
            "3 × 3 × 64 × 64\n"
            "= 36,864\n"
            "```\n"
            "\n"
            "A depthwise separable version uses approximately:\n"
            "\n"
            "```text\n"
            "(3 × 3 × 64)\n"
            "+\n"
            "(64 × 64)\n"
            "= 4,672\n"
            "```\n"
            "\n"
            "That is a large reduction in trainable parameters.\n"
            "\n"
            "Fewer parameters can mean:\n"
            "\n"
            "- a smaller model,\n"
            "- less computation in principle,\n"
            "- lower overfitting risk,\n"
            "- and efficient use of limited training data.\n"
            "\n"
            "The source also notes an important engineering reality: fewer "
            "theoretical operations do not automatically guarantee a matching "
            "GPU speedup because actual performance depends heavily on hardware "
            "and software kernel optimization.\n"
            "\n"
            "### Putting the architecture patterns together\n"
            "\n"
            "A modern block can combine:\n"
            "\n"
            "```text\n"
            "BatchNorm\n"
            "   ↓\n"
            "ReLU\n"
            "   ↓\n"
            "SeparableConv2D\n"
            "   ↓\n"
            "BatchNorm\n"
            "   ↓\n"
            "ReLU\n"
            "   ↓\n"
            "SeparableConv2D\n"
            "   ↓\n"
            "MaxPooling\n"
            "   ↓\n"
            "+ residual shortcut\n"
            "```\n"
            "\n"
            "Then repeat this block with increasing filter counts.\n"
            "\n"
            "A simplified Xception-like architecture looks like:\n"
            "\n"
            "```python\n"
            "inputs = keras.Input(shape=(180, 180, 3))\n"
            "x = layers.Rescaling(1.0 / 255)(inputs)\n"
            "\n"
            "# Regular convolution first because RGB channels are strongly related.\n"
            "x = layers.Conv2D(32, 5, use_bias=False)(x)\n"
            "\n"
            "for filters in [32, 64, 128, 256, 512]:\n"
            "    residual = x\n"
            "\n"
            "    x = layers.BatchNormalization()(x)\n"
            "    x = layers.Activation(\"relu\")(x)\n"
            "    x = layers.SeparableConv2D(\n"
            "        filters,\n"
            "        3,\n"
            "        padding=\"same\",\n"
            "        use_bias=False,\n"
            "    )(x)\n"
            "\n"
            "    x = layers.BatchNormalization()(x)\n"
            "    x = layers.Activation(\"relu\")(x)\n"
            "    x = layers.SeparableConv2D(\n"
            "        filters,\n"
            "        3,\n"
            "        padding=\"same\",\n"
            "        use_bias=False,\n"
            "    )(x)\n"
            "\n"
            "    x = layers.MaxPooling2D(\n"
            "        3,\n"
            "        strides=2,\n"
            "        padding=\"same\",\n"
            "    )(x)\n"
            "\n"
            "    residual = layers.Conv2D(\n"
            "        filters,\n"
            "        1,\n"
            "        strides=2,\n"
            "        padding=\"same\",\n"
            "        use_bias=False,\n"
            "    )(residual)\n"
            "\n"
            "    x = layers.add([x, residual])\n"
            "\n"
            "x = layers.GlobalAveragePooling2D()(x)\n"
            "x = layers.Dropout(0.5)(x)\n"
            "outputs = layers.Dense(1, activation=\"sigmoid\")(x)\n"
            "\n"
            "model = keras.Model(inputs, outputs)\n"
            "```\n"
            "\n"
            "The important lesson is not to memorize this code line by line.\n"
            "\n"
            "Instead, notice the design pattern:\n"
            "\n"
            "```text\n"
            "repeated blocks\n"
            "+\n"
            "increasing channel depth\n"
            "+\n"
            "decreasing spatial dimensions\n"
            "+\n"
            "residual connections\n"
            "+\n"
            "batch normalization\n"
            "+\n"
            "efficient convolution\n"
            "+\n"
            "global pooling\n"
            "+\n"
            "regularized classifier\n"
            "```\n"
            "\n"
            "### ConvNets and Vision Transformers\n"
            "\n"
            "ConvNets are not the only architecture used for computer vision.\n"
            "\n"
            "Vision Transformers, or ViTs, represent an image as a sequence of "
            "patches and use Transformer-style processing to model "
            "relationships between them.\n"
            "\n"
            "A simplified picture is:\n"
            "\n"
            "```text\n"
            "image\n"
            "  ↓\n"
            "split into patches\n"
            "  ↓\n"
            "convert patches to vectors\n"
            "  ↓\n"
            "process as a sequence\n"
            "```\n"
            "\n"
            "The chapter emphasizes that Vision Transformers can be especially "
            "effective at very large scale, while ConvNets retain strong "
            "spatial assumptions that make them highly data efficient, "
            "especially for smaller image-classification datasets.\n"
            "\n"

