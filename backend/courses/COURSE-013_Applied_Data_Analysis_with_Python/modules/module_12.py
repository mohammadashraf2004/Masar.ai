            "## 13. Optimizers\n"
            "\n"
            "Optimization adjusts weights to reduce loss.\n"
            "\n"
            "The chapter introduces several optimizers.\n"
            "\n"
            "### Gradient Descent\n"
            "\n"
            "Uses the full dataset to calculate an update.\n"
            "\n"
            "Conceptual rule:\n"
            "\n"
            "```text\n"
            "move weights\n"
