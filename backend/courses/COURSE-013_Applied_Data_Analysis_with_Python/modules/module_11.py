            "## 18. Gradient Boosting\n"
            "\n"
            "Gradient Boosting is also stage-wise, but it does not primarily reweight examples like AdaBoost.\n"
            "\n"
            "Instead, it fits each new learner to an:\n"
            "\n"
            "```text\n"
            "error signal\n"
            "derived from the loss gradient\n"
            "```\n"
            "\n"
            "The source describes this as following the negative gradient of the chosen loss.\n"
            "\n"
            "---\n"
            "\n"
            "### 18.1 Core workflow\n"
            "\n"
            "Start with:\n"
            "\n"
            "```text\n"
            "baseline constant prediction\n"
            "```\n"
            "\n"
            "Then repeatedly:\n"
            "\n"
            "```text\n"
            "1. compute current loss error signal\n"
            "2. calculate negative gradient\n"
            "3. fit weak learner to that signal\n"
            "4. scale learner contribution by learning rate\n"
            "5. add correction to current model\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 18.2 Intuition\n"
            "\n"
            "For squared-error regression, the negative gradient behaves like residual correction.\n"
            "\n"
            "For classification, the loss gradient reflects the direction that reduces classification loss.\n"
            "\n"
            "So Gradient Boosting generalizes the idea:\n"
            "\n"
            "```text\n"
            "\"fit the remaining mistakes\"\n"
            "```\n"
            "\n"
            "through explicit loss optimization.\n"
            "\n"
            "---\n"
            "\n"
            "## 19. Gradient Boosting in Python\n"
            "\n"
            "The source uses:\n"
            "\n"
            "```python\n"
            "from sklearn.ensemble import (\n"
            "    GradientBoostingClassifier\n"
            ")\n"
            "\n"
            "gradient_boosting = (\n"
            "    GradientBoostingClassifier(\n"
            "        loss=\"log_loss\",\n"
            "        n_estimators=600,\n"
            "        learning_rate=0.1,\n"
            "        max_depth=3,\n"
            "        random_state=42\n"
            "    )\n"
            ")\n"
            "```\n"
            "\n"
            "Important controls:\n"
            "\n"
            "```text\n"
            "loss\n"
            "→ objective being optimized\n"
            "\n"
            "n_estimators\n"
            "→ number of stages\n"
            "\n"
            "learning_rate\n"
            "→ size of each correction\n"
            "\n"
            "max_depth\n"
            "→ complexity of each tree\n"
            "```\n"
            "\n"
