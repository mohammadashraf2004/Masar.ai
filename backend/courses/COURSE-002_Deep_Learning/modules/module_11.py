            "## 2. Set-Based Text Classification: Bag of Words and N-Grams\n"
            "\n"
            "Once text has been tokenized, a major design question remains:\n"
            "\n"
            "> How much should the model care about token order?\n"
            "\n"
            "The simplest answer is:\n"
            "\n"
            "> Ignore order completely.\n"
            "\n"
            "This produces a **bag-of-words** model.\n"
            "\n"
            "### Bag of words\n"
            "\n"
            "Suppose we have:\n"
            "\n"
            "```text\n"
            "\"this movie made me cry\"\n"
            "```\n"
            "\n"
            "After tokenization:\n"
            "\n"
            "```text\n"
            "[this, movie, made, me, cry]\n"
            "```\n"
            "\n"
            "A bag-of-words representation does not care which word came first.\n"
            "\n"
            "It only cares which vocabulary terms are present.\n"
            "\n"
            "Suppose the vocabulary is:\n"
            "\n"
            "```text\n"
            "0 → [UNK]\n"
            "1 → movie\n"
            "2 → film\n"
            "3 → made\n"
            "4 → laugh\n"
            "5 → cry\n"
            "```\n"
            "\n"
            "The review might become:\n"
            "\n"
            "```text\n"
            "[1, 1, 0, 1, 0, 1]\n"
            "```\n"
            "\n"
            "This is a **multi-hot vector**.\n"
            "\n"
            "Each position means:\n"
            "\n"
            "```text\n"
            "1 → token appears\n"
            "0 → token absent\n"
            "```\n"
            "\n"
            "### A very small sentiment classifier\n"
            "\n"
            "Using a 20,000-token vocabulary, an IMDb review becomes:\n"
            "\n"
            "```text\n"
            "(20000,)\n"
            "```\n"
            "\n"
            "One simple classifier is:\n"
            "\n"
            "```python\n"
            "inputs = keras.Input(shape=(20000,))\n"
            "outputs = layers.Dense(1, activation=\"sigmoid\")(inputs)\n"
            "\n"
            "model = keras.Model(inputs, outputs)\n"
            "```\n"
            "\n"
            "For binary sentiment classification:\n"
            "\n"
            "```text\n"
            "output      → one sigmoid unit\n"
            "loss        → binary crossentropy\n"
            "metric      → accuracy\n"
            "```\n"
            "\n"
            "Despite being extremely small, this model can perform surprisingly "
            "well because sentiment is often strongly associated with the "
            "presence of particular words.\n"
            "\n"
            "For example:\n"
            "\n"
            "```text\n"
            "\"terrible\"\n"
            "→ evidence for negative sentiment\n"
            "\n"
            "\"excellent\"\n"
            "→ evidence for positive sentiment\n"
            "```\n"
            "\n"
            "The source's unigram model reaches about 88% test accuracy while "
            "using only about twenty thousand trainable parameters.\n"
            "\n"
            "### Why bag of words is limited\n"
            "\n"
            "Consider:\n"
            "\n"
            "```text\n"
            "\"not bad\"\n"
            "```\n"
            "\n"
            "and:\n"
            "\n"
            "```text\n"
            "\"bad\"\n"
            "```\n"
            "\n"
            "A simple bag-of-words representation sees the word `bad` in both.\n"
            "\n"
            "But the phrase `not bad` can have very different sentiment.\n"
            "\n"
            "Word order contains information.\n"
            "\n"
            "### N-grams\n"
            "\n"
            "An **n-gram** is an ordered sequence of `n` consecutive tokens.\n"
            "\n"
            "For:\n"
            "\n"
            "```text\n"
            "\"this movie made me cry\"\n"
            "```\n"
            "\n"
            "the unigrams are:\n"
            "\n"
            "```text\n"
            "this\n"
            "movie\n"
            "made\n"
            "me\n"
            "cry\n"
            "```\n"
            "\n"
            "The bigrams are:\n"
            "\n"
            "```text\n"
            "this movie\n"
            "movie made\n"
            "made me\n"
            "me cry\n"
            "```\n"
            "\n"
            "Trigrams would contain three consecutive tokens.\n"
            "\n"
            "### Why bigrams help\n"
            "\n"
            "A unigram model treats:\n"
            "\n"
            "```text\n"
            "not\n"
            "bad\n"
            "```\n"
            "\n"
            "as separate clues.\n"
            "\n"
            "A bigram vocabulary can contain:\n"
            "\n"
            "```text\n"
            "\"not bad\"\n"
            "```\n"
            "\n"
            "as its own feature.\n"
            "\n"
            "This preserves some local word order without requiring a full "
            "sequence model.\n"
            "\n"
            "In the chapter, adding unigram and bigram features increases test "
            "accuracy from roughly 88% to roughly 90%.\n"
            "\n"
            "### Why not use arbitrarily large n-grams?\n"
            "\n"
            "The number of possible combinations grows extremely quickly.\n"
            "\n"
            "For a vocabulary of `V` words:\n"
            "\n"
            "```text\n"
            "possible unigrams  ~ V\n"
            "possible bigrams   ~ V²\n"
            "possible trigrams  ~ V³\n"
            "```\n"
            "\n"
            "In practice, not all combinations occur, but the explosion is "
            "still severe.\n"
            "\n"
            "Large n-grams can also cause the model to memorize exact phrases "
            "rather than generalize.\n"
            "\n"
            "This motivates models that consume the original ordered sequence "
            "instead of manually creating every possible phrase feature.\n"
            "\n"
            "### Set models versus sequence models\n"
            "\n"
            "The distinction is:\n"
            "\n"
            "```text\n"
            "SET MODEL\n"
            "text → which tokens / n-grams are present?\n"
            "\n"
            "SEQUENCE MODEL\n"
            "text → which tokens occur, and in what order?\n"
            "```\n"
            "\n"
            "Bag-of-words models are computationally cheap and often excellent "
            "baselines for text classification.\n"
            "\n"

