            '## 11. Pretrained detection with RetinaNet\n'
            '\n'
            'RetinaNet is also a single-stage detector.\n'
            '\n'
            'The chapter uses it to show how a stronger pretrained detector handles objects of different sizes.\n'
            '\n'
            '### The scale problem\n'
            '\n'
            'A deep ConvNet produces features at multiple resolutions.\n'
            '\n'
            'Early features:\n'
            '\n'
            '```text\n'
            'high spatial resolution\n'
            'low semantic abstraction\n'
            '```\n'
            '\n'
            'Late features:\n'
            '\n'
            '```text\n'
            'low spatial resolution\n'
            'high semantic abstraction\n'
            '```\n'
            '\n'
            'This creates a problem.\n'
            '\n'
            'Small objects need high-resolution features.\n'
            '\n'
            'But good object recognition needs high-level semantic features.\n'
            '\n'
            '### Feature Pyramid Network\n'
            '\n'
            'RetinaNet addresses this with a **Feature Pyramid Network (FPN)**.\n'
            '\n'
            'The idea is to combine:\n'
            '\n'
            '```text\n'
            'high-level semantics\n'
            '+\n'
            'high spatial resolution\n'
            '```\n'
            '\n'
            'A simplified flow:\n'
            '\n'
            '```text\n'
            'deep low-resolution features\n'
            '          ↓ upsample\n'
            '          +\n'
            'earlier high-resolution features\n'
            '          ↓\n'
            'multi-scale semantic feature maps\n'
            '```\n'
            '\n'
            'These lateral connections produce strong representations at several spatial scales.\n'
            '\n'
            'The detector can then handle:\n'
            '\n'
            '```text\n'
            'small objects\n'
            'medium objects\n'
            'large objects\n'
            '```\n'
            '\n'
            'more effectively.\n'
            '\n'
            '### Why feature pyramids matter beyond RetinaNet\n'
            '\n'
            'Modern object-detection systems frequently use multi-scale representations.\n'
            '\n'
            'The general principle is:\n'
            '\n'
            '> Do not force every object size to be detected from only one feature-map resolution.\n'
            '\n'
            '### Pretrained detector workflow\n'
            '\n'
            'A high-level pretrained detector typically looks like:\n'
            '\n'
            '```python\n'
            'detector = keras_hub.models.ObjectDetector.from_preset(\n'
            '    "retinanet_resnet50_fpn_v2_coco",\n'
            '    bounding_box_format="rel_xywh",\n'
            ')\n'
            '\n'
            'predictions = detector.predict(images)\n'
            '```\n'
            '\n'
            'The returned structure may contain:\n'
            '\n'
            '```text\n'
            'boxes\n'
            'confidence scores\n'
            'labels\n'
            'number of detections\n'
            '```\n'
            '\n'
            'The model therefore packages much of the complex training and decoding logic behind one inference API.\n'
            '\n'
            '### Out-of-distribution robustness\n'
            '\n'
            'The source demonstrates a pretrained detector on an artistic painting rather than a normal photograph.\n'
            '\n'
            'This illustrates an important advantage of learned high-level visual structure:\n'
            '\n'
            '```text\n'
            'pixels can change dramatically\n'
            'while object-level organization remains recognizable\n'
            '```\n'
            '\n'
            'It does not mean detectors are universally robust, but it shows why semantic feature learning can transfer beyond the exact visual style seen during training.\n'
