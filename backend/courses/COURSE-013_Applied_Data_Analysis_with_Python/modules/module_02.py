            "These correspond to upper and lower triangular regions of a matrix.\n"
            "\n"
            "- `triu()` keeps the upper triangular portion.\n"
            "- `tril()` keeps the lower triangular portion.\n"
            "\n"
            "The source demonstrates using `triu()` to create a Boolean mask for a correlation heatmap:\n"
            "\n"
            "```python\n"
            "import seaborn as sns\n"
            "\n"
            "iris = sns.load_dataset(\"iris\")\n"
            "corr_matrix = iris.corr()\n"
            "\n"
            "mask = np.triu(\n"
            "    np.ones_like(corr_matrix, dtype=bool)\n"
            ")\n"
            "\n"
            "sns.heatmap(\n"
            "    corr_matrix,\n"
            "    mask=mask,\n"
            "    annot=True,\n"
            "    fmt=\".2f\"\n"
            ")\n"
            "```\n"
            "\n"
            "The useful idea is not only matrix triangles.\n"
            "\n"
            "It is that NumPy arrays can be used as **masks** for other libraries.\n"
            "\n"
