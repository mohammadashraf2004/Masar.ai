            "Why does `.sum()` work?\n"
            "\n"
            "Because the null check returns Boolean values:\n"
            "\n"
            "```text\n"
            "True  → missing\n"
            "False → present\n"
            "```\n"
            "\n"
            "and Boolean `True` values can be counted by summation.\n"
            "\n"
            "The result answers:\n"
            "\n"
            "> How many missing values are in each column?\n"
            "\n"
            "---\n"
            "\n"
            "### 15.2 Dropping missing rows\n"
            "\n"
            "```python\n"
            "df.dropna(inplace=True)\n"
            "```\n"
            "\n"
            "This removes rows containing missing values.\n"
            "\n"
            "The chapter's example shows that dropping missing records can reduce the dataset substantially.\n"
            "\n"
            "That teaches an important practical lesson:\n"
            "\n"
            "> Removing missing data is simple, but it may discard a large amount of information.\n"
            "\n"
            "---\n"
            "\n"
            "### 15.3 Filling missing values\n"
            "\n"
            "Example:\n"
            "\n"
            "```python\n"
            "df.fillna(0, inplace=True)\n"
            "```\n"
            "\n"
            "This replaces missing values with `0`.\n"
            "\n"
            "The chapter also mentions filling with measures such as:\n"
            "\n"
            "- mean,\n"
            "- median,\n"
            "- mode.\n"
            "\n"
            "The correct strategy depends on what the missing value means.\n"
            "\n"
            "For example:\n"
            "\n"
            "```text\n"
            "missing revenue ≠ necessarily zero revenue\n"
            "missing age     ≠ automatically average age\n"
            "```\n"
            "\n"
            "So the method is easy; the analytical decision is harder.\n"
