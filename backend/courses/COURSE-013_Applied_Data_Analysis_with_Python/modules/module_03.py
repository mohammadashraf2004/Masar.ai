            "---\n"
            "\n"
            "### 11.1 One-sample t-test\n"
            "\n"
            "Question:\n"
            "\n"
            "> Is the mean of this sample significantly different from a hypothesized value?\n"
            "\n"
            "Source example:\n"
            "\n"
            "```python\n"
            "data = np.array(\n"
            "    [63, 75, 84, 58, 52, 96, 63, 55, 76, 83]\n"
