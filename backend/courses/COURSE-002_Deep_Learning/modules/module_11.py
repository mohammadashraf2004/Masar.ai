            "## 4. Pretraining Embeddings Before Classification\n"
            "\n"
            "Labeled examples are expensive.\n"
            "\n"
            "Raw text is much easier to collect.\n"
            "\n"
            "This creates a powerful idea:\n"
            "\n"
            "> Learn useful language representations from unlabeled text first, "
            "then reuse those representations for the supervised task.\n"
            "\n"
            "This is **pretraining**.\n"
            "\n"
            "### Pretraining versus downstream training\n"
            "\n"
            "Think of the process as two stages.\n"
            "\n"
            "```text\n"
            "STAGE 1 — PRETRAINING\n"
            "\n"
            "large amount of unlabeled text\n"
            "        ↓\n"
            "learn general language representations\n"
            "\n"
            "STAGE 2 — DOWNSTREAM TRAINING\n"
            "\n"
            "smaller labeled dataset\n"
            "        ↓\n"
            "specialize representations for the target task\n"
            "```\n"
            "\n"
            "This general principle eventually became central to modern NLP.\n"
            "\n"
            "### Continuous Bag of Words\n"
            "\n"
            "The chapter demonstrates embedding pretraining with **Continuous "
            "Bag of Words**, or CBOW.\n"
            "\n"
            "The pretraining task is:\n"
            "\n"
            "> Given nearby context words, predict a missing middle word.\n"
            "\n"
            "Suppose we have:\n"
            "\n"
            "```text\n"
            "the movie was surprisingly good and enjoyable\n"
            "```\n"
            "\n"
            "If `good` is hidden, context words around it might help predict it.\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "context:\n"
            "movie, was, surprisingly, and, enjoyable, ...\n"
            "\n"
            "        ↓\n"
            "embedding representations\n"
            "        ↓\n"
            "predict missing token\n"
            "        ↓\n"
            "good\n"
            "```\n"
            "\n"
            "### Why predicting nearby words teaches embeddings\n"
            "\n"
            "Words used in similar contexts tend to have related meanings.\n"
            "\n"
            "For example:\n"
            "\n"
            "```text\n"
            "\"excellent movie\"\n"
            "\"great movie\"\n"
            "\"wonderful movie\"\n"
            "```\n"
            "\n"
            "The words `excellent`, `great`, and `wonderful` occur in similar "
            "contexts.\n"
            "\n"
            "A model that repeatedly predicts words from their contexts can "
            "learn useful geometry in the embedding space.\n"
            "\n"
            "### Creating context windows\n"
            "\n"
            "The chapter uses windows of nine tokens.\n"
            "\n"
            "The middle token becomes the target.\n"
            "\n"
            "The four tokens to the left and four tokens to the right become "
            "the context.\n"
            "\n"
            "```text\n"
            "w1 w2 w3 w4 TARGET w6 w7 w8 w9\n"
            "\n"
            "context =\n"
            "[w1, w2, w3, w4, w6, w7, w8, w9]\n"
            "```\n"
            "\n"
            "### CBOW model\n"
            "\n"
            "The architecture is simple:\n"
            "\n"
            "```python\n"
            "inputs = keras.Input(shape=(8,))\n"
            "\n"
            "embedding = layers.Embedding(\n"
            "    30000,\n"
            "    64,\n"
            ")\n"
            "\n"
            "x = embedding(inputs)\n"
            "x = layers.GlobalAveragePooling1D()(x)\n"
            "outputs = layers.Dense(30000, activation=\"sigmoid\")(x)\n"
            "```\n"
            "\n"
            "The important component is the embedding matrix.\n"
            "\n"
            "The missing-word prediction task exists primarily to force those "
            "embedding vectors to become useful representations of language.\n"
            "\n"
            "### Unsupervised text is valuable\n"
            "\n"
            "The IMDb dataset contains additional unlabeled reviews.\n"
            "\n"
            "They cannot directly train a positive-versus-negative sentiment "
            "classifier because they have no sentiment labels.\n"
            "\n"
            "But they can still train the embedding because CBOW creates its "
            "own learning targets from the text itself.\n"
            "\n"
            "That is a central advantage of self-supervised or unsupervised "
            "pretraining-style tasks:\n"
            "\n"
            "```text\n"
            "raw text itself\n"
            "→ creates training signal\n"
            "```\n"
            "\n"
            "### Transfer the embedding\n"
            "\n"
            "After pretraining, create the sentiment classifier again:\n"
            "\n"
            "```python\n"
            "inputs = keras.Input(shape=(600,))\n"
            "\n"
            "lstm_embedding = layers.Embedding(\n"
            "    input_dim=30000,\n"
            "    output_dim=64,\n"
            "    mask_zero=True,\n"
            ")\n"
            "\n"
            "x = lstm_embedding(inputs)\n"
            "x = layers.Bidirectional(layers.LSTM(64))(x)\n"
            "x = layers.Dropout(0.5)(x)\n"
            "outputs = layers.Dense(1, activation=\"sigmoid\")(x)\n"
            "```\n"
            "\n"
            "Then initialize the new embedding using the pretrained weights:\n"
            "\n"
            "```python\n"
            "lstm_embedding.embeddings.assign(\n"
            "    cbow_embedding.embeddings\n"
            ")\n"
            "```\n"
            "\n"
            "Now the classifier does not begin with random token representations.\n"
            "\n"
            "It begins with embeddings already trained to capture contextual "
            "regularities from additional text.\n"
            "\n"
            "### Effect of embedding pretraining\n"
            "\n"
            "The source reports approximately:\n"
            "\n"
            "```text\n"
            "LSTM + randomly learned embedding\n"
            "≈ 84% test accuracy\n"
            "\n"
            "LSTM + pretrained CBOW embedding\n"
            "≈ 89% test accuracy\n"
            "```\n"
            "\n"
            "This is a substantial improvement.\n"
            "\n"
            "It brings the sequence model close to the strong bigram baseline.\n"
            "\n"
            "### Why doesn't the sequence model clearly dominate yet?\n"
            "\n"
            "Sequence models are more expressive, but they are also more "
            "data-hungry.\n"
            "\n"
            "The model must learn relationships across ordered text, which is "
            "more complicated than learning individual unigram or bigram weights.\n"
            "\n"
            "With only a limited amount of labeled ordered text, the simple "
            "model can still be highly competitive.\n"
            "\n"
            "This leads to a valuable engineering principle:\n"
            "\n"
            "> Always compare sophisticated models with strong simple baselines.\n"
            "\n"
            "### Text augmentation is difficult\n"
            "\n"
            "In computer vision, an image can often be flipped, cropped, or "
            "slightly rotated without changing its class.\n"
            "\n"
            "Language is much more fragile.\n"
            "\n"
            "Changing one word or changing word order can change the sentence's "
            "meaning.\n"
            "\n"
            "For example:\n"
            "\n"
            "```text\n"
            "\"The movie was good.\"\n"
            "```\n"
            "\n"
            "and:\n"
            "\n"
            "```text\n"
            "\"The movie was not good.\"\n"
            "```\n"
            "\n"
            "differ by only one token but have nearly opposite sentiment.\n"
            "\n"
            "Random deletion or word swapping can therefore corrupt labels.\n"
            "\n"
            "This is one reason text augmentation has historically been less "
            "straightforward than image augmentation.\n"
            "\n"
            "### The broader NLP progression\n"
            "\n"
            "This chapter reveals an important progression in NLP modeling:\n"
            "\n"
            "```text\n"
            "RAW TEXT\n"
            "   ↓\n"
            "tokenization\n"
            "   ↓\n"
            "simple set representation\n"
            "   ↓\n"
            "bag of words\n"
            "   ↓\n"
            "n-grams\n"
            "   ↓\n"
            "ordered token sequences\n"
            "   ↓\n"
            "embeddings\n"
            "   ↓\n"
            "sequence model\n"
            "   ↓\n"
            "pretraining\n"
            "```\n"
            "\n"
            "The next major step is the Transformer, which addresses ordered "
            "relationships differently and scales much more effectively to "
            "large amounts of text and compute.\n"
