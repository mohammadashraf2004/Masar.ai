            "## 22. CART and Gini impurity\n"
            "\n"
            "CART stands for:\n"
            "\n"
            "```text\n"
            "Classification and Regression Tree\n"
            "```\n"
            "\n"
            "The chapter describes CART as recursively splitting the data into binary branches.\n"
            "\n"
            "The goal is to create purer child nodes.\n"
            "\n"
            "---\n"
            "\n"
            "### 22.1 Gini impurity\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "Gini\n"
            "=\n"
            "1\n"
            "-\n"
            "Σ pᵢ²\n"
            "```\n"
            "\n"
            "Where:\n"
            "\n"
            "```text\n"
            "pᵢ\n"
            "→ proportion of class i in node\n"
            "```\n"
            "\n"
            "Source example:\n"
            "\n"
            "```text\n"
            "3 Churn\n"
            "2 Not Churn\n"
            "```\n"
            "\n"
            "So:\n"
            "\n"
            "```text\n"
            "p_churn     = 3/5 = 0.6\n"
            "p_notchurn  = 2/5 = 0.4\n"
            "```\n"
            "\n"
            "Gini:\n"
            "\n"
            "```text\n"
            "1 - 0.6² - 0.4²\n"
            "=\n"
            "0.48\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 22.2 Pure node\n"
            "\n"
            "If all samples belong to one class:\n"
            "\n"
            "```text\n"
            "Gini = 0\n"
            "```\n"
            "\n"
            "Lower Gini means greater purity.\n"
            "\n"
            "---\n"
            "\n"
            "### 22.3 Weighted split impurity\n"
            "\n"
            "CART combines child impurity according to child size.\n"
            "\n"
            "A good split produces:\n"
            "\n"
            "```text\n"
            "low weighted impurity\n"
            "```\n"
            "\n"
            "The algorithm chooses the best candidate.\n"
            "\n"
            "---\n"
            "\n"
            "### 22.4 Recursive splitting\n"
            "\n"
            "After one split:\n"
            "\n"
            "```text\n"
            "left child\n"
            "right child\n"
            "```\n"
            "\n"
            "the algorithm repeats the process within each child.\n"
            "\n"
            "---\n"
