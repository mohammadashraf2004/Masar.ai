            "## 3. TPU Training and Keeping Accelerators Busy\n"
            "\n"
            "GPUs are not the only hardware used for deep learning.\n"
            "\n"
            "A **Tensor Processing Unit**, or TPU, is specialized hardware "
            "designed for machine-learning tensor computation.\n"
            "\n"
            "The general principle is the same:\n"
            "\n"
            "> Specialized hardware is useful only when you feed it enough work.\n"
            "\n"
            "### TPU distribution\n"
            "\n"
            "The chapter explains that Keras distribution APIs can also be used "
            "with TPU devices.\n"
            "\n"
            "As with GPU distribution, the distribution configuration should be "
            "set before creating the model.\n"
            "\n"
            "### Data loading can become the bottleneck\n"
            "\n"
            "Suppose a TPU can consume batches extremely quickly.\n"
            "\n"
            "If your storage delivers data slowly, the TPU may sit idle.\n"
            "\n"
            "```text\n"
            "slow storage\n"
            "      ↓\n"
            "waiting\n"
            "      ↓\n"
            "underutilized accelerator\n"
            "```\n"
            "\n"
            "For small enough datasets, caching can help:\n"
            "\n"
            "```python\n"
            "dataset = dataset.cache()\n"
            "```\n"
            "\n"
            "### Batch size and accelerator utilization\n"
            "\n"
            "Large accelerators generally need sufficient batch sizes to reach "
            "high utilization.\n"
            "\n"
            "A tiny batch might not provide enough matrix operations to occupy "
            "all available compute units.\n"
            "\n"
            "### Large batches and learning rate\n"
            "\n"
            "If the batch size grows substantially, the model performs fewer "
            "parameter updates per epoch.\n"
            "\n"
            "But each update is based on more examples and may therefore provide "
            "a more stable gradient estimate.\n"
            "\n"
            "The source notes that larger batches often call for a larger "
            "learning rate.\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "larger batch\n"
            "→ fewer updates\n"
            "→ each gradient uses more samples\n"
            "→ potentially larger useful update step\n"
            "```\n"
            "\n"
            "This is a tuning decision rather than a universal fixed formula.\n"
            "\n"
            "### Step fusing\n"
            "\n"
            "Another approach is to perform several training steps within one "
            "accelerator execution cycle.\n"
            "\n"
            "In Keras:\n"
            "\n"
            "```python\n"
            "model.compile(\n"
            "    ...,\n"
            "    steps_per_execution=8,\n"
            ")\n"
            "```\n"
            "\n"
            "Instead of:\n"
            "\n"
            "```text\n"
            "host ↔ accelerator\n"
            "for every single step\n"
            "```\n"
            "\n"
            "you perform:\n"
            "\n"
            "```text\n"
            "host\n"
            " ↓\n"
            "accelerator runs several steps\n"
            " ↓\n"
            "host\n"
            "```\n"
            "\n"
            "This reduces communication overhead and can improve accelerator "
            "utilization, especially for relatively small models.\n"
