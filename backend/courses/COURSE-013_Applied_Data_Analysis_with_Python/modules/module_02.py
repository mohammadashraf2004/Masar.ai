            "## 17. Working with dates and time\n"
            "\n"
            "Datetime data requires special handling because time contains structure:\n"
            "\n"
            "- year,\n"
            "- month,\n"
            "- day,\n"
            "- hour,\n"
            "- minute,\n"
            "- week,\n"
            "- quarter,\n"
