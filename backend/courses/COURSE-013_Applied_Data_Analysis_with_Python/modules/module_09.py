            "## 24. ID3, entropy, and information gain\n"
            "\n"
            "ID3 is another decision-tree algorithm.\n"
            "\n"
            "Instead of Gini impurity, the chapter uses:\n"
            "\n"
            "```text\n"
            "entropy\n"
            "```\n"
            "\n"
            "and chooses splits through:\n"
            "\n"
            "```text\n"
            "information gain\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 24.1 Entropy\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "Entropy\n"
            "=\n"
            "-Σ pᵢ log₂(pᵢ)\n"
            "```\n"
            "\n"
