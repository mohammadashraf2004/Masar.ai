            "\n"
            "## 4. Measuring dispersion\n"
            "\n"
            "Central tendency alone does not describe the full dataset.\n"
            "\n"
            "Consider:\n"
            "\n"
            "```text\n"
            "Dataset A: 49, 50, 50, 50, 51\n"
            "Dataset B: 10, 30, 50, 70, 90\n"
            "```\n"
            "\n"
            "Both have a center around 50.\n"
            "\n"
            "But their spread is very different.\n"
            "\n"
            "Dispersion measures how observations vary around the center.\n"
            "\n"
            "The chapter teaches:\n"
            "\n"
            "- range,\n"
            "- interquartile range,\n"
            "- variance,\n"
            "- standard deviation.\n"
            "\n"
            "---\n"
            "\n"
            "### 4.1 Range\n"
            "\n"
            "The range is:\n"
            "\n"
            "```text\n"
            "maximum - minimum\n"
            "```\n"
            "\n"
            "Formula:\n"
            "\n"
            "```text\n"
            "Range = max(x) - min(x)\n"
            "```\n"
            "\n"
            "For communication scores:\n"
            "\n"
            "```text\n"
            "max = 45\n"
            "min = 23\n"
            "range = 45 - 23 = 22\n"
            "```\n"
            "\n"
            "Pandas:\n"
            "\n"
            "```python\n"
            "column_range = (\n"
            "    data['communication_skill_score'].max()\n"
            "    -\n"
            "    data['communication_skill_score'].min()\n"
            ")\n"
            "```\n"
            "\n"
            "### Strength\n"
            "\n"
            "Very easy to compute and interpret.\n"
            "\n"
            "### Limitation\n"
            "\n"
            "Uses only the two extreme values.\n"
            "\n"
            "A single extreme outlier can make the range very large.\n"
            "\n"
            "---\n"
            "\n"
            "### 4.2 Interquartile range (IQR)\n"
            "\n"
            "The IQR describes the middle 50% of observations.\n"
            "\n"
            "Formula:\n"
            "\n"
            "```text\n"
            "IQR = Q3 - Q1\n"
            "```\n"
            "\n"
            "where:\n"
            "\n"
            "- `Q1` = 25th percentile,\n"
            "- `Q3` = 75th percentile.\n"
            "\n"
            "Pandas:\n"
            "\n"
            "```python\n"
            "q1 = data['communication_skill_score'].quantile(0.25)\n"
            "q3 = data['communication_skill_score'].quantile(0.75)\n"
            "iqr = q3 - q1\n"
            "```\n"
            "\n"
            "Because it focuses on the middle half of the data, IQR is less dominated by extreme ends.\n"
            "\n"
            "### Mental picture\n"
            "\n"
            "```text\n"
            "min ---- Q1 ===== median ===== Q3 ---- max\n"
            "             <--- IQR --->\n"
            "```\n"
            "\n"
            "IQR is therefore very useful when data contains outliers.\n"
            "\n"
            "---\n"
            "\n"
            "### 4.3 Variance\n"
            "\n"
            "Variance measures average squared deviation from the mean.\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "1. Find the mean\n"
            "2. Find each deviation from the mean\n"
            "3. Square each deviation\n"
            "4. Average the squared deviations\n"
            "```\n"
            "\n"
            "The squaring has two important effects:\n"
            "\n"
            "- negative and positive deviations do not cancel,\n"
            "- large deviations receive more weight.\n"
            "\n"
            "The source example uses:\n"
            "\n"
            "```python\n"
            "data['communication_skill_score'].var()\n"
            "```\n"
            "\n"
            "and obtains:\n"
            "\n"
            "```text\n"
            "69.2\n"
            "```\n"
            "\n"
            "### Main limitation\n"
            "\n"
            "The unit becomes squared.\n"
            "\n"
            "If the original data is in:\n"
            "\n"
            "```text\n"
            "kg\n"
