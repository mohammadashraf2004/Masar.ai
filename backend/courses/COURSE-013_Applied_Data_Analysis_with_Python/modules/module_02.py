            "\n"
            "```python\n"
            "arr[3:]\n"
            "```\n"
            "\n"
            "Output:\n"
            "\n"
            "```text\n"
            "[3 4 5 6 7 8 9]\n"
            "```\n"
            "\n"
            "Leaving the stop blank means:\n"
            "\n"
            "> continue to the end.\n"
            "\n"
            "---\n"
            "\n"
            "### 6.3 Negative indexing\n"
            "\n"
            "```python\n"
            "arr[-3:]\n"
            "```\n"
            "\n"
            "Output:\n"
            "\n"
            "```text\n"
            "[7 8 9]\n"
            "```\n"
            "\n"
            "Negative indexing begins from the right.\n"
            "\n"
            "Memory rule:\n"
            "\n"
            "```text\n"
