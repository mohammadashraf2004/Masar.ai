            "\n"
            "Poor centroid initialization can lead to a less useful local solution.\n"
            "\n"
            "Mitigation:\n"
            "\n"
            "```text\n"
            "K-Means++\n"
            "multiple initializations\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### Scaling\n"
            "\n"
            "Distance is affected by feature magnitude.\n"
            "\n"
            "Therefore:\n"
            "\n"
            "```text\n"
            "standardization is important\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### Must choose K\n"
            "\n"
            "K is not discovered automatically.\n"
            "\n"
            "---\n"
            "\n"
            "### Geometry\n"
            "\n"
            "K-Means works best with compact centroid-like clusters.\n"
            "\n"
            "It can struggle with:\n"
            "\n"
            "- arbitrary shapes,\n"
            "- varying densities.\n"
            "\n"
            "That motivates other clustering methods.\n"
            "\n"
            "---\n"
            "\n"
            "## 19. Hierarchical clustering\n"
            "\n"
            "Hierarchical clustering creates a multi-level cluster structure.\n"
            "\n"
            "The chapter distinguishes:\n"
            "\n"
            "```text\n"
            "Agglomerative\n"
            "→ bottom-up merging\n"
            "\n"
            "Divisive\n"
            "→ top-down splitting\n"
            "```\n"
            "\n"
            "It focuses on:\n"
            "\n"
            "```text\n"
            "agglomerative clustering\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 19.1 Agglomerative idea\n"
            "\n"
            "Start with:\n"
            "\n"
            "```text\n"
            "each point\n"
            "=\n"
            "its own cluster\n"
            "```\n"
            "\n"
            "Then repeatedly merge the closest clusters.\n"
            "\n"
            "Eventually:\n"
            "\n"
            "```text\n"
            "all points\n"
            "→ one root cluster\n"
            "```\n"
            "\n"
            "The full merging history forms a:\n"
            "\n"
            "```text\n"
            "dendrogram\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "## 20. Reading a dendrogram\n"
            "\n"
            "A dendrogram is a tree-like visualization of cluster merges.\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "leaves\n"
            "→ individual observations / small clusters\n"
            "\n"
            "branches\n"
            "→ merges\n"
            "\n"
            "height\n"
            "→ merge distance / dissimilarity\n"
            "\n"
            "root\n"
            "→ all observations joined\n"
            "```\n"
            "\n"
            "Unlike K-Means, the full hierarchy can be built without selecting K first.\n"
            "\n"
            "You can later choose a cut height to define clusters.\n"
            "\n"
            "[[IMAGE_NEEDED: Agglomerative dendrogram anatomy | Dendrogram with leaves, merge branches, distance axis, horizontal cut line, and resulting clusters colored | Learner should understand that cluster count comes from where the tree is cut]]\n"
            "\n"
            "---\n"
            "\n"
            "## 21. Distance and linkage\n"
            "\n"
            "Hierarchical clustering requires deciding how to measure distance between clusters.\n"
            "\n"
            "The chapter first describes:\n"
            "\n"
            "```text\n"
            "single linkage\n"
            "```\n"
            "\n"
            "Single linkage uses:\n"
            "\n"
            "```text\n"
            "shortest distance\n"
            "between any two points\n"
            "from the two clusters\n"
            "```\n"
            "\n"
            "The source implementation later uses:\n"
            "\n"
            "```python\n"
            "linked = linkage(\n"
            "    X_scaled,\n"
            "    method='ward'\n"
            ")\n"
            "```\n"
            "\n"
            "Ward linkage is therefore the actual method used in its Python dendrogram example.\n"
            "\n"
            "---\n"
            "\n"
            "### 21.1 Extracting clusters\n"
            "\n"
            "After examining the dendrogram:\n"
            "\n"
            "```python\n"
            "cluster_labels = fcluster(\n"
            "    linked,\n"
            "    t=3,\n"
            "    criterion='maxclust'\n"
            ")\n"
            "```\n"
            "\n"
            "This creates three cluster labels.\n"
            "\n"
            "The hierarchy is built first.\n"
            "\n"
            "The desired number of clusters can be selected afterward.\n"
            "\n"
            "---\n"
            "\n"
            "## 22. DBSCAN\n"
            "\n"
            "DBSCAN stands for:\n"
            "\n"
            "```text\n"
            "Density-Based Spatial Clustering\n"
            "of Applications with Noise\n"
            "```\n"
            "\n"
            "It defines clusters through density rather than centroids.\n"
            "\n"
            "This makes DBSCAN useful for:\n"
            "\n"
            "- irregular shapes,\n"
            "- separated dense regions,\n"
            "- explicit noise points.\n"
            "\n"
            "The chapter contrasts it with K-Means and hierarchical clustering on shapes such as:\n"
            "\n"
            "- moons,\n"
            "- circles,\n"
            "- blobs.\n\n{{image:clustering-shapes}}\n"
            "\n"
            "---\n"
            "\n"
            "## 23. Epsilon and MinPts\n"
            "\n"
            "DBSCAN requires two central parameters.\n"
            "\n"
            "### Epsilon (`eps`)\n"
            "\n"
            "Neighborhood radius.\n"
            "\n"
            "Two points can be considered neighbors if they are sufficiently close within the radius.\n"
            "\n"
            "---\n"
            "\n"
            "### MinPts / `min_samples`\n"
            "\n"
            "Minimum number of points needed in the epsilon neighborhood for a point to be considered part of a dense region.\n"
            "\n"
            "---\n"
            "\n"
            "### 23.1 Core point\n"
            "\n"
            "If its neighborhood contains at least the required number of points:\n"
            "\n"
            "```text\n"
            "core point\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 23.2 Border point\n"
            "\n"
            "Not dense enough to be a core point, but reachable from a core point.\n"
            "\n"
            "---\n"
            "\n"
            "### 23.3 Noise\n"
            "\n"
            "Not density-reachable from a valid cluster.\n"
            "\n"
            "In scikit-learn output:\n"
            "\n"
            "```text\n"
            "label = -1\n"
            "→ noise\n"
            "```\n"
            "\n"
            "[[IMAGE_NEEDED: DBSCAN point types | Dense cluster with epsilon circle around a core point, nearby border point, and distant noise point, labeled core/border/noise | Learner should understand eps and MinPts geometrically]]\n"
            "\n"
            "---\n"
            "\n"
            "## 24. How DBSCAN grows clusters\n"
            "\n"
            "The source describes this recursive process:\n"
            "\n"
            "```text\n"
            "choose point\n"
            "     ↓\n"
            "inspect epsilon neighborhood\n"
            "     ↓\n"
            "enough points?\n"
            "     ↓ yes\n"
            "core point\n"
            "     ↓\n"
            "start/expand cluster\n"
            "     ↓\n"
            "visit reachable neighbors\n"
            "     ↓\n"
            "expand while new core points exist\n"
            "```\n"
            "\n"
            "Unlike K-Means:\n"
            "\n"
            "```text\n"
            "no centroid\n"
            "no fixed K required\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
