            "## Important misconceptions\n"
            "\n"
            "### Misconception 1\n"
            "\n"
            "> A convolutional layer learns a completely different detector "
            "for every image position.\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "The same convolution kernel is reused across spatial positions. "
            "This parameter sharing is one reason ConvNets can recognize a "
            "learned pattern in different parts of an image.\n"
            "\n"
            "### Misconception 2\n"
            "\n"
            "> Max pooling learns its own weight parameters.\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "Max pooling applies a fixed maximum operation to local regions. "
            "Unlike convolution, it does not learn a convolution kernel.\n"
            "\n"
            "### Misconception 3\n"
            "\n"
            "> Data augmentation creates entirely new independent information.\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "Augmentation generates useful variations of existing examples, "
            "but those examples remain correlated with the original data. "
            "It cannot fully replace collecting genuinely new images.\n"
            "\n"
            "### Misconception 4\n"
            "\n"
            "> When using a pretrained model, all layers should immediately be "
            "trained together with the new classifier.\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "The new classifier begins randomly initialized. Large early "
            "updates can damage pretrained representations. The usual sequence "
            "is to freeze the backbone, train the new classifier, and only "
            "then fine-tune appropriate pretrained layers.\n"
            "\n"
            "### Misconception 5\n"
            "\n"
            "> Fine-tuning should use a large learning rate so the pretrained "
            "model can quickly learn the new task.\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "Fine-tuning is meant to make small adjustments to already useful "
            "representations. Large parameter updates can destroy those "
            "representations.\n"
            "\n"
            "### Misconception 6\n"
            "\n"
            "> Residual connections are only useful because they add more "
            "parameters.\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "The core purpose of residual connections is to provide an "
            "information and gradient shortcut around processing blocks, "
            "making deeper networks easier to optimize.\n"
            "\n"
            "### Misconception 7\n"
            "\n"
            "> A lower theoretical FLOP count always guarantees proportionally "
            "faster execution on a GPU.\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "Actual runtime also depends on implementation quality, memory "
            "behavior, hardware, and how well specific operations have been "
            "optimized by the underlying software stack.\n"
            "\n"
