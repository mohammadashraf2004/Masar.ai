            "## 12. Extremely Randomized Trees (Extra Trees)\n"
            "\n"
            "Extra Trees increases randomness beyond Random Forest.\n"
            "\n"
            "The source highlights two main differences.\n"
            "\n"
            "---\n"
            "\n"
            "### 12.1 Bootstrap behavior\n"
            "\n"
            "Random Forest commonly:\n"
            "\n"
            "```text\n"
            "uses bootstrap samples\n"
            "```\n"
            "\n"
            "Extra Trees commonly:\n"
            "\n"
            "```text\n"
            "uses the full dataset\n"
            "without bootstrap\n"
            "```\n"
            "\n"
            "unless bootstrapping is explicitly enabled.\n"
            "\n"
            "---\n"
            "\n"
            "### 12.2 Split thresholds\n"
            "\n"
            "Random Forest:\n"
            "\n"
            "```text\n"
            "searches candidate split thresholds\n"
            "and picks a strong split\n"
            "```\n"
            "\n"
