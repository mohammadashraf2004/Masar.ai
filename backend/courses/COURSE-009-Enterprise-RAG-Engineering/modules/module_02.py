                       '## 32. Vector similarity: dot product and cosine similarity\n'
                       '\n'
                       'A retriever needs a numerical rule for deciding which stored vectors are '
                       'closest to a query.\n'
                       '\n'
                       'A common operation is the **dot product**:\n'
                       '\n'
                       '```text\n'
                       'a · b = Σ aᵢbᵢ\n'
                       '```\n'
                       '\n'
                       'If vectors are normalized to magnitude 1, the dot product is equivalent to '
                       'cosine similarity. Cosine similarity focuses on the angle between vectors '
                       'rather than their absolute magnitude.\n'
                       '\n'
                       'For normalized embeddings:\n'
                       '\n'
                       '```text\n'
                       'same direction     → high similarity\n'
                       'different direction → lower similarity\n'
                       '```\n'
                       '\n'
                       'This gives semantic search a fast mathematical primitive.\n'
                       '\n'
                       'Be careful with database operators: some systems expose a **distance** '
                       'rather than a similarity. A smaller cosine distance means closer vectors. '
                       'If you want a similarity-style score, you may need to convert the value. '
                       'The pgvector example later uses this distinction explicitly.\n'
                       '\n'
