            "---\n"
            "\n"
            "## 56. Otsu thresholding for contour masks\n"
            "\n"
            "Source:\n"
            "\n"
            "```python\n"
            "_, mask = cv2.threshold(\n"
            "    gray_u8,\n"
            "    0,\n"
            "    255,\n"
