            "## 25. Evaluating clustering\n"
            "\n"
            "Because no class labels are normally available, the chapter uses internal clustering metrics:\n"
            "\n"
            "```text\n"
            "Silhouette Coefficient\n"
            "Calinski-Harabasz Index\n"
            "Davies-Bouldin Index\n"
            "```\n"
            "\n"
            "They assess cluster geometry rather than classification accuracy.\n"
            "\n"
            "---\n"
            "\n"
            "## 26. Silhouette coefficient\n"
            "\n"
            "Silhouette compares:\n"
            "\n"
            "```text\n"
            "within-cluster closeness\n"
            "vs\n"
            "nearest-other-cluster distance\n"
            "```\n"
            "\n"
            "Range:\n"
            "\n"
            "```text\n"
            "-1 to 1\n"
            "```\n"
            "\n"
            "Source interpretation:\n"
            "\n"
            "```text\n"
            "near 1\n"
            "→ compact and separated\n"
            "\n"
            "near 0\n"
            "→ overlap / weak structure\n"
            "\n"
            "negative\n"
            "→ likely poor assignment\n"
            "```\n"
            "\n"
            "Source example:\n"
            "\n"
            "```text\n"
            "0.2615\n"
            "```\n"
            "\n"
            "The chapter notes it is positive and therefore indicates some separation.\n"
            "\n"
            "A positive score alone does not imply very strong clustering; its magnitude still matters.\n"
            "\n"
            "---\n"
            "\n"
            "## 27. Calinski–Harabasz index\n"
            "\n"
            "The Calinski–Harabasz index compares:\n"
            "\n"
            "```text\n"
            "between-cluster dispersion\n"
            "to\n"
            "within-cluster dispersion\n"
            "```\n"
            "\n"
            "Interpretation:\n"
            "\n"
            "```text\n"
            "higher\n"
            "→ better separation/compactness\n"
            "```\n"
            "\n"
            "The source warns that there is no fixed maximum.\n"
            "\n"
            "Therefore it is most useful for:\n"
            "\n"
            "```text\n"
            "comparing candidate clusterings\n"
            "```\n"
            "\n"
            "rather than interpreting one number universally.\n"
            "\n"
            "---\n"
            "\n"
            "## 28. Davies–Bouldin index\n"
            "\n"
            "Davies–Bouldin compares each cluster's scatter with its separation from the most similar competing cluster.\n"
            "\n"
            "Interpretation:\n"
            "\n"
            "```text\n"
            "lower\n"
            "→ better\n"
            "```\n"
            "\n"
            "A smaller value means:\n"
            "\n"
            "- tighter clusters,\n"
            "- better separation.\n"
            "\n"
            "Again, it is most useful comparatively.\n"
            "\n"
            "---\n"
            "\n"
            "### 28.1 Metric direction summary\n"
            "\n"
            "| Metric | Better direction |\n"
            "|---|---|\n"
            "| Silhouette | higher |\n"
            "| Calinski–Harabasz | higher |\n"
            "| Davies–Bouldin | lower |\n"
            "\n"
