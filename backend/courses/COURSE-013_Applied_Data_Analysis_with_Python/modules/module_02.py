            "    '01-01-2000',\n"
            "    periods=45,\n"
            "    freq='D'\n"
            ")\n"
            "```\n"
            "\n"
            "This creates 45 daily timestamps beginning January 1, 2000.\n"
            "\n"
            "The important parameters are:\n"
            "\n"
            "```text\n"
            "start   → first date/time\n"
            "periods → how many timestamps\n"
            "freq    → spacing between timestamps\n"
