            "## 30. TF-IDF\n"
            "\n"
            "Bag-of-Words counts presence/frequency.\n"
            "\n"
            "TF-IDF also asks:\n"
            "\n"
            "> Is this term distinctive across the corpus?\n"
            "\n"
            "TF-IDF combines:\n"
            "\n"
            "```text\n"
            "Term Frequency\n"
            "×\n"
            "Inverse Document Frequency\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "## 31. Term Frequency (TF)\n"
            "\n"
            "TF reflects how strongly a term appears inside one document.\n"
            "\n"
            "The source notes that TF may use:\n"
            "\n"
            "- raw frequency,\n"
            "- sublinear scaling such as `1 + log(count)`.\n"
            "\n"
            "High TF:\n"
            "\n"
            "```text\n"
            "term is frequent in this document\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "## 32. Inverse Document Frequency (IDF)\n"
            "\n"
            "IDF reduces the importance of terms that occur in many documents.\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "rare across corpus\n"
            "→ higher IDF\n"
            "\n"
            "common everywhere\n"
            "→ lower IDF\n"
            "```\n"
            "\n"
            "So a term can receive high TF-IDF when it is:\n"
            "\n"
            "```text\n"
            "frequent in one document\n"
            "but uncommon across the corpus\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
