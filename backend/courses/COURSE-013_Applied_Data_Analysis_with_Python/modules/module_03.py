            "## 7. Central Limit Theorem\n"
            "\n"
            "The chapter now moves from descriptive statistics to inferential statistics.\n"
            "\n"
            "The key problem becomes:\n"
            "\n"
            "> We usually cannot measure an entire population. How can a sample tell us something about it?\n"
            "\n"
            "The Central Limit Theorem (CLT) is introduced as a bridge.\n"
            "\n"
            "The chapter states that as sample size increases, the sampling distribution tends toward a normal shape and sample estimates become more stable around population behavior.\n"
            "\n"
            "The important mental model is:\n"
            "\n"
            "```text\n"
            "Population\n"
            "   ↓ repeated random samples\n"
            "Sample means\n"
            "   ↓\n"
            "Sampling distribution\n"
            "   ↓ as sample size grows\n"
            "more stable / increasingly normal-like\n"
            "```\n"
            "\n"
            "### Why this matters\n"
            "\n"
            "Many inferential procedures rely on the behavior of sampling distributions.\n"
            "\n"
            "The chapter illustrates sample sizes such as:\n"
            "\n"
            "```text\n"
            "50\n"
            "100\n"
            "200\n"
            "500\n"
            "```\n"
            "\n"
            "with distributions becoming smoother and more normal-like as size increases.\n"
            "\n"
            "### Important distinction\n"
            "\n"
            "Do not confuse:\n"
            "\n"
            "```text\n"
            "distribution of raw observations\n"
            "```\n"
            "\n"
            "with:\n"
            "\n"
            "```text\n"
            "sampling distribution of a statistic such as the sample mean\n"
            "```\n"
            "\n"
            "The CLT is fundamentally about the behavior of a statistic across repeated samples.\n"
            "\n"
            "### Source note\n"
            "\n"
            "The chapter says “all statistical tests assume the population is normally distributed,” but later explicitly teaches distribution-free non-parametric tests. Those two statements are internally inconsistent. For this lesson, treat the CLT as important for many inferential methods, not as evidence that every statistical test requires a normal population.\n"
