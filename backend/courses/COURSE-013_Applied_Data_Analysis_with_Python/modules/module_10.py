            "## 40. Evaluating anomaly detection without labels\n"
            "\n"
            "In many anomaly problems:\n"
            "\n"
            "```text\n"
            "ground truth is absent\n"
            "```\n"
            "\n"
            "The chapter therefore introduces score-based evaluation ideas.\n"
            "\n"
            "It focuses on:\n"
            "\n"
            "```text\n"
