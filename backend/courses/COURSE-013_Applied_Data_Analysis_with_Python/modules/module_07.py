            "## 8. Mean, median, and mode imputation\n"
            "\n"
            "The chapter introduces central-tendency imputation.\n"
            "\n"
            "For numeric columns:\n"
            "\n"
            "```python\n"
            "customers_ct['Age'] = (\n"
            "    customers_ct['Age']\n"
            "    .fillna(\n"
            "        customers_ct['Age']\n"
            "        .mean()\n"
            "    )\n"
            ")\n"
            "```\n"
            "\n"
            "Median:\n"
            "\n"
            "```python\n"
            "customers_ct[\n"
            "    'PurchaseCount'\n"
            "] = (\n"
            "    customers_ct[\n"
            "        'PurchaseCount'\n"
            "    ]\n"
            "    .fillna(\n"
            "        customers_ct[\n"
            "            'PurchaseCount'\n"
            "        ].median()\n"
            "    )\n"
            ")\n"
            "```\n"
            "\n"
            "Categorical mode:\n"
            "\n"
            "```python\n"
            "customers_ct[\n"
            "    'Country'\n"
            "] = (\n"
            "    customers_ct[\n"
            "        'Country'\n"
            "    ]\n"
            "    .fillna(\n"
            "        customers_ct[\n"
            "            'Country'\n"
            "        ].mode()[0]\n"
            "    )\n"
            ")\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 8.1 Why the statistic depends on the variable\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "numeric\n"
            "→ mean or median\n"
            "\n"
            "categorical\n"
            "→ mode\n"
            "```\n"
            "\n"
            "A category does not have a meaningful arithmetic average.\n"
            "\n"
            "---\n"
            "\n"
            "### 8.2 Risk: reduced variance\n"
            "\n"
            "The source gives an important warning.\n"
            "\n"
            "If many missing observations are replaced with the exact same mean:\n"
            "\n"
            "```text\n"
            "repeated identical values ↑\n"
            "spread ↓\n"
            "variance ↓\n"
            "standard deviation ↓\n"
            "```\n"
            "\n"
            "That can make the data appear more concentrated than it really is.\n"
            "\n"
            "So simple imputation is convenient but not neutral.\n"
            "\n"
            "---\n"
