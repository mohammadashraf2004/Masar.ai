            "\n"
            "Sample mean:\n"
            "\n"
            "```python\n"
            "np.mean(data)\n"
            "```\n"
            "\n"
            "Output:\n"
            "\n"
            "```text\n"
            "70.5\n"
            "```\n"
            "\n"
            "Hypotheses:\n"
            "\n"
            "```text\n"
            "H₀: μ = 68\n"
            "Hₐ: μ ≠ 68\n"
            "```\n"
            "\n"
            "Test:\n"
            "\n"
            "```python\n"
