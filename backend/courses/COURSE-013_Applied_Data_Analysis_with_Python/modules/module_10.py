            "```\n"
            "\n"
            "PCA is then used only to visualize the high-dimensional clusters in 2D.\n"
            "\n"
            "Important distinction:\n"
            "\n"
            "```text\n"
            "K-Means clustering\n"
            "→ performed in standardized original feature space\n"
            "\n"
