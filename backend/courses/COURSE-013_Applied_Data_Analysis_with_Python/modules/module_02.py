            "## 4. Stacking and splitting arrays\n"
            "\n"
            "Often, data arrives in separate arrays and must be combined.\n"
            "\n"
            "At other times, a large array must be divided into smaller pieces.\n"
            "\n"
            "NumPy provides both operations.\n"
            "\n"
            "---\n"
            "\n"
            "### 4.1 Horizontal stacking\n"
            "\n"
            "Create:\n"
            "\n"
            "```python\n"
            "arr1 = np.arange(1, 10).reshape(3, 3)\n"
            "arr2 = 2 * arr1\n"
            "```\n"
            "\n"
            "`arr1`:\n"
            "\n"
            "```text\n"
            "[[1 2 3]\n"
            " [4 5 6]\n"
            " [7 8 9]]\n"
            "```\n"
            "\n"
            "`arr2`:\n"
            "\n"
            "```text\n"
            "[[ 2  4  6]\n"
            " [ 8 10 12]\n"
            " [14 16 18]]\n"
            "```\n"
            "\n"
            "Horizontal stacking:\n"
            "\n"
            "```python\n"
            "np.hstack((arr1, arr2))\n"
            "```\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "arr1 columns | arr2 columns\n"
            "```\n"
            "\n"
            "Output:\n"
            "\n"
            "```text\n"
            "[[ 1  2  3  2  4  6]\n"
            " [ 4  5  6  8 10 12]\n"
            " [ 7  8  9 14 16 18]]\n"
            "```\n"
            "\n"
            "You can express the same idea with:\n"
            "\n"
            "```python\n"
            "np.concatenate((arr1, arr2), axis=1)\n"
            "```\n"
            "\n"
            "Here:\n"
            "\n"
            "```text\n"
            "axis=1 → combine across columns\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 4.2 Vertical stacking\n"
            "\n"
            "```python\n"
            "np.vstack((arr1, arr2))\n"
            "```\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "arr1 rows\n"
            "arr2 rows\n"
            "```\n"
            "\n"
            "Equivalent concatenation:\n"
            "\n"
            "```python\n"
            "np.concatenate((arr1, arr2), axis=0)\n"
            "```\n"
            "\n"
            "Here:\n"
            "\n"
            "```text\n"
            "axis=0 → combine across rows\n"
            "```\n"
            "\n"
            "A very useful memory rule is:\n"
            "\n"
            "```text\n"
            "axis 0 → row direction\n"
            "axis 1 → column direction\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 4.3 Depth stacking\n"
            "\n"
            "```python\n"
            "np.dstack((arr1, arr2))\n"
            "```\n"
            "\n"
            "Depth stacking combines arrays along a third axis.\n"
            "\n"
            "This is useful when the first two dimensions represent rows and columns and you want a third “layer” or “channel.”\n"
            "\n"
            "---\n"
            "\n"
            "### 4.4 Column stacking\n"
            "\n"
            "For one-dimensional arrays:\n"
            "\n"
