            "## 4. Bagging\n"
            "\n"
            "Bagging stands for:\n"
            "\n"
            "```text\n"
            "Bootstrap Aggregating\n"
            "```\n"
            "\n"
            "The source describes it as:\n"
            "\n"
            "```text\n"
            "train many copies of a base learner\n"
            "on different resampled versions of training data\n"
            "then aggregate predictions\n"
            "```\n"
            "\n"
            "The models are trained independently.\n"
            "\n"
            "That independence means training can often happen in parallel.\n"
            "\n"
            "---\n"
            "\n"
            "### 4.1 Why bagging works\n"
            "\n"
            "If each model sees a slightly different training sample:\n"
            "\n"
            "```text\n"
            "model errors differ\n"
            "```\n"
            "\n"
            "Aggregation then smooths the individual variation.\n"
            "\n"
            "This is why bagging is strongly associated with:\n"
            "\n"
            "```text\n"
            "variance reduction\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "## 5. Bootstrap sampling\n"
            "\n"
            "Bootstrapping creates new datasets by sampling:\n"
            "\n"
            "```text\n"
            "with replacement\n"
            "```\n"
            "\n"
            "Suppose the original data is:\n"
            "\n"
            "```text\n"
            "[A, B, C, D, E]\n"
            "```\n"
            "\n"
            "One bootstrap sample might be:\n"
            "\n"
            "```text\n"
            "[A, C, C, E, B]\n"
            "```\n"
            "\n"
            "Another:\n"
            "\n"
            "```text\n"
            "[D, D, A, E, C]\n"
            "```\n"
            "\n"
            "Each sample can:\n"
            "\n"
            "- repeat rows,\n"
            "- omit other rows,\n"
            "- remain the same size as the original training set.\n"
            "\n"
            "---\n"
            "\n"
            "### 5.1 Python example\n"
            "\n"
            "The source uses:\n"
            "\n"
            "```python\n"
            "from sklearn.utils import (\n"
            "    resample\n"
            ")\n"
            "\n"
            "data = [\n"
            "    2, 3, 5, 7, 11\n"
            "]\n"
            "\n"
            "bootstrap_sample = (\n"
            "    resample(\n"
            "        data\n"
            "    )\n"
            ")\n"
            "```\n"
            "\n"
            "Running again may produce a different bootstrap sample.\n"
            "\n"
            "---\n"
            "\n"
            "### 5.2 Why duplicates are expected\n"
            "\n"
            "Sampling with replacement means:\n"
            "\n"
            "```text\n"
            "after selecting one observation\n"
            "it remains available\n"
            "for another draw\n"
            "```\n"
            "\n"
            "So duplicates are not errors.\n"
            "\n"
            "They are part of the bootstrap design.\n"
            "\n"
