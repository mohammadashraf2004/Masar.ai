            "Model 3 ─┘\n"
            "```\n"
            "\n"
            "The chapter's intuition is that different models often make different mistakes.\n"
            "\n"
            "If errors are not perfectly aligned, aggregation can reduce the impact of any one model's mistake.\n"
            "\n"
            "This can improve:\n"
            "\n"
            "- stability,\n"
            "- generalization,\n"
            "- predictive performance.\n"
            "\n"
            "---\n"
            "\n"
            "### 1.1 Ensemble does not automatically mean “better”\n"
            "\n"
            "Combining poor or highly correlated models may add complexity without much benefit.\n"
            "\n"
            "The ensemble should create:\n"
            "\n"
            "```text\n"
            "useful diversity\n"
            "```\n"
            "\n"
            "among base learners.\n"
            "\n"
            "Diversity can come from:\n"
            "\n"
            "- different training samples,\n"
            "- different feature subsets,\n"
            "- different model families,\n"
            "- different sequential error focus.\n"
            "\n"
            "That idea connects every method in this chapter.\n"
