            "## 32. Root Mean Squared Error (RMSE)\n"
            "\n"
            "RMSE squares errors before averaging.\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "RMSE\n"
            "=\n"
            "sqrt(\n"
            "    average(\n"
            "        error²\n"
            "    )\n"
            ")\n"
            "```\n"
            "\n"
            "Because errors are squared:\n"
            "\n"
            "```text\n"
            "large errors\n"
            "→ receive more penalty\n"
            "```\n"
            "\n"
            "This makes RMSE useful when large misses are especially undesirable.\n"
            "\n"
            "The chapter also warns that this sensitivity can make RMSE strongly influenced by outliers.\n"
            "\n"
            "### Source consistency note\n"
            "\n"
            "The supplied source says the RMSE result has a different unit from the original data. That statement is inconsistent with the mathematical definition shown: **RMSE is returned in the same unit as the target because the square root reverses the squared unit**. Since the user's instruction is to preserve source framing unless asked to correct it, this lesson flags the inconsistency instead of silently replacing it.\n"
            "\n"
