            "## 6. Scaled dot-product attention\n"
            "\n"
            "The chapter presents attention as:\n"
            "\n"
            "```text\n"
            "Attention(Q, K, V)\n"
            "=\n"
            "softmax(\n"
            "    QKᵀ / √dₖ\n"
            ")\n"
            "V\n"
            "```\n"
            "\n"
            "Break the formula into steps.\n"
            "\n"
            "### Step 1 — Similarity\n"
            "\n"
            "```text\n"
            "QKᵀ\n"
            "```\n"
            "\n"
            "measures how well each query aligns with the keys.\n"
            "\n"
            "### Step 2 — Scale\n"
            "\n"
            "```text\n"
            "divide by √dₖ\n"
            "```\n"
            "\n"
            "so raw dot products do not become excessively large as vector dimension grows.\n"
            "\n"
            "### Step 3 — Normalize\n"
            "\n"
            "```text\n"
            "softmax\n"
            "```\n"
            "\n"
            "turns scores into weights that sum to 1 across each query row.\n"
            "\n"
            "### Step 4 — Mix information\n"
            "\n"
            "```text\n"
            "attention weights × V\n"
            "```\n"
            "\n"
            "creates a new context-aware representation.\n"
            "\n"
            "[[IMAGE_NEEDED: Scaled dot-product attention | Q and K matrices form score matrix, divide by sqrt(dk), softmax creates attention weights, weights multiply V to create output | Learner should understand each operation in the attention formula]]\n"
            "\n"
            "---\n"
            "\n"
            "## 7. Attention in NumPy\n"
            "\n"
            "The source implements:\n"
            "\n"
            "```python\n"
            "import numpy as np\n"
            "\n"
            "def softmax(x):\n"
            "    exp_x = np.exp(\n"
            "        x\n"
            "        -\n"
            "        np.max(\n"
            "            x,\n"
            "            axis=-1,\n"
            "            keepdims=True\n"
            "        )\n"
            "    )\n"
            "\n"
            "    return (\n"
            "        exp_x\n"
            "        /\n"
            "        exp_x.sum(\n"
            "            axis=-1,\n"
            "            keepdims=True\n"
            "        )\n"
            "    )\n"
            "```\n"
            "\n"
            "Then:\n"
            "\n"
            "```python\n"
            "def scaled_dot_product_attention(\n"
            "    Q,\n"
            "    K,\n"
            "    V\n"
            "):\n"
            "    d_k = Q.shape[-1]\n"
            "\n"
            "    scores = (\n"
            "        np.matmul(\n"
            "            Q,\n"
            "            K.T\n"
            "        )\n"
            "        /\n"
            "        np.sqrt(d_k)\n"
            "    )\n"
            "\n"
            "    weights = softmax(\n"
            "        scores\n"
            "    )\n"
            "\n"
            "    output = np.matmul(\n"
            "        weights,\n"
            "        V\n"
            "    )\n"
            "\n"
            "    return (\n"
            "        output,\n"
            "        weights\n"
            "    )\n"
            "```\n"
            "\n"
            "This small implementation exposes the core mechanics clearly.\n"
            "\n"
