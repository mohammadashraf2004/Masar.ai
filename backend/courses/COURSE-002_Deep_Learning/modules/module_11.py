            "## 1. Turning Human Language into Numbers\n"
            "\n"
            "Neural networks operate on numerical tensors.\n"
            "\n"
            "But text begins as strings:\n"
            "\n"
            "```text\n"
            "The quick brown fox jumped over the lazy dog.\n"
            "```\n"
            "\n"
            "A neural network cannot directly multiply this sentence by a "
            "weight matrix.\n"
            "\n"
            "Before modeling text, we therefore need a transformation:\n"
            "\n"
            "```text\n"
            "Raw text\n"
            "   ↓\n"
            "tokens\n"
            "   ↓\n"
            "token IDs\n"
            "   ↓\n"
            "numeric representation\n"
            "   ↓\n"
            "machine learning model\n"
            "```\n"
            "\n"
            "This numerical preprocessing is fundamental to natural language "
            "processing, or **NLP**.\n"
            "\n"
            "### What is NLP?\n"
            "\n"
            "Natural language processing applies computational techniques to "
            "human language.\n"
            "\n"
            "Examples include:\n"
            "\n"
            "```text\n"
            "Email → spam probability\n"
            "\n"
            "English sentence → translated sentence\n"
            "\n"
            "Incomplete sentence → likely next word\n"
            "\n"
            "Movie review → positive / negative sentiment\n"
            "```\n"
            "\n"
            "Modern NLP models generally learn statistical regularities from "
            "large amounts of text instead of depending entirely on manually "
            "written grammar rules.\n"
            "\n"
            "### The three stages of tokenization\n"
            "\n"
            "The preprocessing pipeline in this chapter can be understood as:\n"
            "\n"
            "```text\n"
            "1. STANDARDIZATION\n"
            "       ↓\n"
            "2. SPLITTING\n"
            "       ↓\n"
            "3. INDEXING\n"
            "```\n"
            "\n"
            "People often use the word **tokenization** for this overall process.\n"
            "\n"
            "### Stage 1: Standardization\n"
            "\n"
            "Text can contain many superficial differences.\n"
            "\n"
            "For example:\n"
            "\n"
            "```text\n"
            "Movie\n"
            "movie\n"
            "MOVIE\n"
            "```\n"
            "\n"
            "A simple tokenizer might initially treat these as three distinct "
            "tokens.\n"
            "\n"
            "Standardization attempts to remove differences that we do not want "
            "the model to learn independently.\n"
            "\n"
            "A simple standardization strategy could include:\n"
            "\n"
            "```text\n"
            "convert to lowercase\n"
            "remove selected punctuation\n"
            "normalize character encoding\n"
            "```\n"
            "\n"
            "For example:\n"
            "\n"
            "```text\n"
            "\"This Movie Is GREAT!\"\n"
            "          ↓\n"
            "\"this movie is great\"\n"
            "```\n"
            "\n"
            "However, aggressive normalization can remove useful information.\n"
            "\n"
            "Word tense, punctuation, capitalization, and morphology can carry "
            "meaning, so larger modern models often use relatively light "
            "standardization.\n"
            "\n"
            "### Stage 2: Splitting\n"
            "\n"
            "Splitting converts a string into smaller units called **tokens**.\n"
            "\n"
            "There are several possible token units.\n"
            "\n"
            "#### Character tokens\n"
            "\n"
            "```text\n"
            "\"cat\"\n"
            " ↓\n"
            "[\"c\", \"a\", \"t\"]\n"
            "```\n"
            "\n"
            "#### Word tokens\n"
            "\n"
            "```text\n"
            "\"the quick fox\"\n"
            " ↓\n"
            "[\"the\", \"quick\", \"fox\"]\n"
            "```\n"
            "\n"
            "#### Subword tokens\n"
            "\n"
            "A word may be divided into reusable pieces:\n"
            "\n"
            "```text\n"
            "\"unbelievable\"\n"
            " ↓\n"
            "[\"un\", \"believ\", \"able\"]\n"
            "```\n"
            "\n"
            "The exact pieces depend on the tokenizer vocabulary and algorithm.\n"
            "\n"
            "### Stage 3: Indexing\n"
            "\n"
            "After splitting, the tokens are still strings.\n"
            "\n"
            "We need to map each token to an integer.\n"
            "\n"
            "Suppose our vocabulary is:\n"
            "\n"
            "```python\n"
            "vocabulary = {\n"
            "    \"[UNK]\": 0,\n"
            "    \"the\": 1,\n"
            "    \"quick\": 2,\n"
            "    \"brown\": 3,\n"
            "    \"fox\": 4,\n"
            "}\n"
            "```\n"
            "\n"
            "Then:\n"
            "\n"
            "```text\n"
            "\"the quick fox\"\n"
            "      ↓\n"
            "[1, 2, 4]\n"
            "```\n"
            "\n"
            "These integer IDs can then be used by machine-learning layers.\n"
            "\n"
            "### Vocabulary\n"
            "\n"
            "A **vocabulary** is the collection of known tokens that the "
            "tokenizer can map to IDs.\n"
            "\n"
            "For word tokenization, a vocabulary might contain:\n"
            "\n"
            "```text\n"
            "[UNK]\n"
            "the\n"
            "movie\n"
            "great\n"
            "terrible\n"
            "actor\n"
            "...\n"
            "```\n"
            "\n"
            "Large vocabularies allow more tokens to be represented directly, "
            "but they also increase memory requirements and model size.\n"
            "\n"
            "### The `[UNK]` token\n"
            "\n"
            "What happens when the tokenizer sees a token that is not in its "
            "vocabulary?\n"
            "\n"
            "A special token is used:\n"
            "\n"
            "```text\n"
            "[UNK] = unknown token\n"
            "```\n"
            "\n"
            "Suppose `lazy` is missing from the vocabulary:\n"
            "\n"
            "```text\n"
            "\"the lazy dog\"\n"
            "      ↓\n"
            "[1, 0, 7]\n"
            "```\n"
            "\n"
            "The unknown word is mapped to ID 0 in this example.\n"
            "\n"
            "### Character tokenization\n"
            "\n"
            "Character tokenizers have a small vocabulary.\n"
            "\n"
            "For example, an entire English book may be representable using "
            "only dozens of frequent characters.\n"
            "\n"
            "Advantage:\n"
            "\n"
            "```text\n"
            "small vocabulary\n"
            "few unknown symbols\n"
            "```\n"
            "\n"
            "Disadvantage:\n"
            "\n"
            "```text\n"
            "very long sequences\n"
            "```\n"
            "\n"
            "The sentence:\n"
            "\n"
            "```text\n"
            "\"machine learning\"\n"
            "```\n"
            "\n"
            "requires many character tokens but only two word tokens.\n"
            "\n"
            "### Word tokenization\n"
            "\n"
            "Word-level tokenization greatly shortens sequences.\n"
            "\n"
            "```text\n"
            "\"machine learning is useful\"\n"
            " ↓\n"
            "[machine, learning, is, useful]\n"
            "```\n"
            "\n"
            "However, natural language contains huge numbers of possible words, "
            "including names, spelling variants, rare terms, and new words.\n"
            "\n"
            "A fixed word vocabulary therefore creates a tradeoff:\n"
            "\n"
            "```text\n"
            "small vocabulary\n"
            "→ many unknown words\n"
            "\n"
            "huge vocabulary\n"
            "→ expensive model\n"
            "```\n"
            "\n"
            "### Subword tokenization\n"
            "\n"
            "Subword tokenization aims to combine the strengths of character "
            "and word approaches.\n"
            "\n"
            "The goal is:\n"
            "\n"
            "```text\n"
            "reasonably short sequences\n"
            "+\n"
            "manageable vocabulary\n"
            "+\n"
            "ability to represent rare words\n"
            "```\n"
            "\n"
            "A common word may become one token while an unusual word is split "
            "into several smaller units.\n"
            "\n"
            "For example, conceptually:\n"
            "\n"
            "```text\n"
            "common word:\n"
            "\"movie\"\n"
            "→ [movie]\n"
            "\n"
            "rare word:\n"
            "\"movielike\"\n"
            "→ [movie, like]\n"
            "```\n"
            "\n"
            "### Byte-pair encoding intuition\n"
            "\n"
            "One popular way to learn subword units is **byte-pair encoding**, "
            "or BPE.\n"
            "\n"
            "The basic idea is surprisingly simple.\n"
            "\n"
            "Start from small symbols such as characters:\n"
            "\n"
            "```text\n"
            "t h e\n"
            "b r o w n\n"
            "f o x\n"
            "```\n"
            "\n"
            "Then repeatedly find frequently neighboring symbol pairs and "
            "merge them.\n"
            "\n"
            "For example:\n"
            "\n"
            "```text\n"
            "t h\n"
            "→ th\n"
            "\n"
            "th e\n"
            "→ the\n"
            "```\n"
            "\n"
            "Common sequences eventually become whole tokens, while uncommon "
            "words may remain divided into smaller pieces.\n"
            "\n"
            "This gives the tokenizer a useful compromise between character "
            "and word tokenization.\n"
            "\n"
            "### Which tokenization should you choose?\n"
            "\n"
            "There is no universal answer.\n"
            "\n"
            "```text\n"
            "Character-level\n"
            "→ useful when individual characters matter\n"
            "→ long sequences\n"
            "\n"
            "Word-level\n"
            "→ simple and interpretable\n"
            "→ vocabulary can become huge\n"
            "\n"
            "Subword-level\n"
            "→ good balance of vocabulary size and sequence length\n"
            "→ widely used by modern language models\n"
            "```\n"
            "\n"
            "When using a pretrained language model, however, you generally "
            "must use the same tokenization scheme that was used during "
            "pretraining.\n"
