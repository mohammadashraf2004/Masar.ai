            "- inventory levels,\n"
            "- workflow labels,\n"
            "- state-like variables where the last known value remains valid until change.\n"
            "\n"
            "---\n"
            "\n"
            "### 8.2 Backward fill\n"
            "\n"
            "```python\n"
            "sales_filled = (\n"
            "    sales.bfill()\n"
            ")\n"
            "```\n"
            "\n"
            "A missing value is filled with the next available value.\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "10\n"
            "NaN\n"
            "13\n"
            "```\n"
            "\n"
            "becomes:\n"
            "\n"
            "```text\n"
            "10\n"
            "13\n"
            "13\n"
            "```\n"
