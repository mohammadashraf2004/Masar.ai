export const STRINGS: Record<UiLanguage, Record<StringKey, string>> = { en: EN, ar: AR }

export function translate(key: StringKey, language: UiLanguage): string {
  return STRINGS[language][key] ?? EN[key]
}

/** Fill `{name}` placeholders. A placeholder with no value is left visible
 *  rather than silently dropped, so a missing argument shows up in review. */
export function fmt(template: string, vars: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
  )
}

/** Which of the four count forms a number takes. English only distinguishes one
 *  from many; Arabic has separate forms for one, two, 3-10 and 11+, which is
 *  why the keys are `.one`, `.two`, `.few` and `.many` in both languages. */
export function countForm(n: number, language: UiLanguage): 'one' | 'two' | 'few' | 'many' {
  if (n === 1) return 'one'
  if (language === 'en') return 'many'
  if (n === 2) return 'two'
  return n >= 3 && n <= 10 ? 'few' : 'many'
}

/**
 * The one hook UI components use for language. Returns the active language,
 * its direction, a `t()` bound to it, and the terminology mode so a component
 * can adjust how much English it shows.
 */
export function useI18n() {
  const language = useLanguageStore((s) => s.language)
  const mode = useLanguageStore((s) => s.mode)
  const annotateTerms = useLanguageStore((s) => s.annotateTerms)
  const dir = directionFor(language)

  return {
    language,
    mode,
    annotateTerms,
    dir,
    isRtl: dir === 'rtl',
    t: (key: StringKey) => translate(key, language),
    /** `t` plus placeholder substitution: tf('onb.step', { n: 2, total: 4 }). */
    tf: (key: StringKey, vars?: Record<string, string | number>) => fmt(translate(key, language), vars),
    /** "3 courses" / "3 دورات", chosen by the language's own plural rule. */
    courseCount: (n: number) =>
      fmt(translate(`learn.courses.${countForm(n, language)}` as StringKey, language), { n }),
    /** "14 weeks" / "14 أسبوعاً", by the language's own plural rule. */
    weeks: (n: number) =>
      fmt(translate(`tracks.weeks.${countForm(n, language)}` as StringKey, language), { n }),
    /** "16 skills to gain" / "16 مهارة ستكتسبها", by the language's own plural rule. */
    skillsToGain: (n: number) =>
      fmt(translate(`intro.toGain.${countForm(n, language)}` as StringKey, language), { n }),
  }
}
