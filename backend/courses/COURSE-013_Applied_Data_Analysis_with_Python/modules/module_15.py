            "## 49. LoRA\n"
            "\n"
            "LoRA means:\n"
            "\n"
            "```text\n"
            "Low-Rank Adaptation\n"
            "```\n"
            "\n"
            "The source writes the adapted weight conceptually as:\n"
            "\n"
            "```text\n"
            "W'\n"
            "=\n"
            "W\n"
            "+\n"
            "BA\n"
            "```\n"
            "\n"
            "Where:\n"
            "\n"
            "```text\n"
            "W\n"
            "→ frozen pretrained weight\n"
            "\n"
            "A, B\n"
            "→ smaller trainable matrices\n"
            "```\n"
            "\n"
            "The product:\n"
            "\n"
            "```text\n"
            "BA\n"
            "```\n"
            "\n"
            "approximates the task-specific weight update.\n"
            "\n"
            "[[IMAGE_NEEDED: Full fine-tuning versus LoRA | Full FT duplicates and updates all base weights; LoRA freezes base and trains two small low-rank matrices attached to selected layers | Learner should understand parameter-efficiency visually]]\n"
            "\n"
            "---\n"
            "\n"
            "## 50. Why low rank helps\n"
            "\n"
            "A full dense update has many trainable values.\n"
            "\n"
            "LoRA constrains the update through smaller matrices.\n"
            "\n"
            "If the chosen rank:\n"
            "\n"
            "```text\n"
            "r\n"
            "```\n"
            "\n"
            "is much smaller than the full hidden dimension, the number of trainable parameters can be dramatically smaller.\n"
            "\n"
            "The trade-off is that adaptation capacity is constrained to this low-rank update.\n"
            "\n"
            "---\n"
