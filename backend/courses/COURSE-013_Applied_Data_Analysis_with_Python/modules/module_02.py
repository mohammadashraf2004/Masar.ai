            "## Important misconceptions\n"
            "\n"
            "### Misconception 1\n"
            "\n"
            "> “A NumPy array is just a faster Python list.”\n"
            "\n"
            "### Why this is incomplete\n"
            "\n"
            "A NumPy array also has:\n"
            "\n"
            "- a fixed numerical representation through `dtype`,\n"
            "- dimensions and shape,\n"
            "- vectorized operations,\n"
            "- broadcasting,\n"
            "- view/copy behavior,\n"
            "- multidimensional indexing.\n"
            "\n"
            "It is a different computational model, not merely a list replacement.\n"
            "\n"
            "---\n"
            "\n"
            "### Misconception 2\n"
            "\n"
            "> “`type(arr)` and `arr.dtype` tell me the same thing.”\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "`type(arr)` describes the Python object.\n"
            "\n"
            "`arr.dtype` describes the stored element representation.\n"
            "\n"
            "---\n"
            "\n"
            "### Misconception 3\n"
            "\n"
            "> “`flatten()` and `ravel()` are interchangeable in every practical sense.”\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "Both create a one-dimensional representation, but the chapter distinguishes them by memory behavior: `ravel()` can return a reference/view-like representation and avoid extra memory, while `flatten()` produces a separate flattened result.\n"
            "\n"
            "---\n"
            "\n"
            "### Misconception 4\n"
            "\n"
            "> “A NumPy view is an independent backup.”\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "A view can share data with the original array.\n"
            "\n"
            "Changes to the shared underlying data can appear in both.\n"
            "\n"
            "Use a copy when you need an independent replica.\n"
            "\n"
            "---\n"
            "\n"
            "### Misconception 5\n"
            "\n"
            "> “`arr[2:7]` includes index 7.”\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "Python/NumPy slicing stops before the stop index.\n"
            "\n"
            "So `2:7` includes indices:\n"
            "\n"
            "```text\n"
            "2,3,4,5,6\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### Misconception 6\n"
            "\n"
            "> “Fancy indexing always selects rectangular blocks.”\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "Paired row and column index arrays can select individual coordinates.\n"
            "\n"
            "For example:\n"
            "\n"
            "```python\n"
            "arr[[1, 2], [2, 3]]\n"
            "```\n"
            "\n"
            "selects `(1,2)` and `(2,3)`.\n"
            "\n"
            "---\n"
            "\n"
            "### Misconception 7\n"
            "\n"
            "> “Pandas DataFrames and NumPy arrays have the same data model.”\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "NumPy arrays emphasize homogeneous array computation.\n"
            "\n"
            "Pandas DataFrames emphasize labeled tabular data and can contain columns with different types.\n"
            "\n"
            "---\n"
            "\n"
            "### Misconception 8\n"
            "\n"
            "> “A Pandas column selection always returns another DataFrame.”\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "Selecting one column such as:\n"
            "\n"
            "```python\n"
            "df['Country']\n"
            "```\n"
            "\n"
            "returns a Series.\n"
            "\n"
            "Selecting a list of columns returns a DataFrame.\n"
            "\n"
            "---\n"
            "\n"
            "### Misconception 9\n"
            "\n"
            "> “`groupby()` simply sorts rows into groups.”\n"
            "\n"
            "### Why this is incomplete\n"
            "\n"
            "The chapter emphasizes **split-apply-combine**:\n"
            "\n"
            "1. split rows into groups,\n"
            "2. apply an aggregation,\n"
            "3. combine results.\n"
            "\n"
            "---\n"
            "\n"
            "### Misconception 10\n"
            "\n"
            "> “`merge()` and `concat()` are the same operation.”\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "`merge()` matches records using keys.\n"
            "\n"
            "`concat()` stacks compatible structures.\n"
            "\n"
            "---\n"
            "\n"
            "### Misconception 11\n"
            "\n"
            "> “Dropping missing values is always the safest cleaning strategy.”\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "Dropping rows can remove a large part of a dataset.\n"
            "\n"
            "The chapter also introduces filling strategies, and the choice depends on what missingness means.\n"
            "\n"
            "---\n"
            "\n"
            "### Misconception 12\n"
            "\n"
            "> “Dates should remain ordinary strings.”\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "Datetime objects support:\n"
            "\n"
            "- sorting,\n"
            "- date arithmetic,\n"
            "- feature extraction,\n"
            "- timezone operations,\n"
            "- formatting,\n"
            "- time-series analysis.\n"
            "\n"
