            "  ↓\n"
            "Decoder\n"
            "  ↓\n"
            "Reconstruction\n"
            "```\n"
            "\n"
            "It is primarily presented as an unsupervised deep-learning method in the chapter.\n"
            "\n"
            "Applications include:\n"
            "\n"
            "- dimensionality reduction,\n"
            "- feature extraction,\n"
            "- anomaly detection,\n"
            "- denoising,\n"
            "- image compression.\n"
            "\n"
