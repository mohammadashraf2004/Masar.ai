            "## 8. Missing values in time series\n"
            "\n"
            "Time-series data has special fill strategies because neighboring observations have temporal meaning.\n"
            "\n"
            "The chapter introduces:\n"
            "\n"
            "```text\n"
            "forward fill\n"
