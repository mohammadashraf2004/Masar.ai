            "## 3. Principal Component Analysis (PCA)\n"
            "\n"
            "PCA is the chapter's main dimensionality-reduction method.\n"
            "\n"
            "It is a:\n"
            "\n"
            "```text\n"
            "linear transformation\n"
            "```\n"
            "\n"
            "that creates new features called:\n"
            "\n"
            "```text\n"
            "Principal Components\n"
            "```\n"
            "\n"
            "or:\n"
            "\n"
            "```text\n"
            "PCs\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 3.1 Linear combination\n"
            "\n"
            "A principal component is built from weighted combinations of original features.\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "PC1\n"
            "=\n"
            "w₁x₁\n"
            "+\n"
            "w₂x₂\n"
            "+\n"
            "w₃x₃\n"
            "+\n"
            "...\n"
            "```\n"
            "\n"
            "Where:\n"
            "\n"
            "```text\n"
            "x\n"
            "→ original features\n"
            "\n"
            "w\n"
            "→ component weights/loadings\n"
            "```\n"
            "\n"
            "The resulting component does not correspond to one original variable.\n"
            "\n"
            "It is a new coordinate direction.\n"
            "\n"
            "---\n"
            "\n"
            "## 4. PCA geometry: directions of maximum variance\n"
            "\n"
            "The chapter explains PCA as finding the most informative perspective from which to view the data.\n"
            "\n"
            "Imagine a 3D cloud.\n"
            "\n"
            "You want to project it onto a 2D plane.\n"
            "\n"
            "There are many possible planes.\n"
            "\n"
            "PCA searches for directions that preserve as much spread as possible.\n"
            "\n"
            "---\n"
            "\n"
            "### 4.1 PC1\n"
            "\n"
            "The first principal component captures the greatest variance.\n"
            "\n"
            "---\n"
            "\n"
            "### 4.2 PC2\n"
            "\n"
            "PC2 captures the next greatest variance while remaining:\n"
            "\n"
            "```text\n"
            "orthogonal\n"
            "```\n"
            "\n"
            "to PC1.\n"
            "\n"
            "Orthogonal means the component directions are perpendicular and represent different linear directions.\n"
            "\n"
            "---\n"
            "\n"
            "### 4.3 Later components\n"
            "\n"
            "Each next PC:\n"
            "\n"
            "- captures remaining variance,\n"
            "- remains orthogonal to prior components.\n"
            "\n"
            "If the original dataset has `p` features:\n"
            "\n"
            "```text\n"
            "maximum PCs = p\n"
            "```\n"
            "\n"
            "Together, all PCs retain the full variance representation before components are discarded.\n"
            "\n"
            "[[IMAGE_NEEDED: PCA 3D-to-2D projection | 3D point cloud with PC1 and PC2 arrows and a best-fit projection plane, then the same points represented on the 2D PC1-PC2 plane | Learner should understand PCA as rotation and projection onto maximum-variance directions]]\n"
            "\n"
            "---\n"
            "\n"
            "## 5. Why PCA is standardized first\n"
            "\n"
            "The source standardizes features before PCA:\n"
            "\n"
            "```python\n"
            "from sklearn.preprocessing import (\n"
            "    StandardScaler\n"
            ")\n"
            "\n"
            "features = (\n"
            "    customer_behavior\n"
            "    .columns\n"
            "    .tolist()\n"
            ")\n"
            "\n"
            "scaler = StandardScaler()\n"
            "\n"
            "X_scaled = (\n"
            "    scaler.fit_transform(\n"
            "        customer_behavior[\n"
            "            features\n"
            "        ]\n"
            "    )\n"
            ")\n"
            "```\n"
            "\n"
            "Why?\n"
            "\n"
            "PCA is sensitive to scale.\n"
            "\n"
            "Suppose:\n"
            "\n"
            "```text\n"
            "session_count\n"
            "→ 1 to 20\n"
            "\n"
            "annual_spend\n"
            "→ 100 to 100,000\n"
            "```\n"
            "\n"
            "Without scaling, the large-magnitude feature can dominate variance simply because of units.\n"
            "\n"
            "Standardization makes each feature approximately:\n"
            "\n"
            "```text\n"
            "mean = 0\n"
            "variance = 1\n"
            "```\n"
            "\n"
            "before PCA.\n"
            "\n"
