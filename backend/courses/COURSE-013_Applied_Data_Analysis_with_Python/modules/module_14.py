            "## 47. Unsharp Masking\n"
            "\n"
            "Despite the name, Unsharp Masking sharpens an image.\n"
            "\n"
            "Workflow:\n"
            "\n"
            "```text\n"
            "original\n"
            "   ↓\n"
            "blur\n"
            "   ↓\n"
            "original - blur\n"
            "   ↓\n"
            "detail layer\n"
            "   ↓\n"
            "original + scaled detail\n"
            "```\n"
            "\n"
            "Source:\n"
            "\n"
            "```python\n"
            "blur = cv2.GaussianBlur(\n"
            "    img_rgb,\n"
            "    ksize=(0, 0),\n"
            "    sigmaX=sigma,\n"
            "    sigmaY=sigma\n"
            ")\n"
            "\n"
            "detail = (\n"
            "    img_rgb\n"
            "    -\n"
            "    blur\n"
            ")\n"
            "```\n"
            "\n"
            "Then:\n"
            "\n"
            "```python\n"
            "usm_rgb = np.clip(\n"
            "    img_rgb\n"
            "    +\n"
            "    amount\n"
            "    *\n"
            "    detail\n"
            "    *\n"
            "    mask,\n"
            "    0.0,\n"
            "    1.0\n"
            ")\n"
            "```\n"
            "\n"
            "Controls:\n"
            "\n"
            "```text\n"
            "sigma\n"
            "→ blur radius\n"
            "\n"
            "amount\n"
            "→ sharpening strength\n"
            "\n"
            "threshold\n"
            "→ ignore weak/noisy detail\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "## 48. Laplacian sharpening\n"
            "\n"
