            '## 3. Building a segmentation model from scratch\n'
            '\n'
            'A segmentation network has a different job from a classifier.\n'
            '\n'
            'A classifier can progressively destroy spatial detail and end with one global vector.\n'
            '\n'
            'A segmentation model must eventually return to the original image resolution.\n'
            '\n'
            'This naturally leads to an **encoder-decoder** structure.\n'
            '\n'
            '```text\n'
            'input image\n'
            '    ↓\n'
            'encoder\n'
            '    ↓\n'
            'compressed spatial representation\n'
            '    ↓\n'
            'decoder\n'
            '    ↓\n'
            'pixel-level mask\n'
            '```\n'
            '\n'
            '### Encoder: compress while learning useful features\n'
            '\n'
            'The first half looks similar to an ordinary ConvNet.\n'
            '\n'
            'Example idea:\n'
            '\n'
            '```python\n'
            'inputs = keras.Input(shape=(200, 200, 3))\n'
            'x = layers.Rescaling(1 / 255.0)(inputs)\n'
            '\n'
            'x = layers.Conv2D(64, 3, strides=2, padding="same",\n'
            '                  activation="relu")(x)\n'
            'x = layers.Conv2D(64, 3, padding="same",\n'
            '                  activation="relu")(x)\n'
            '\n'
            'x = layers.Conv2D(128, 3, strides=2, padding="same",\n'
            '                  activation="relu")(x)\n'
            'x = layers.Conv2D(128, 3, padding="same",\n'
            '                  activation="relu")(x)\n'
            '```\n'
            '\n'
            'The spatial resolution becomes smaller while the number of learned channels grows.\n'
            '\n'
            'You can think of this as:\n'
            '\n'
            '```text\n'
            'large image\n'
            '   ↓\n'
            'smaller but richer feature maps\n'
            '```\n'
            '\n'
            '### Why strided convolution instead of max pooling?\n'
            '\n'
            'For classification, losing exact position information is often acceptable.\n'
            '\n'
            'For segmentation, position is essential because the model must reconstruct a pixel-level output.\n'
            '\n'
            'A `2 × 2` max-pooling operation says:\n'
            '\n'
            '> Keep the strongest value in this local region.\n'
            '\n'
            'But it discards which location inside that window produced the value.\n'
            '\n'
            'Strided convolutions can downsample while learning a spatial transformation.\n'
            '\n'
            'So for tasks where location matters, a useful principle is:\n'
            '\n'
            '```text\n'
            'prefer spatially aware downsampling\n'
            '```\n'
            '\n'
            'rather than aggressively throwing position information away.\n'
            '\n'
            '### Decoder: reconstruct spatial resolution\n'
            '\n'
            'After encoding, you may have something like:\n'
            '\n'
            '```text\n'
            '25 × 25 × 256\n'
            '```\n'
            '\n'
            'but the desired output is:\n'
            '\n'
            '```text\n'
            '200 × 200 × num_classes\n'
            '```\n'
            '\n'
            'The decoder must therefore upsample.\n'
            '\n'
            'One useful layer is:\n'
            '\n'
            '```text\n'
            'Conv2DTranspose\n'
            '```\n'
            '\n'
            'A transposed convolution learns how to increase spatial resolution.\n'
            '\n'
            'Conceptually:\n'
            '\n'
            '```text\n'
            '25 × 25\n'
            '   ↓\n'
            '50 × 50\n'
            '   ↓\n'
            '100 × 100\n'
            '   ↓\n'
            '200 × 200\n'
            '```\n'
            '\n'
            'A simplified decoder might look like:\n'
            '\n'
            '```python\n'
            'x = layers.Conv2DTranspose(\n'
            '    256, 3, padding="same", activation="relu"\n'
            ')(x)\n'
            '\n'
            'x = layers.Conv2DTranspose(\n'
            '    128, 3, strides=2, padding="same", activation="relu"\n'
            ')(x)\n'
            '\n'
            'x = layers.Conv2DTranspose(\n'
            '    64, 3, strides=2, padding="same", activation="relu"\n'
            ')(x)\n'
            '\n'
            'outputs = layers.Conv2D(\n'
            '    num_classes,\n'
            '    3,\n'
            '    padding="same",\n'
            '    activation="softmax",\n'
            ')(x)\n'
            '```\n'
            '\n'
            'The final softmax returns a class probability distribution for each pixel.\n'
            '\n'
            '### Per-pixel classification\n'
            '\n'
            'This is the key idea:\n'
            '\n'
            '> Semantic segmentation is classification performed at every pixel location.\n'
            '\n'
            'If there are three classes, then every output pixel contains three scores.\n'
            '\n'
            'For one location:\n'
            '\n'
            '```text\n'
            'foreground = 0.91\n'
            'background = 0.06\n'
            'contour    = 0.03\n'
            '```\n'
            '\n'
            'The predicted class is the highest-scoring class.\n'
            '\n'
            '---\n'
            '\n'
            '## 4. Intersection over Union: a shared metric for segmentation and detection\n'
            '\n'
            'Both chapters rely on **Intersection over Union**, usually abbreviated **IoU**.\n'
            '\n'
            'IoU measures how well a predicted spatial region matches the ground truth.\n'
            '\n'
            '### Step 1 — Find the intersection\n'
            '\n'
            'The intersection is the region covered by both:\n'
            '\n'
            '```text\n'
            'predicted region\n'
            'AND\n'
            'ground-truth region\n'
            '```\n'
            '\n'
            '### Step 2 — Find the union\n'
            '\n'
            'The union is the total area covered by either region:\n'
            '\n'
            '```text\n'
            'predicted region\n'
            'OR\n'
            'ground-truth region\n'
            '```\n'
            '\n'
            '### Step 3 — Divide\n'
            '\n'
            '```text\n'
            'IoU =\n'
            'intersection area\n'
            '─────────────────\n'
            'union area\n'
            '```\n'
            '\n'
            'The result lies between:\n'
            '\n'
            '```text\n'
            '0 and 1\n'
            '```\n'
            '\n'
            'Interpretation:\n'
            '\n'
            '```text\n'
            'IoU = 1.0 -> perfect overlap\n'
            'IoU ≈ 0.5 -> partial overlap\n'
            'IoU = 0.0 -> no overlap\n'
            '```\n'
            '\n'
            '### Why accuracy alone is not enough\n'
            '\n'
            'Suppose the foreground object covers only 10% of the image.\n'
            '\n'
            'A model that predicts every pixel as background could still obtain high raw pixel accuracy.\n'
            '\n'
            'IoU focuses directly on spatial overlap and is therefore often more informative for masks and boxes.\n'
            '\n'
            '### IoU in segmentation\n'
            '\n'
            'For semantic segmentation, IoU can be computed separately per class.\n'
            '\n'
            'For example:\n'
            '\n'
            '```text\n'
            'foreground IoU\n'
            'background IoU\n'
            'contour IoU\n'
            '```\n'
            '\n'
            'or averaged across classes.\n'
            '\n'
            '### IoU in object detection\n'
            '\n'
            'For bounding boxes, IoU measures:\n'
            '\n'
            '```text\n'
            'how well the predicted box overlaps the ground-truth box\n'
            '```\n'
            '\n'
            'This becomes important later when YOLO learns confidence scores.\n'
            '\n'
            '---\n'
            '\n'
            '## 5. Training and validating the segmentation model\n'
            '\n'
            'With sparse integer masks, a natural loss is:\n'
            '\n'
            '```text\n'
            'sparse categorical cross-entropy\n'
            '```\n'
            '\n'
            'because each pixel contains one integer class ID.\n'
            '\n'
            'A high-level compile step might look like:\n'
            '\n'
            '```python\n'
            'model.compile(\n'
            '    optimizer="adam",\n'
            '    loss="sparse_categorical_crossentropy",\n'
            '    metrics=[foreground_iou],\n'
            ')\n'
            '```\n'
            '\n'
            '### Why validation still matters\n'
            '\n'
            'A segmentation network can overfit just like any other neural network.\n'
            '\n'
            'Typical pattern:\n'
            '\n'
            '```text\n'
            'training loss   -> keeps falling\n'
            'validation loss -> falls, reaches a minimum, then rises\n'
            '```\n'
            '\n'
            'The correct response is not to use the final epoch automatically.\n'
            '\n'
            'Instead, save the best model according to validation performance.\n'
            '\n'
            'For example:\n'
            '\n'
            '```python\n'
            'checkpoint = keras.callbacks.ModelCheckpoint(\n'
            '    "best_segmentation.keras",\n'
            '    save_best_only=True,\n'
            ')\n'
            '```\n'
            '\n'
            'Then train with:\n'
            '\n'
            '```python\n'
            'model.fit(\n'
            '    train_images,\n'
            '    train_masks,\n'
            '    validation_data=(val_images, val_masks),\n'
            '    callbacks=[checkpoint],\n'
            ')\n'
            '```\n'
            '\n'
            '### Turning predictions into masks\n'
            '\n'
            'The model outputs class probabilities:\n'
            '\n'
            '```text\n'
            'height × width × num_classes\n'
            '```\n'
            '\n'
            'To get the final predicted class ID for each pixel:\n'
            '\n'
            '```python\n'
            'mask = np.argmax(prediction, axis=-1)\n'
            '```\n'
            '\n'
            'The resulting 2D array can then be displayed as a segmentation mask.\n'
            '\n'
            '---\n'
            '\n'
            '## 6. Using a pretrained segmentation model: Segment Anything\n'
            '\n'
            'Training a segmentation model from scratch is useful for learning the mechanics.\n'
            '\n'
            'In real applications, a large pretrained segmentation model can provide much stronger behavior.\n'
            '\n'
            'The chapter introduces the **Segment Anything Model (SAM)**.\n'
            '\n'
            'Its key idea is unusual and powerful:\n'
            '\n'
            '> The model is prompted with an image plus a hint about which object you want segmented.\n'
            '\n'
            'The prompt can be:\n'
            '\n'
            '```text\n'
            'a foreground point\n'
            'a background point\n'
            'multiple points\n'
            'a bounding box\n'
            '```\n'
            '\n'
            '### High-level architecture\n'
            '\n'
            'SAM can be understood as three parts:\n'
            '\n'
            '```text\n'
            'image\n'
            '  ↓\n'
            'image encoder\n'
            '  ↓\n'
            'image embedding\n'
            '                \\\n'
            '                 -> mask decoder -> candidate masks\n'
            '                /\n'
            'prompt\n'
            '  ↓\n'
            'prompt encoder\n'
            '  ↓\n'
            'prompt embedding\n'
            '```\n'
            '\n'
            'The image encoder represents the visual content.\n'
            '\n'
            "The prompt encoder represents the user's hint.\n"
            '\n'
            "The mask decoder combines both to predict the requested object's mask.\n"
            '\n'
            '### Training data structure\n'
            '\n'
            'Conceptually, SAM learns from triples:\n'
            '\n'
            '```text\n'
            '(image, prompt, target mask)\n'
            '```\n'
            '\n'
            'For an object mask, a prompt can be generated automatically.\n'
            '\n'
            'For example:\n'
            '\n'
            '```text\n'
            'choose one object mask\n'
            '       ↓\n'
            'sample a point inside it\n'
            '       ↓\n'
            'use that point as the prompt\n'
            '```\n'
            '\n'
            'or:\n'
            '\n'
            '```text\n'
            'choose one object mask\n'
            '       ↓\n'
            'compute a box around it\n'
            '       ↓\n'
            'use the box as the prompt\n'
            '```\n'
            '\n'
            'This allows many training examples to be generated from richly annotated images.\n'
            '\n'
            '### Point prompting\n'
            '\n'
            'Suppose you click on a peach.\n'
            '\n'
            'The input to the model includes:\n'
            '\n'
            '```text\n'
            'image\n'
            'point coordinates\n'
            'point label = foreground\n'
            '```\n'
            '\n'
            'The model returns candidate masks for the object that contains that point.\n'
            '\n'
            'If the request is ambiguous, multiple points can help.\n'
            '\n'
            'You can also mark background points to say:\n'
            '\n'
            '```text\n'
            'do not include this area\n'
            '```\n'
            '\n'
            '### Multiple candidate masks\n'
            '\n'
            'An ambiguous prompt may correspond to more than one sensible object region.\n'
            '\n'
            'For example, clicking one banana in a pair may lead to candidates such as:\n'
            '\n'
            '```text\n'
            'only one banana\n'
            'both bananas\n'
            'a larger grouped region\n'
            '```\n'
            '\n'
            'Returning alternative masks makes the system more useful when object boundaries are ambiguous.\n'
            '\n'
            '### Box prompting\n'
            '\n'
            'A box prompt says roughly:\n'
            '\n'
            '> Segment the object inside this region.\n'
            '\n'
            "The box does not need to trace the object's exact boundary.\n"
            '\n'
            'That is the point of the segmentation model.\n'
            '\n'
            'The box provides a coarse spatial hint, and the model generates a precise mask.\n'
            '\n'
            '### Why pretrained segmentation is valuable\n'
            '\n'
            'A large pretrained segmentation model is especially useful when:\n'
            '\n'
            '- you have little labeled data,\n'
            '- you need rapid annotation,\n'
            '- you need interactive object selection,\n'
            '- you want to bootstrap a custom segmentation dataset.\n'
            '\n'
            'One particularly useful workflow is:\n'
            '\n'
            '```text\n'
            'raw images\n'
            '   ↓\n'
            'human gives point/box prompts\n'
            '   ↓\n'
            'SAM proposes masks\n'
            '   ↓\n'
            'human corrects masks\n'
            '   ↓\n'
            'new labeled segmentation dataset\n'
            '```\n'
            '\n'
