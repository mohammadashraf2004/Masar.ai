            "\n"
            "The corresponding positions are added element by element.\n"
            "\n"
            "---\n"
            "\n"
            "### 7.2 Array-to-array multiplication\n"
            "\n"
            "```python\n"
            "arr1 * arr2\n"
            "```\n"
            "\n"
            "Output:\n"
            "\n"
            "```text\n"
            "[[ 5 12]\n"
            " [21 32]]\n"
            "```\n"
            "\n"
            "This is element-wise multiplication.\n"
            "\n"
            "---\n"
            "\n"
            "### 7.3 Scalar addition\n"
            "\n"
            "```python\n"
            "arr1 + 3\n"
            "```\n"
            "\n"
            "Output:\n"
            "\n"
            "```text\n"
            "[[4 5]\n"
            " [6 7]]\n"
            "```\n"
            "\n"
