            "## 4. Prepare data with reusable transformations\n"
            "\n"
            "Do not manually clean a dataset once and hope you can repeat the process later.\n"
            "\n"
            "Machine learning preprocessing should be:\n"
            "\n"
            "- reproducible,\n"
            "- reusable,\n"
            "- applied consistently to training and future data,\n"
            "- compatible with validation/test sets,\n"
            "- and preferably part of a pipeline.\n"
            "\n"
            "First separate inputs from labels:\n"
            "\n"
            "```python\n"
            "housing = strat_train_set.drop(\n"
            "    \"median_house_value\",\n"
            "    axis=1,\n"
            ")\n"
            "\n"
            "housing_labels = strat_train_set[\n"
            "    \"median_house_value\"\n"
            "].copy()\n"
            "```\n"
            "\n"
            "### Missing values and imputation\n"
            "\n"
            "The dataset contains missing `total_bedrooms` values.\n"
            "\n"
            "Three basic strategies are:\n"
            "\n"
            "```text\n"
            "1. remove affected rows\n"
            "2. remove the feature\n"
            "3. fill the missing values\n"
            "```\n"
            "\n"
            "Filling missing values is called **imputation**.\n"
            "\n"
            "A robust Scikit-Learn approach:\n"
            "\n"
            "```python\n"
            "from sklearn.impute import SimpleImputer\n"
            "import numpy as np\n"
            "\n"
            "housing_num = housing.select_dtypes(include=[np.number])\n"
            "\n"
            "imputer = SimpleImputer(strategy=\"median\")\n"
            "imputer.fit(housing_num)\n"
            "\n"
            "X = imputer.transform(housing_num)\n"
            "```\n"
            "\n"
            "The key is that the imputer **learns medians from the training data** and stores them.\n"
            "\n"
            "Then the same learned values can be applied to:\n"
            "\n"
            "- validation data,\n"
            "- test data,\n"
            "- future production data.\n"
            "\n"
            "Do not independently recompute preprocessing statistics on the test set.\n"
            "\n"
            "That would leak test information into the system.\n"
            "\n"
            "### Understand Scikit-Learn’s API\n"
            "\n"
            "The chapter emphasizes several design patterns.\n"
            "\n"
            "**Estimator**\n"
            "\n"
            "An object that learns parameters from data using:\n"
            "\n"
            "```python\n"
            "estimator.fit(X, y)\n"
            "```\n"
            "\n"
            "or, for unsupervised transformations:\n"
            "\n"
            "```python\n"
            "estimator.fit(X)\n"
            "```\n"
            "\n"
            "**Transformer**\n"
            "\n"
            "An estimator that can transform input:\n"
            "\n"
            "```python\n"
            "X_transformed = transformer.transform(X)\n"
            "```\n"
            "\n"
            "Many transformers provide:\n"
            "\n"
            "```python\n"
            "transformer.fit_transform(X)\n"
            "```\n"
            "\n"
            "**Predictor**\n"
            "\n"
            "An estimator that can generate predictions:\n"
            "\n"
            "```python\n"
            "predictions = model.predict(X_new)\n"
            "```\n"
            "\n"
            "### Learned attributes versus hyperparameters\n"
            "\n"
            "A useful Scikit-Learn convention:\n"
            "\n"
            "```text\n"
            "constructor argument       -> hyperparameter\n"
            "attribute ending in \"_\"    -> learned/fitted attribute\n"
            "```\n"
            "\n"
            "Examples:\n"
            "\n"
            "```python\n"
            "imputer.strategy       # hyperparameter\n"
            "imputer.statistics_    # learned from training data\n"
            "```\n"
            "\n"
            "This distinction becomes very useful when debugging pipelines.\n"
            "\n"
            "### Categorical variables\n"
            "\n"
            "`ocean_proximity` is categorical.\n"
            "\n"
            "An **ordinal encoding** maps categories to integers, but this can falsely imply an order:\n"
            "\n"
            "```text\n"
            "category 0 is closer to category 1\n"
            "than to category 4\n"
            "```\n"
            "\n"
            "That is inappropriate for unordered categories.\n"
            "\n"
            "A safer choice here is **one-hot encoding**:\n"
            "\n"
            "```python\n"
            "from sklearn.preprocessing import OneHotEncoder\n"
            "\n"
            "cat_encoder = OneHotEncoder(\n"
            "    handle_unknown=\"ignore\"\n"
            ")\n"
            "\n"
            "housing_cat_1hot = cat_encoder.fit_transform(\n"
            "    housing[[\"ocean_proximity\"]]\n"
            ")\n"
            "```\n"
            "\n"
            "One-hot encoding creates one binary feature per category.\n"
            "\n"
            "Why use `OneHotEncoder` rather than independently generating dummy columns on every dataset?\n"
            "\n"
            "Because the fitted encoder remembers the categories learned from the training data and keeps a stable output schema.\n"
            "\n"
            "That is essential in production.\n"
            "\n"
            "### Sparse matrices\n"
            "\n"
            "One-hot features contain mostly zeros.\n"
            "\n"
            "Instead of storing:\n"
            "\n"
            "```text\n"
            "0 0 0 1 0 0 0 0 ...\n"
            "```\n"
            "\n"
            "as a full dense matrix, Scikit-Learn can use a **sparse matrix** that stores mostly the nonzero values and their locations.\n"
            "\n"
            "This saves memory when categorical cardinality is large.\n"
            "\n"
            "### Feature scaling\n"
            "\n"
            "Many algorithms behave poorly when numerical features operate on very different scales.\n"
            "\n"
            "Two common approaches are:\n"
            "\n"
            "**Min-max scaling**\n"
            "\n"
            "```text\n"
            "shift and rescale values into a chosen range\n"
            "```\n"
            "\n"
            "**Standardization**\n"
            "\n"
            "```text\n"
            "subtract mean\n"
            "divide by standard deviation\n"
            "```\n"
            "\n"
            "With Scikit-Learn:\n"
            "\n"
            "```python\n"
            "from sklearn.preprocessing import StandardScaler\n"
            "\n"
            "std_scaler = StandardScaler()\n"
            "housing_num_scaled = std_scaler.fit_transform(\n"
            "    housing_num\n"
            ")\n"
            "```\n"
            "\n"
            "Again:\n"
            "\n"
            "> **Fit the scaler on the training set only.**\n"
            "\n"
            "Use only `transform()` on validation, test, and production data.\n"
            "\n"
            "### Handle skewed distributions before scaling\n"
            "\n"
            "Scaling does not automatically fix a badly skewed distribution.\n"
            "\n"
            "For positive right-skewed features, transformations such as:\n"
            "\n"
            "```text\n"
            "square root\n"
            "logarithm\n"
            "```\n"
            "\n"
            "may make the distribution more symmetric.\n"
            "\n"
            "The source uses population as an example.\n"
            "\n"
            "{{image:log-transform-skewed-feature}}\n"
            "\n"
            "Other options include:\n"
            "\n"
            "- bucketizing heavy-tailed values,\n"
            "- treating multimodal ranges as categories,\n"
            "- or creating similarity features around meaningful modes.\n"
            "\n"
            "### Gaussian RBF similarity features\n"
            "\n"
            "A **radial basis function (RBF)** can convert “distance from a reference value” into a smooth similarity score.\n"
            "\n"
            "For example:\n"
            "\n"
            "```python\n"
            "from sklearn.metrics.pairwise import rbf_kernel\n"
            "\n"
            "age_simil_35 = rbf_kernel(\n"
            "    housing[[\"housing_median_age\"]],\n"
            "    [[35]],\n"
            "    gamma=0.1,\n"
            ")\n"
            "```\n"
            "\n"
            "The similarity is highest around age `35` and falls as distance increases.\n"
            "\n"
            "This can help a model learn effects around important modes without assuming a simple straight-line relationship.\n"
            "\n"
            "### Transforming the target\n"
            "\n"
            "Sometimes the target itself needs transformation.\n"
            "\n"
            "For example, you may want to standardize or log-transform a target before model fitting, but predictions still need to be returned in the original unit.\n"
            "\n"
            "Scikit-Learn’s `TransformedTargetRegressor` can manage that mapping:\n"
            "\n"
            "```python\n"
            "from sklearn.compose import TransformedTargetRegressor\n"
            "from sklearn.linear_model import LinearRegression\n"
            "from sklearn.preprocessing import StandardScaler\n"
            "\n"
            "model = TransformedTargetRegressor(\n"
            "    LinearRegression(),\n"
            "    transformer=StandardScaler(),\n"
            ")\n"
            "\n"
            "model.fit(\n"
            "    housing[[\"median_income\"]],\n"
            "    housing_labels,\n"
            ")\n"
            "```\n"
            "\n"
            "This is safer than manually remembering when to transform and inverse-transform the target.\n"
            "\n"
            "---\n"
            "\n"
            "## 5. Build preprocessing pipelines instead of disconnected steps\n"
            "\n"
            "As preprocessing grows, manually applying every transformation in the right order becomes fragile.\n"
            "\n"
            "A **Pipeline** packages a sequence of transformations.\n"
            "\n"
            "```python\n"
            "from sklearn.pipeline import make_pipeline\n"
            "from sklearn.impute import SimpleImputer\n"
            "from sklearn.preprocessing import StandardScaler\n"
            "\n"
            "num_pipeline = make_pipeline(\n"
            "    SimpleImputer(strategy=\"median\"),\n"
            "    StandardScaler(),\n"
            ")\n"
            "```\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "raw numerical features\n"
            "        |\n"
            "imputation\n"
            "        |\n"
            "scaling\n"
            "        |\n"
            "prepared features\n"
            "```\n"
            "\n"
            "When you call:\n"
            "\n"
            "```python\n"
            "num_pipeline.fit_transform(X_train)\n"
            "```\n"
            "\n"
            "each step learns only from the training data, and the output flows into the next step.\n"
            "\n"
            "When you later call:\n"
            "\n"
            "```python\n"
            "num_pipeline.transform(X_new)\n"
            "```\n"
            "\n"
            "the already-learned preprocessing is reused.\n"
            "\n"
            "This reduces data leakage and training/serving mismatch.\n"
            "\n"
            "### ColumnTransformer\n"
            "\n"
            "Numerical and categorical columns need different preprocessing.\n"
            "\n"
            "`ColumnTransformer` lets one object route different columns through different pipelines.\n"
            "\n"
            "```python\n"
            "from sklearn.compose import ColumnTransformer\n"
            "from sklearn.pipeline import make_pipeline\n"
            "from sklearn.preprocessing import OneHotEncoder\n"
            "\n"
            "num_attribs = [\n"
            "    \"longitude\",\n"
            "    \"latitude\",\n"
            "    \"housing_median_age\",\n"
            "    \"total_rooms\",\n"
            "    \"total_bedrooms\",\n"
            "    \"population\",\n"
            "    \"households\",\n"
            "    \"median_income\",\n"
            "]\n"
            "\n"
            "cat_attribs = [\"ocean_proximity\"]\n"
            "\n"
            "cat_pipeline = make_pipeline(\n"
            "    SimpleImputer(strategy=\"most_frequent\"),\n"
            "    OneHotEncoder(handle_unknown=\"ignore\"),\n"
            ")\n"
            "\n"
            "preprocessing = ColumnTransformer([\n"
            "    (\"num\", num_pipeline, num_attribs),\n"
            "    (\"cat\", cat_pipeline, cat_attribs),\n"
            "])\n"
            "```\n"
            "\n"
            "Now one transformer handles the entire input table consistently.\n"
            "\n"
            "### Custom transformations\n"
            "\n"
            "You are not limited to built-in transformers.\n"
            "\n"
            "For transformations that do not need training, `FunctionTransformer` is convenient:\n"
            "\n"
            "```python\n"
            "import numpy as np\n"
            "from sklearn.preprocessing import FunctionTransformer\n"
            "\n"
            "log_transformer = FunctionTransformer(\n"
            "    np.log,\n"
            "    inverse_func=np.exp,\n"
            ")\n"
            "```\n"
            "\n"
            "For trainable custom transformations, implement the Scikit-Learn interface.\n"
            "\n"
            "At minimum, a transformer generally needs:\n"
            "\n"
            "```text\n"
            "fit()\n"
            "transform()\n"
            "```\n"
            "\n"
            "`TransformerMixin` can provide `fit_transform()`.\n"
            "\n"
            "`BaseEstimator` helps with parameter inspection and hyperparameter tuning.\n"
            "\n"
            "### Geographic cluster-similarity features\n"
            "\n"
            "The chapter creates a useful custom idea:\n"
            "\n"
            "1. learn geographic cluster centers using k-means,\n"
            "2. measure each district’s RBF similarity to each center,\n"
            "3. add those similarities as new features.\n"
            "\n"
            "This converts raw latitude/longitude into features describing proximity to learned population centers.\n"
            "\n"
            "{{image:geographic-cluster-similarity}}\n"
            "\n"
            "The important idea is broader than this exact transformer:\n"
            "\n"
            "> **A good transformation converts raw measurements into representations that make useful structure easier for a model to learn.**\n"
            "\n"
            "### The complete preprocessing design\n"
            "\n"
            "The chapter’s full preprocessing pipeline performs several tasks:\n"
            "\n"
            "```text\n"
            "missing numerical values\n"
            "    -> median imputation\n"
            "\n"
            "missing categorical values\n"
            "    -> most-frequent imputation\n"
            "\n"
            "categorical values\n"
            "    -> one-hot encoding\n"
            "\n"
            "raw totals\n"
            "    -> ratio features\n"
            "\n"
            "right-skewed features\n"
            "    -> log transformation\n"
            "\n"
            "latitude/longitude\n"
            "    -> cluster-similarity features\n"
            "\n"
            "numerical features\n"
            "    -> standardization\n"
            "```\n"
            "\n"
            "This is a much stronger engineering pattern than scattered notebook cells.\n"
            "\n"
            "It means the same preprocessing logic can travel with the model.\n"
            "\n"
            "---\n"
            "\n"
            "## 6. Train baselines, then evaluate with cross-validation\n"
            "\n"
            "After problem framing, splitting, EDA, and preprocessing, model training is surprisingly short.\n"
            "\n"
            "### Start with a simple baseline\n"
            "\n"
            "```python\n"
            "from sklearn.linear_model import LinearRegression\n"
            "from sklearn.pipeline import make_pipeline\n"
            "\n"
            "lin_reg = make_pipeline(\n"
            "    preprocessing,\n"
            "    LinearRegression(),\n"
            ")\n"
            "\n"
            "lin_reg.fit(housing, housing_labels)\n"
            "```\n"
            "\n"
            "Evaluate it using RMSE:\n"
            "\n"
            "```python\n"
            "from sklearn.metrics import root_mean_squared_error\n"
            "\n"
            "housing_predictions = lin_reg.predict(housing)\n"
            "\n"
            "lin_rmse = root_mean_squared_error(\n"
            "    housing_labels,\n"
            "    housing_predictions,\n"
            ")\n"
            "```\n"
            "\n"
            "The source obtains a training RMSE around `$68,973`.\n"
            "\n"
            "That is not satisfactory for the target range, suggesting the linear model **underfits**.\n"
            "\n"
            "Possible reasons:\n"
            "\n"
            "- the model is too simple,\n"
            "- the features are not expressive enough.\n"
            "\n"
            "### Try a more flexible model\n"
            "\n"
            "A decision tree can model nonlinear relationships.\n"
            "\n"
            "```python\n"
            "from sklearn.tree import DecisionTreeRegressor\n"
            "\n"
            "tree_reg = make_pipeline(\n"
            "    preprocessing,\n"
            "    DecisionTreeRegressor(random_state=42),\n"
            ")\n"
            "\n"
            "tree_reg.fit(housing, housing_labels)\n"
            "```\n"
            "\n"
            "On the training set, its RMSE becomes:\n"
            "\n"
            "```text\n"
            "0.0\n"
            "```\n"
            "\n"
            "That does **not** mean the model is perfect.\n"
            "\n"
            "It is a warning sign.\n"
            "\n"
            "The tree may have memorized the training set.\n"
            "\n"
            "### Do not use the test set to diagnose this\n"
            "\n"
            "The test set is still reserved for the final system.\n"
            "\n"
            "Instead, use validation.\n"
            "\n"
            "### k-fold cross-validation\n"
            "\n"
            "In **k-fold cross-validation**:\n"
            "\n"
            "1. split the training set into `k` folds,\n"
            "2. train on `k - 1` folds,\n"
            "3. validate on the remaining fold,\n"
            "4. repeat until every fold has served as validation once,\n"
            "5. summarize the scores.\n"
            "\n"
            "{{image:k-fold-cross-validation}}\n"
            "\n"
            "With Scikit-Learn:\n"
            "\n"
            "```python\n"
            "from sklearn.model_selection import cross_val_score\n"
            "\n"
            "tree_rmses = -cross_val_score(\n"
            "    tree_reg,\n"
            "    housing,\n"
            "    housing_labels,\n"
            "    scoring=\"neg_root_mean_squared_error\",\n"
            "    cv=10,\n"
            ")\n"
            "```\n"
            "\n"
            "Why the minus sign?\n"
            "\n"
            "Scikit-Learn’s scoring convention expects “higher is better,” so error metrics may be represented as negative scores. Negating the result gives ordinary positive RMSE values.\n"
            "\n"
            "Cross-validation reveals that the decision tree’s validation RMSE is around `$66,574` even though its training error is zero.\n"
            "\n"
            "That is classic overfitting.\n"
            "\n"
            "### Compare several candidate models\n"
            "\n"
            "The chapter also evaluates a random forest:\n"
            "\n"
            "```python\n"
            "from sklearn.ensemble import RandomForestRegressor\n"
            "\n"
            "forest_reg = make_pipeline(\n"
            "    preprocessing,\n"
            "    RandomForestRegressor(random_state=42),\n"
            ")\n"
            "\n"
            "forest_rmses = -cross_val_score(\n"
            "    forest_reg,\n"
            "    housing,\n"
            "    housing_labels,\n"
            "    scoring=\"neg_root_mean_squared_error\",\n"
            "    cv=10,\n"
            ")\n"
            "```\n"
            "\n"
            "The mean validation RMSE drops substantially, to around `$47,038`.\n"
            "\n"
            "But the training RMSE remains far lower than validation RMSE, so some overfitting is still present.\n"
            "\n"
            "The right response is not to spend days polishing the first model that looks decent.\n"
            "\n"
            "A good workflow is:\n"
            "\n"
            "```text\n"
            "train several reasonable model families\n"
            "        |\n"
            "evaluate consistently\n"
            "        |\n"
            "shortlist a few promising candidates\n"
            "        |\n"
            "fine-tune only those\n"
            "```\n"
            "\n"
            "This saves time and reduces attachment to one approach.\n"
            "\n"
            "---\n"
            "\n"
            "## 7. Fine-tune the system and analyze its errors\n"
            "\n"
            "Once you have a shortlist of promising models, tune their hyperparameters systematically.\n"
            "\n"
            "### Grid search\n"
            "\n"
            "`GridSearchCV` evaluates predefined combinations.\n"
            "\n"
            "```python\n"
            "from sklearn.model_selection import GridSearchCV\n"
            "from sklearn.ensemble import RandomForestRegressor\n"
            "from sklearn.pipeline import Pipeline\n"
            "\n"
            "full_pipeline = Pipeline([\n"
            "    (\"preprocessing\", preprocessing),\n"
            "    (\n"
            "        \"random_forest\",\n"
            "        RandomForestRegressor(random_state=42),\n"
            "    ),\n"
            "])\n"
            "\n"
            "param_grid = [\n"
            "    {\n"
            "        \"preprocessing__geo__n_clusters\": [5, 8, 10],\n"
            "        \"random_forest__max_features\": [4, 6, 8],\n"
            "    },\n"
            "    {\n"
            "        \"preprocessing__geo__n_clusters\": [10, 15],\n"
            "        \"random_forest__max_features\": [6, 8, 10],\n"
            "    },\n"
            "]\n"
            "\n"
            "grid_search = GridSearchCV(\n"
            "    full_pipeline,\n"
            "    param_grid,\n"
            "    cv=3,\n"
            "    scoring=\"neg_root_mean_squared_error\",\n"
            ")\n"
            "\n"
            "grid_search.fit(housing, housing_labels)\n"
            "```\n"
            "\n"
            "Notice something powerful:\n"
            "\n"
            "```text\n"
            "preprocessing__geo__n_clusters\n"
            "```\n"
            "\n"
            "refers to a hyperparameter deep inside the preprocessing pipeline.\n"
            "\n"
            "So preprocessing and model hyperparameters can be tuned together.\n"
            "\n"
            "That matters because they interact.\n"
            "\n"
            "For example, the ideal number of geographic clusters may depend on how much capacity the model has to use them.\n"
            "\n"
            "### Grid search cost\n"
            "\n"
            "If the grid contains:\n"
            "\n"
            "```text\n"
            "15 parameter combinations\n"
            "x\n"
            "3 CV folds\n"
            "```\n"
            "\n"
            "then the system performs:\n"
            "\n"
            "```text\n"
            "45 training runs\n"
            "```\n"
            "\n"
            "Hyperparameter tuning can become expensive very quickly.\n"
            "\n"
            "### Randomized search\n"
            "\n"
            "When the search space is large, `RandomizedSearchCV` is often more efficient.\n"
            "\n"
            "Instead of evaluating every combination, it samples a chosen number of configurations.\n"
            "\n"
            "```python\n"
            "from scipy.stats import randint\n"
            "from sklearn.model_selection import RandomizedSearchCV\n"
            "\n"
            "param_distribs = {\n"
            "    \"preprocessing__geo__n_clusters\": randint(\n"
            "        low=3,\n"
            "        high=50,\n"
            "    ),\n"
            "    \"random_forest__max_features\": randint(\n"
            "        low=2,\n"
            "        high=20,\n"
            "    ),\n"
            "}\n"
            "\n"
            "rnd_search = RandomizedSearchCV(\n"
            "    full_pipeline,\n"
            "    param_distributions=param_distribs,\n"
            "    n_iter=10,\n"
            "    cv=3,\n"
            "    scoring=\"neg_root_mean_squared_error\",\n"
            "    random_state=42,\n"
            ")\n"
            "\n"
            "rnd_search.fit(housing, housing_labels)\n"
            "```\n"
            "\n"
            "Why randomized search is useful:\n"
            "\n"
            "- it can explore many distinct values for continuous hyperparameters,\n"
            "- unimportant hyperparameters do not multiply the full grid cost,\n"
            "- you choose the computational budget directly using `n_iter`.\n"
            "\n"
            "The chapter also mentions successive-halving search strategies, which begin with many candidates using limited resources and progressively allocate more resources to the best ones.\n"
            "\n"
            "### Ensemble methods\n"
            "\n"
            "Combining strong but diverse models can outperform one model alone if their errors differ.\n"
            "\n"
            "The chapter only introduces the concept here; ensemble learning is covered later in more depth.\n"
            "\n"
            "The takeaway is:\n"
            "\n"
            "```text\n"
            "diverse useful models\n"
            "        +\n"
            "uncorrelated errors\n"
            "        ->\n"
            "potentially better combined prediction\n"
            "```\n"
            "\n"
            "### Inspect feature importance\n"
            "\n"
            "Tuning is not the end.\n"
            "\n"
            "A strong model should be investigated.\n"
            "\n"
            "For a random forest:\n"
            "\n"
            "```python\n"
            "final_model = rnd_search.best_estimator_\n"
            "\n"
            "feature_importances = (\n"
            "    final_model[\"random_forest\"]\n"
            "    .feature_importances_\n"
            ")\n"
            "```\n"
            "\n"
            "The source finds `median_income` particularly influential, along with engineered geographic and ratio features.\n"
            "\n"
            "Feature importance can help you:\n"
            "\n"
            "- understand what the model relies on,\n"
            "- identify nearly useless features,\n"
            "- design better features,\n"
            "- detect suspicious behavior.\n"
            "\n"
            "### Analyze actual errors\n"
            "\n"
            "Do not inspect only average RMSE.\n"
            "\n"
            "Study specific cases where predictions are poor.\n"
            "\n"
            "Ask:\n"
            "\n"
            "```text\n"
            "Are errors concentrated in a geographic region?\n"
            "Do expensive districts fail more often?\n"
            "Are there outliers?\n"
            "Are some feature values missing or unreliable?\n"
            "Does one category receive systematically worse predictions?\n"
            "```\n"
            "\n"
            "This can send you back to:\n"
            "\n"
            "- data cleaning,\n"
            "- feature engineering,\n"
            "- model selection,\n"
            "- or data collection.\n"
            "\n"
            "### Fairness and subgroup performance\n"
            "\n"
            "A model can have acceptable average performance and still fail badly for a subgroup.\n"
            "\n"
            "The chapter recommends checking categories such as:\n"
            "\n"
            "- rural versus urban,\n"
            "- rich versus poor,\n"
            "- different geographic areas,\n"
            "- relevant demographic groups.\n"
            "\n"
            "The general principle is:\n"
            "\n"
            "> **Evaluate where the model fails, not only how much it fails on average.**\n"
            "\n"
            "---\n"
            "\n"
            "## 8. Test once, communicate the result, and prepare for production\n"
            "\n"
            "After model selection and tuning are complete, evaluate the final pipeline on the untouched test set.\n"
            "\n"
            "```python\n"
            "X_test = strat_test_set.drop(\n"
            "    \"median_house_value\",\n"
            "    axis=1,\n"
            ")\n"
            "\n"
            "y_test = strat_test_set[\n"
            "    \"median_house_value\"\n"
            "].copy()\n"
            "\n"
            "final_predictions = final_model.predict(X_test)\n"
            "\n"
            "final_rmse = root_mean_squared_error(\n"
            "    y_test,\n"
            "    final_predictions,\n"
            ")\n"
            "\n"
            "print(final_rmse)\n"
            "```\n"
            "\n"
