            "## 14. Boosting\n"
            "\n"
            "Boosting is fundamentally different from bagging.\n"
            "\n"
            "Bagging:\n"
            "\n"
            "```text\n"
            "models trained independently\n"
            "```\n"
            "\n"
            "Boosting:\n"
            "\n"
            "```text\n"
            "models trained sequentially\n"
            "```\n"
            "\n"
            "Each new learner focuses on what the existing ensemble still gets wrong.\n"
            "\n"
            "---\n"
            "\n"
            "### 14.1 Stage-wise additive model\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "Model 1\n"
            "    ↓\n"
            "find errors\n"
            "    ↓\n"
            "Model 2 corrects some errors\n"
            "    ↓\n"
            "Model 3 corrects remaining errors\n"
            "    ↓\n"
            "...\n"
            "    ↓\n"
            "weighted/additive final model\n"
            "```\n"
            "\n"
            "This is why the source describes boosting as:\n"
            "\n"
            "```text\n"
            "iterative\n"
            "corrective\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "## 15. Why boosting works — and why it can overfit\n"
            "\n"
            "The source highlights four ideas.\n"
            "\n"
            "### Error focus\n"
            "\n"
            "Later learners focus more on:\n"
            "\n"
            "- misclassified points,\n"
            "- residual-like errors,\n"
            "- loss gradients.\n"
            "\n"
            "### Learning rate\n"
            "\n"
            "Each learner contributes only a controlled correction.\n"
            "\n"
            "Small steps can make the ensemble less reactive to noise.\n"
            "\n"
            "### Regularization\n"
            "\n"
            "Examples include:\n"
            "\n"
            "- shallow trees,\n"
            "- row subsampling,\n"
            "- feature subsampling,\n"
            "- early stopping.\n"
            "\n"
            "### Loss optimization\n"
            "\n"
            "Boosting can optimize a chosen loss such as:\n"
            "\n"
            "- squared error,\n"
            "- logistic loss.\n"
            "\n"
            "---\n"
            "\n"
            "### 15.1 Bias and variance\n"
            "\n"
            "Boosting often reduces bias by adding corrective learners.\n"
            "\n"
            "But without regularization:\n"
            "\n"
            "```text\n"
            "too many learners\n"
            "or\n"
            "too aggressive corrections\n"
            "→ overfitting risk\n"
            "```\n"
            "\n"
            "So boosting strength comes from:\n"
            "\n"
            "```text\n"
            "sequential correction\n"
            "+\n"
            "controlled complexity\n"
            "```\n"
            "\n"
            "[[IMAGE_NEEDED: Bagging versus boosting | Left: parallel independent learners aggregating; right: sequential learners with arrows from previous errors to next learner | Learner should immediately see parallel versus corrective training]]\n"
            "\n"
            "---\n"
            "\n"
            "## 16. AdaBoost\n"
            "\n"
            "AdaBoost means:\n"
            "\n"
            "```text\n"
            "Adaptive Boosting\n"
            "```\n"
            "\n"
            "It combines many weak learners.\n"
            "\n"
            "The source uses shallow decision trees as weak learners.\n"
            "\n"
            "Core idea:\n"
            "\n"
            "```text\n"
            "hard examples\n"
            "receive more attention\n"
            "in later rounds\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 16.1 Initial weights\n"
            "\n"
            "At the beginning:\n"
            "\n"
            "```text\n"
            "every training observation\n"
            "has equal importance\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 16.2 Fit weak learner\n"
            "\n"
            "Train the first learner using the current sample weights.\n"
            "\n"
            "---\n"
            "\n"
            "### 16.3 Measure weighted error\n"
            "\n"
            "Incorrectly classified observations contribute to the learner's error.\n"
            "\n"
            "A better learner receives greater influence in the ensemble.\n"
            "\n"
            "---\n"
            "\n"
            "### 16.4 Reweight observations\n"
            "\n"
            "Misclassified examples:\n"
            "\n"
            "```text\n"
            "weight ↑\n"
            "```\n"
            "\n"
            "Correctly classified examples:\n"
            "\n"
            "```text\n"
            "relative weight ↓\n"
            "```\n"
            "\n"
            "The next learner therefore focuses more strongly on difficult observations.\n"
            "\n"
            "---\n"
            "\n"
            "### 16.5 Aggregate learners\n"
            "\n"
            "Final output uses a weighted combination of learners.\n"
            "\n"
            "Classification commonly uses:\n"
            "\n"
            "```text\n"
            "weighted vote / scores\n"
            "```\n"
            "\n"
            "The source describes regression variants as combining numeric outputs.\n"
            "\n"
            "[[IMAGE_NEEDED: AdaBoost reweighting | Same training points across three rounds; misclassified points become larger/heavier, next weak learner focuses on them, final weighted ensemble combines learners | Learner should understand adaptive sample weighting]]\n"
            "\n"
            "---\n"
            "\n"
            "## 17. AdaBoost in Python\n"
            "\n"
