            "\n"
            "### 14.2 Limitation\n"
            "\n"
            "The chapter warns that:\n"
            "\n"
            "- manual “eyeballing” is not robust,\n"
            "- a scatter plot only shows two-dimensional relationships.\n"
            "\n"
            "A multivariate outlier can exist in three or more dimensions.\n"
            "\n"
            "This motivates Mahalanobis distance.\n"
            "\n"
            "---\n"
            "\n"
            "## 15. Mahalanobis distance\n"
            "\n"
            "Mahalanobis distance measures how far a point lies from the center of a multivariate distribution **while accounting for correlations between variables**.\n"
            "\n"
            "The source uses:\n"
            "\n"
            "```text\n"
            "Age\n"
            "Income\n"
            "CreditScore\n"
            "```\n"
            "\n"
            "This is fundamentally different from measuring each variable independently.\n"
            "\n"
            "[[IMAGE_NEEDED: Euclidean-style versus Mahalanobis-style distance intuition | Elliptical correlated data cloud with one point measured relative to covariance-aware contour rather than simple circular distance | Learner should understand that Mahalanobis distance accounts for feature correlation]]\n"
            "\n"
            "---\n"
            "\n"
            "### 15.1 Prepare features\n"
            "\n"
            "```python\n"
            "cols = [\n"
            "    'Age',\n"
            "    'Income ($)',\n"
            "    'CreditScore'\n"
            "]\n"
            "\n"
            "customers_multivariate = (\n"
            "    customers[cols]\n"
            "    .dropna()\n"
            ")\n"
            "```\n"
            "\n"
            "Synthetic outliers:\n"
            "\n"
            "```python\n"
            "synthetic_outliers = pd.DataFrame({\n"
            "    'Age': [20, 70],\n"
            "    'Income ($)': [\n"
            "        500000,\n"
            "        600000\n"
            "    ],\n"
            "    'CreditScore': [\n"
            "        200,\n"
            "        950\n"
            "    ]\n"
            "})\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 15.2 Mean vector and covariance\n"
            "\n"
            "```python\n"
            "mean_vector = (\n"
            "    customers_multivariate\n"
            "    .mean()\n"
            ")\n"
            "\n"
            "cov_matrix = np.cov(\n"
            "    customers_multivariate.T\n"
            ")\n"
            "\n"
            "inv_cov_matrix = (\n"
            "    np.linalg.inv(\n"
            "        cov_matrix\n"
            "    )\n"
            ")\n"
            "```\n"
            "\n"
            "The covariance matrix represents how variables vary together.\n"
            "\n"
            "---\n"
            "\n"
            "### 15.3 Compute distances\n"
            "\n"
            "```python\n"
            "from scipy.spatial import (\n"
            "    distance\n"
            ")\n"
            "\n"
            "mahalanobis_distances = (\n"
            "    customers_multivariate\n"
            "    .apply(\n"
            "        lambda row:\n"
            "            distance.mahalanobis(\n"
            "                row,\n"
            "                mean_vector,\n"
            "                inv_cov_matrix\n"
            "            ),\n"
            "        axis=1\n"
            "    )\n"
            ")\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 15.4 Chi-square threshold\n"
            "\n"
            "The chapter uses:\n"
            "\n"
            "```python\n"
            "from scipy.stats import chi2\n"
            "\n"
            "alpha = 0.975\n"
            "df_degrees = len(cols)\n"
            "\n"
            "threshold = np.sqrt(\n"
            "    chi2.ppf(\n"
            "        alpha,\n"
            "        df_degrees\n"
            "    )\n"
            ")\n"
            "```\n"
            "\n"
            "Then:\n"
            "\n"
            "```python\n"
            "outliers = (\n"
            "    customers_multivariate[\n"
            "        mahalanobis_distances\n"
            "        > threshold\n"
            "    ]\n"
            ")\n"
            "```\n"
            "\n"
            "Source threshold:\n"
            "\n"
            "```text\n"
            "3.06\n"
            "```\n"
            "\n"
            "and detected outliers:\n"
            "\n"
            "```text\n"
            "Age 20, Income 500000, CreditScore 200\n"
            "Age 70, Income 600000, CreditScore 950\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "## 16. Managing outliers\n"
            "\n"
            "Detection is only the first step.\n"
            "\n"
            "The chapter gives three main strategies:\n"
            "\n"
            "```text\n"
            "remove\n"
            "cap\n"
            "transform\n"
            "```\n"
            "\n"
            "The correct method depends on the cause of the outlier.\n"
            "\n"
            "---\n"
            "\n"
            "### 16.1 Remove\n"
            "\n"
            "Remove an observation if the outlier represents an invalid record.\n"
            "\n"
            "The source filters based on the Z-score threshold:\n"
            "\n"
            "```python\n"
            "income_removed = (\n"
            "    income_with_outliers[\n"
            "        z_scores <= threshold\n"
            "    ]\n"
            ")\n"
            "```\n"
            "\n"
            "Appropriate when the value is caused by something like:\n"
            "\n"
            "- corrupted data,\n"
            "- clear data-entry error.\n"
            "\n"
            "But removal is not automatically correct for a genuine extreme event.\n"
            "\n"
            "---\n"
            "\n"
            "### 16.2 Cap\n"
            "\n"
            "Capping limits values to selected boundaries.\n"
            "\n"
            "The source uses percentiles:\n"
            "\n"
            "```python\n"
            "lower_cap = (\n"
            "    income_with_outliers\n"
            "    .quantile(0.05)\n"
            ")\n"
            "\n"
            "upper_cap = (\n"
            "    income_with_outliers\n"
            "    .quantile(0.95)\n"
            ")\n"
            "```\n"
            "\n"
            "Apply:\n"
            "\n"
            "```python\n"
            "income_capped = (\n"
            "    income_with_outliers\n"
            "    .clip(\n"
            "        lower=lower_cap,\n"
            "        upper=upper_cap\n"
            "    )\n"
            ")\n"
            "```\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "below lower cap\n"
            "→ replace with lower cap\n"
            "\n"
            "within range\n"
            "→ unchanged\n"
            "\n"
            "above upper cap\n"
            "→ replace with upper cap\n"
            "```\n"
            "\n"
            "This preserves the observation count while reducing extreme influence.\n"
            "\n"
            "---\n"
            "\n"
            "### 16.3 Transform\n"
            "\n"
            "The source uses log transformation:\n"
            "\n"
            "```python\n"
            "customers[\n"
            "    'Income_log'\n"
            "] = np.log1p(\n"
            "    customers[\n"
            "        'Income ($)'\n"
            "    ]\n"
            ")\n"
            "```\n"
            "\n"
            "The logarithm compresses large values.\n"
            "\n"
            "The source notes that transformed values become closer together.\n"
            "\n"
            "This can help with highly skewed data.\n"
            "\n"
            "---\n"
            "\n"
            "### 16.4 Treatment decision\n"
            "\n"
            "Ask:\n"
            "\n"
            "```text\n"
            "Is it an error?\n"
            "→ removal may make sense\n"
            "\n"
            "Is it real but too influential?\n"
            "→ capping may help\n"
            "\n"
            "Is the entire distribution skewed?\n"
            "→ transformation may help\n"
            "```\n"
            "\n"
            "Do not choose a treatment before understanding the cause.\n"
            "\n"
            "{{exercise:M07.L01.EX02}}\n"
            "\n"
