            "## Important misconceptions\n"
            "\n"
            "### Misconception 1\n"
            "\n"
            "> “A neuron simply sums inputs.”\n"
            "\n"
            "It performs a weighted sum, adds bias, then applies an activation.\n"
            "\n"
            "### Misconception 2\n"
            "\n"
            "> “Deep stacks of linear activations can learn any nonlinear pattern.”\n"
            "\n"
            "Without nonlinear activation, stacked linear layers remain a linear mapping.\n"
            "\n"
            "### Misconception 3\n"
            "\n"
            "> “Sigmoid is the best hidden activation for every deep network.”\n"
            "\n"
            "The chapter explains sigmoid can suffer from vanishing gradients.\n"
            "\n"
            "### Misconception 4\n"
            "\n"
            "> “ReLU has no failure mode.”\n"
            "\n"
            "It can produce dying neurons when negative-region behavior dominates.\n"
            "\n"
            "### Misconception 5\n"
            "\n"
            "> “Softmax is applied independently to each class.”\n"
            "\n"
            "Its outputs are coupled because they form one probability distribution summing to 1.\n"
            "\n"
            "### Misconception 6\n"
            "\n"
            "> “Optimizer and regularization mean the same thing.”\n"
            "\n"
            "Optimization reduces loss; regularization controls complexity/generalization.\n"
            "\n"
            "### Misconception 7\n"
            "\n"
            "> “Dropout removes neurons permanently.”\n"
            "\n"
            "It randomly omits units during training; it is a training-time regularization mechanism.\n"
            "\n"
            "### Misconception 8\n"
            "\n"
            "> “MLP means exactly one hidden layer.”\n"
            "\n"
            "An MLP may contain one or several hidden layers.\n"
            "\n"
            "### Misconception 9\n"
            "\n"
            "> “Backpropagation is a separate prediction architecture unrelated to MLP.”\n"
            "\n"
            "In the source, MLP training already uses backpropagation.\n"
            "\n"
            "### Misconception 10\n"
            "\n"
            "> “CNNs connect every image pixel directly to every feature detector.”\n"
            "\n"
            "Convolution uses local receptive regions and shared filters.\n"
            "\n"
            "### Misconception 11\n"
            "\n"
            "> “Pooling creates more spatial detail.”\n"
            "\n"
            "Pooling reduces spatial resolution.\n"
            "\n"
            "### Misconception 12\n"
            "\n"
            "> “Flattening learns image features.”\n"
            "\n"
            "The convolutional layers learn spatial features; flattening reshapes them for dense layers.\n"
            "\n"
            "### Misconception 13\n"
            "\n"
            "> “RNN inputs are just 2D matrices.”\n"
            "\n"
            "The recurrent layers expect `(samples, timesteps, features)`.\n"
            "\n"
            "### Misconception 14\n"
            "\n"
            "> “`return_sequences=True` means the model predicts multiple targets automatically.”\n"
            "\n"
            "It means the recurrent layer returns outputs for all time steps to the next recurrent layer.\n"
            "\n"
            "### Misconception 15\n"
            "\n"
            "> “An LSTM has no RNN relationship.”\n"
            "\n"
            "LSTM is a recurrent architecture with gated memory.\n"
            "\n"
            "### Misconception 16\n"
            "\n"
            "> “The source's lower LSTM RMSE proves LSTM always beats RNN.”\n"
            "\n"
            "It shows the provided LSTM configuration performed better in that experiment.\n"
            "\n"
            "### Misconception 17\n"
            "\n"
            "> “An autoencoder needs class labels.”\n"
            "\n"
            "The reconstruction objective uses the input itself—or a clean version of it—as the target.\n"
            "\n"
            "### Misconception 18\n"
            "\n"
            "> “Reconstruction should look sharper than the original.”\n"
            "\n"
            "The chapter explicitly says reconstructed outputs can be smoother and blurrier.\n"
            "\n"
            "### Misconception 19\n"
            "\n"
            "> “A denoising autoencoder is trained noisy → noisy.”\n"
            "\n"
            "It is trained:\n"
            "\n"
            "```text\n"
            "noisy input\n"
            "→ clean target\n"
            "```\n"
            "\n"
            "### Misconception 20\n"
            "\n"
            "> “A test set can be used repeatedly during training and still be a completely untouched test set.”\n"
            "\n"
            "Once it is used for validation monitoring, it is no longer fully untouched.\n"
