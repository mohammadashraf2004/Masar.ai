            "\n"
            "```text\n"
            "start at index 2\n"
            "stop before index 7\n"
            "move by 2 each time\n"
            "```\n"
            "\n"
            "General slice pattern:\n"
            "\n"
            "```python\n"
            "array[start:stop:step]\n"
            "```\n"
            "\n"
