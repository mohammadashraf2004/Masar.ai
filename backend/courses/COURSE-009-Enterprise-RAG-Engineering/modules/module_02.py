                       '\n'
                       '## 23. How to evaluate a chunking strategy\n'
                       '\n'
                       'Chunking can be evaluated at two stages.\n'
                       '\n'
                       '### Retrieval-side evaluation\n'
                       '\n'
                       'Ask whether the correct evidence is retrieved. Metrics mentioned in the '
                       'chapter include:\n'
                       '\n'
                       '- precision,\n'
                       '- recall,\n'
                       '- F1,\n'
                       '- nDCG,\n'
                       '- MRR.\n'
                       '\n'
                       'These metrics focus on ranking and retrieval quality.\n'
                       '\n'
                       '### Generation-side evaluation\n'
                       '\n'
                       'Ask whether the generator can produce a correct, useful answer from the '
                       'retrieved context. The chapter mentions question-answering / '
                       'machine-reading-comprehension style evaluation, BERTScore, and LLM-based '
                       'judgments.\n'
                       '\n'
                       'Generation metrics are influenced by more than chunking. The order of '
                       'retrieved chunks matters because models can pay more attention to evidence '
                       'near the beginning and end of a long prompt—the “lost in the middle” '
                       'effect.\n'
                       '\n'
                       'Therefore, a generation score alone cannot prove that one chunking '
                       'strategy is superior. Isolate retrieval performance where possible, then '
                       'evaluate the full system.\n'
                       '\n'
