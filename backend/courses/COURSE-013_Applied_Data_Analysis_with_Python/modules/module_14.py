            "    return np.clip(\n"
            "        img + beta,\n"
            "        0.0,\n"
            "        1.0\n"
            "    )\n"
            "```\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "positive beta\n"
            "→ brighter\n"
