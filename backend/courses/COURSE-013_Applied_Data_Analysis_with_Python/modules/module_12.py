            "## 8. Identity and step activation functions\n"
            "\n"
            "### Identity\n"
            "\n"
            "```text\n"
            "f(x) = x\n"
            "```\n"
            "\n"
            "Output equals input.\n"
            "\n"
            "Useful source role:\n"
            "\n"
            "```text\n"
            "regression output layer\n"
            "```\n"
            "\n"
            "Limitation:\n"
            "\n"
            "```text\n"
            "no nonlinearity\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### Binary step\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
