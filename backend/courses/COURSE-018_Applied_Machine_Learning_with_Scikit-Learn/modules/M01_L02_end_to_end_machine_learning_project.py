            "\n"
            "### Do not tune after looking at test performance\n"
            "\n"
            "If the test result is disappointing, it is tempting to adjust hyperparameters until the test number improves.\n"
            "\n"
            "Do not do that.\n"
            "\n"
            "Once test results affect model choices, the test set becomes part of the development loop and loses its role as an independent estimate.\n"
            "\n"
            "If you genuinely begin a new model-development cycle, you may eventually need a new untouched test set.\n"
            "\n"
            "### Point estimate versus uncertainty\n"
            "\n"
            "One RMSE value does not tell you how uncertain the estimate is.\n"
            "\n"
