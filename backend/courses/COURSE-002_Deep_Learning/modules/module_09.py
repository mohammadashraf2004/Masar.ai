            '## 12. Choosing classification, segmentation, or detection\n'
            '\n'
            'The most important practical lesson from these two chapters is not how to memorize individual architectures.\n'
            '\n'
            'It is how to define the computer-vision problem correctly.\n'
            '\n'
            '### Scenario 1 — Product recognition\n'
            '\n'
            'Requirement:\n'
            '\n'
            '```text\n'
            '"Tell me what product appears in this image."\n'
            '```\n'
            '\n'
            'Use:\n'
            '\n'
            '```text\n'
            'classification\n'
            '```\n'
            '\n'
            '### Scenario 2 — Count cars in traffic\n'
            '\n'
            'Requirement:\n'
            '\n'
            '```text\n'
            '"How many cars are visible, and where are they?"\n'
            '```\n'
            '\n'
            'Use:\n'
            '\n'
            '```text\n'
            'object detection\n'
            '```\n'
            '\n'
            'There is no need to pay the cost of pixel-perfect masks.\n'
            '\n'
            "### Scenario 3 — Replace a person's video-call background\n"
            '\n'
            'Requirement:\n'
            '\n'
            '```text\n'
            '"Separate the person from every background pixel."\n'
            '```\n'
            '\n'
            'Use:\n'
            '\n'
            '```text\n'
            'segmentation\n'
            '```\n'
            '\n'
            '### Scenario 4 — Identify and separately edit every fruit\n'
            '\n'
            'Requirement:\n'
            '\n'
            '```text\n'
            '"Give me the exact pixels for each individual fruit."\n'
            '```\n'
            '\n'
            'Use:\n'
            '\n'
            '```text\n'
            'instance segmentation\n'
            '```\n'
            '\n'
            '### Scenario 5 — Real-time embedded perception\n'
            '\n'
            'If latency and compute are highly constrained, detection may be more practical than segmentation when boxes are sufficient.\n'
            '\n'
            'Single-stage detectors are especially attractive for real-time systems.\n'
            '\n'
            '### Scenario 6 — Rapidly create a segmentation dataset\n'
            '\n'
            'Use a pretrained promptable segmentation model.\n'
            '\n'
            'Workflow:\n'
            '\n'
            '```text\n'
            'point/box prompt\n'
            '    ↓\n'
            'predicted mask\n'
            '    ↓\n'
            'human review\n'
            '    ↓\n'
            'saved label\n'
            '```\n'
            '\n'
            '### One decision tree to remember\n'
            '\n'
            '```text\n'
            'Do I need spatial location?\n'
            '        |\n'
            '        +-- No --> Classification\n'
            '        |\n'
            '        +-- Yes\n'
            '             |\n'
            '             +-- Is a bounding box enough?\n'
            '             |       |\n'
            '             |       +-- Yes --> Object Detection\n'
            '             |\n'
            '             +-- No --> Segmentation\n'
            '                      |\n'
            '                      +-- Need separate object identities?\n'
            '                              |\n'
            '                              +-- No --> Semantic Segmentation\n'
            '                              |\n'
            '                              +-- Yes --> Instance / Panoptic Segmentation\n'
            '```\n'
            '\n'
            '---\n'
            '\n'
            '## Important misconceptions\n'
            '\n'
            '### Misconception 1\n'
            '\n'
            '> "Segmentation and detection are just two names for the same problem."\n'
            '\n'
            'They both locate objects, but the output resolution is different.\n'
            '\n'
            '```text\n'
            'detection   -> boxes\n'
            'segmentation -> pixel masks\n'
            '```\n'
            '\n'
            '### Misconception 2\n'
            '\n'
            '> "If segmentation gives more information, it is always the better choice."\n'
            '\n'
            'More information can mean more:\n'
            '\n'
            '- compute,\n'
            '- labeling cost,\n'
            '- memory,\n'
            '- system complexity.\n'
            '\n'
            'If boxes are enough, detection may be the better engineering choice.\n'
            '\n'
            '### Misconception 3\n'
            '\n'
            '> "YOLO only predicts classes."\n'
            '\n'
            'A detector must learn spatial outputs as well.\n'
            '\n'
            'A YOLO-style model jointly predicts:\n'
            '\n'
            '```text\n'
            'class information\n'
            'box geometry\n'
            'object confidence\n'
            '```\n'
            '\n'
            '### Misconception 4\n'
            '\n'
            '> "IoU is only a segmentation metric."\n'
            '\n'
            'IoU is useful for any spatial-overlap problem.\n'
            '\n'
            'It works for:\n'
            '\n'
            '```text\n'
            'mask overlap\n'
            'bounding-box overlap\n'
            '```\n'
