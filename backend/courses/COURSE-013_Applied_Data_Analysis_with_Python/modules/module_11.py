            "## 26. One-vs-One (OvO)\n"
            "\n"
            "OvO trains one binary classifier for every pair of classes.\n"
            "\n"
            "For:\n"
            "\n"
            "```text\n"
            "C classes\n"
            "```\n"
            "\n"
            "the number of pairwise classifiers grows approximately as:\n"
            "\n"
            "```text\n"
            "C(C - 1) / 2\n"
            "```\n"
            "\n"
            "Example:\n"
            "\n"
            "```text\n"
            "A vs B\n"
            "A vs C\n"
            "B vs C\n"
            "```\n"
            "\n"
            "Prediction is aggregated from pairwise decisions/votes.\n"
            "\n"
            "---\n"
            "\n"
            "### 26.1 Source implementation\n"
            "\n"
            "```python\n"
            "from sklearn.multiclass import (\n"
            "    OneVsOneClassifier\n"
            ")\n"
            "\n"
            "from sklearn.svm import SVC\n"
            "\n"
            "base = SVC(\n"
            "    kernel='rbf',\n"
            "    C=2.0,\n"
            "    gamma='scale',\n"
            "    probability=True,\n"
            "    random_state=42\n"
            ")\n"
            "\n"
            "ovo = OneVsOneClassifier(\n"
            "    base\n"
            ")\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "## 27. OvR versus OvO\n"
            "\n"
            "| OvR | OvO |\n"
            "|---|---|\n"
            "| one classifier per class | one classifier per class pair |\n"
            "| scales roughly linearly with class count | grows quadratically with class count |\n"
            "| strong default when many classes | useful when class count is moderate |\n"
            "| each classifier sees one class vs all others | each classifier focuses on two classes |\n"
            "\n"
            "Source rule of thumb:\n"
            "\n"
            "```text\n"
            "many classes / limited compute\n"
            "→ OvR\n"
            "\n"
            "moderate class count / strong pairwise discrimination\n"
            "→ OvO\n"
            "```\n"
            "\n"
            "### Source consistency note\n"
            "\n"
            "The source says “both methods only need one model,” but then correctly explains that OvR and OvO train **multiple binary classifiers using the same base classifier type**.\n"
            "\n"
            "The intended meaning is:\n"
            "\n"
            "```text\n"
            "one base model family/type\n"
            "reused across multiple binary subproblems\n"
            "```\n"
            "\n"
            "not one fitted classifier total.\n"
