            "\n"
            "### Misconception 1\n"
            "\n"
            "> Tokenization simply means splitting text on spaces.\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "The chapter treats text preprocessing as a larger process "
            "including standardization, splitting, and indexing. Modern "
            "tokenizers may also operate on subword units rather than words.\n"
            "\n"
            "### Misconception 2\n"
            "\n"
            "> A larger vocabulary is always better.\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "Larger vocabularies increase representation and model costs. "
            "Subword tokenization provides a compromise by representing rare "
            "words with smaller reusable pieces.\n"
            "\n"
            "### Misconception 3\n"
            "\n"
            "> Bag-of-words models understand sentence order.\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "A basic bag-of-words representation records token presence while "
            "discarding sequence order. N-grams restore only limited local order.\n"
            "\n"
            "### Misconception 4\n"
            "\n"
            "> A more sophisticated LSTM must outperform a simple linear model.\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "Model usefulness depends on data, representation, optimization, "
            "and task structure. In the source experiment, a small bigram "
            "classifier outperforms the much larger initial LSTM model.\n"
            "\n"
            "### Misconception 5\n"
            "\n"
            "> One-hot token vectors encode semantic similarity between words.\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "One-hot vectors treat token categories independently. Learned "
            "embeddings can instead place related words in related regions of "
            "a dense representation space.\n"
            "\n"
            "### Misconception 6\n"
            "\n"
            "> Padding tokens should be processed like ordinary words.\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "Padding exists only to make batch tensors rectangular. Masking "
