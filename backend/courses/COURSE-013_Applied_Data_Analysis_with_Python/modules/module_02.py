            "## 1. NumPy arrays: the numerical foundation\n"
            "\n"
            "NumPy arrays are one of the core data structures used in scientific and engineering Python.\n"
            "\n"
            "The main NumPy object is:\n"
            "\n"
            "```python\n"
            "numpy.ndarray\n"
            "```\n"
            "\n"
            "An array may be:\n"
            "\n"
            "- one-dimensional,\n"
            "- two-dimensional,\n"
            "- or multidimensional.\n"
            "\n"
            "A one-dimensional numerical array can be thought of as a vector. A two-dimensional array often behaves like a matrix.\n"
            "\n"
            "### Why NumPy arrays are different from Python lists\n"
            "\n"
            "A NumPy array is designed around **homogeneous data**.\n"
            "\n"
            "That means its elements normally share one underlying data type.\n"
            "\n"
            "For example:\n"
            "\n"
            "```text\n"
            "[1, 2, 3, 4]       → integer array\n"
            "[1.5, 2.5, 3.5]    → floating-point array\n"
            "```\n"
            "\n"
            "The chapter emphasizes several benefits:\n"
            "\n"
            "- compact storage,\n"
            "- faster numerical computation,\n"
            "- contiguous memory layout,\n"
            "- vectorized operations,\n"
            "- compiled low-level implementation.\n"
            "\n"
            "The important study idea is not simply “NumPy is faster.”\n"
            "\n"
            "It is:\n"
            "\n"
            "> **NumPy represents numerical data in a form designed for array-wide computation.**\n"
            "\n"
            "Instead of writing Python loops over every value, you can often express an operation directly on the whole array.\n"
            "\n"
