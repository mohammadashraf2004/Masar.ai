            "## 2. Scaling Training Across Multiple Devices\n"
            "\n"
            "Model quality depends heavily on experimentation.\n"
            "\n"
            "A useful engineering loop is:\n"
            "\n"
            "```text\n"
            "idea\n"
            " ↓\n"
            "experiment\n"
            " ↓\n"
            "results\n"
            " ↓\n"
            "analysis\n"
            " ↓\n"
            "better idea\n"
            " ↓\n"
            "repeat\n"
            "```\n"
            "\n"
            "If training one experiment takes two days, iteration is slow.\n"
            "\n"
            "If it takes fifteen minutes, many more ideas can be tested.\n"
            "\n"
            "Faster training therefore contributes indirectly to better models.\n"
            "\n"
            "### Two forms of parallelism\n"
            "\n"
            "There are two main ways to distribute deep-learning computation:\n"
            "\n"
            "```text\n"
            "DATA PARALLELISM\n"
            "→ split the data\n"
            "\n"
            "MODEL PARALLELISM\n"
            "→ split the model\n"
            "```\n"
            "\n"
            "### Data parallelism\n"
            "\n"
            "With data parallelism, every device stores a full copy of the model.\n"
            "\n"
            "The batch is divided among devices.\n"
            "\n"
            "Suppose:\n"
            "\n"
            "```text\n"
            "global batch size = 128\n"
            "GPUs              = 2\n"
            "```\n"
            "\n"
            "Then:\n"
            "\n"
            "```text\n"
            "GPU 0\n"
            "→ model replica\n"
            "→ 64 samples\n"
            "\n"
            "GPU 1\n"
            "→ model replica\n"
            "→ 64 samples\n"
            "```\n"
            "\n"
            "Each replica computes gradients from its local sub-batch.\n"
            "\n"
            "The gradients are then combined—typically averaged—and all model "
            "replicas receive the same update.\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "batch\n"
            " ├── GPU 0 → gradients ──┐\n"
            " └── GPU 1 → gradients ──┤\n"
            "                          ↓\n"
            "                    average gradients\n"
            "                          ↓\n"
            "                    update all replicas\n"
            "```\n"
            "\n"
            "This keeps model weights synchronized.\n"
            "\n"
            "### Limitation of data parallelism\n"
            "\n"
            "Every device must contain a full copy of the model.\n"
            "\n"
            "Therefore:\n"
            "\n"
            "```text\n"
            "model must fit on one GPU\n"
            "```\n"
            "\n"
            "If the model itself is larger than one device's memory, data "
            "parallelism alone is not enough.\n"
            "\n"
            "### Model parallelism\n"
            "\n"
            "With model parallelism, one model is divided across several devices.\n"
            "\n"
            "```text\n"
            "GPU 0 → part of model\n"
            "GPU 1 → part of model\n"
            "GPU 2 → part of model\n"
            "GPU 3 → part of model\n"
            "```\n"
            "\n"
            "This enables training models that cannot fit on one accelerator.\n"
            "\n"
            "### Horizontal model partitioning\n"
            "\n"
            "One approach puts different layers on different devices.\n"
            "\n"
            "For example:\n"
            "\n"
            "```text\n"
            "GPU 0\n"
            "→ Layer 1\n"
            "\n"
            "GPU 1\n"
            "→ Layer 2\n"
            "```\n"
            "\n"
            "The disadvantage is communication overhead.\n"
            "\n"
            "The output from GPU 0 must travel to GPU 1 before computation can continue.\n"
            "\n"
            "If intermediate tensors are large, device communication may become "
            "a bottleneck.\n"
            "\n"
            "### Vertical partitioning\n"
            "\n"
            "Another approach divides individual layer parameters across devices.\n"
            "\n"
            "Suppose a Dense kernel has shape:\n"
            "\n"
            "```text\n"
            "(16000, 64000)\n"
            "```\n"
            "\n"
            "With two GPUs, it could be divided into:\n"
            "\n"
            "```text\n"
            "GPU 0 → (16000, 32000)\n"
            "GPU 1 → (16000, 32000)\n"
            "```\n"
            "\n"
            "Each GPU computes part of the output, then the pieces are combined.\n"
            "\n"
            "This is often called **sharding** or **partitioning**.\n"
            "\n"
            "### Combining data and model parallelism\n"
            "\n"
            "Large training systems may use both.\n"
            "\n"
            "For example, with eight GPUs:\n"
            "\n"
            "```text\n"
            "4 GPUs\n"
            "→ one sharded model replica\n"
            "\n"
            "another 4 GPUs\n"
            "→ second sharded model replica\n"
            "```\n"
            "\n"
            "Now you have:\n"
            "\n"
            "```text\n"
            "model parallelism within each group\n"
            "+\n"
            "data parallelism between groups\n"
            "```\n"
            "\n"
            "### Keras data parallelism\n"
            "\n"
            "The chapter demonstrates Keras distribution with the JAX backend.\n"
            "\n"
            "Data parallelism can be enabled before model construction:\n"
            "\n"
            "```python\n"
            "keras.distribution.set_distribution(\n"
            "    keras.distribution.DataParallel()\n"
            ")\n"
            "```\n"
            "\n"
            "Specific devices can also be supplied:\n"
            "\n"
            "```python\n"
            "keras.distribution.set_distribution(\n"
            "    keras.distribution.DataParallel([\n"
            "        \"gpu:0\",\n"
            "        \"gpu:1\",\n"
            "    ])\n"
            ")\n"
            "```\n"
            "\n"
            "### Scaling is not perfectly linear\n"
            "\n"
            "Two GPUs do not always make training exactly twice as fast.\n"
            "\n"
            "Additional overhead comes from:\n"
            "\n"
            "```text\n"
            "gradient synchronization\n"
            "communication\n"
            "device coordination\n"
            "data loading\n"
            "```\n"
            "\n"
            "The source reports example scaling close to:\n"
            "\n"
            "```text\n"
            "2 GPUs → about 2×\n"
            "4 GPUs → about 3.8×\n"
            "8 GPUs → about 7.3×\n"
            "```\n"
            "\n"
            "provided the global batch is large enough to keep all devices busy.\n"
            "\n"
            "### Device meshes\n"
            "\n"
            "For more complex distributed setups, Keras uses a **device mesh**.\n"
            "\n"
            "Imagine eight GPUs arranged logically as:\n"
            "\n"
            "```text\n"
            "        model axis\n"
            "        → → → →\n"
            "\n"
            "data ↓  GPU GPU GPU GPU\n"
            "axis ↓  GPU GPU GPU GPU\n"
            "```\n"
            "\n"
            "For example:\n"
            "\n"
            "```python\n"
            "device_mesh = keras.distribution.DeviceMesh(\n"
            "    shape=(2, 4),\n"
