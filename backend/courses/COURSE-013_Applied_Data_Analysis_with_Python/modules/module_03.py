            "\n"
            "Each describes the center differently.\n"
            "\n"
            "---\n"
            "\n"
            "### 3.1 Example dataset\n"
            "\n"
            "The chapter uses skill scores such as:\n"
            "\n"
            "```python\n"
            "sample_data = {\n"
            "    'name': ['John', 'Alia', 'Ananya', 'Steve', 'Ben'],\n"
            "    'gender': ['M', 'F', 'F', 'M', 'M'],\n"
            "    'communication_skill_score': [40, 45, 23, 39, 39],\n"
            "    'quantitative_skill_score': [38, 41, 42, 48, 32]\n"
            "}\n"
            "```\n"
            "\n"
            "The communication scores are:\n"
            "\n"
            "```text\n"
            "40, 45, 23, 39, 39\n"
            "```\n"
            "\n"
            "We will use this small dataset repeatedly.\n"
            "\n"
            "---\n"
            "\n"
            "### 3.2 Mean\n"
            "\n"
            "The arithmetic mean is:\n"
            "\n"
            "```text\n"
            "sum of observations\n"
            "-------------------\n"
            "number of observations\n"
            "```\n"
            "\n"
            "For observations:\n"
            "\n"
            "```text\n"
            "x₁, x₂, ..., xₙ\n"
            "```\n"
            "\n"
            "the mean is:\n"
            "\n"
            "```text\n"
            "x̄ = (x₁ + x₂ + ... + xₙ) / n\n"
            "```\n"
            "\n"
            "For the communication scores:\n"
            "\n"
            "```text\n"
            "40 + 45 + 23 + 39 + 39 = 186\n"
            "186 / 5 = 37.2\n"
            "```\n"
            "\n"
            "So:\n"
            "\n"
            "```text\n"
            "mean = 37.2\n"
            "```\n"
            "\n"
            "Pandas:\n"
            "\n"
            "```python\n"
            "data['communication_skill_score'].mean()\n"
            "```\n"
            "\n"
            "### Why the mean is useful\n"
            "\n"
            "The mean uses every value.\n"
            "\n"
            "That makes it very informative when the data is reasonably well-behaved.\n"
            "\n"
            "But it also means unusual extreme values can shift it.\n"
            "\n"
            "Example:\n"
            "\n"
            "```text\n"
            "40, 45, 23, 39, 39\n"
            "```\n"
            "\n"
            "versus:\n"
            "\n"
            "```text\n"
            "40, 45, 230, 39, 39\n"
            "```\n"
            "\n"
            "The extreme `230` would dramatically increase the mean.\n"
            "\n"
            "### Key idea\n"
            "\n"
            "> The mean is sensitive to outliers because every observation contributes directly to it.\n"
            "\n"
            "---\n"
            "\n"
            "### 3.3 Mode\n"
            "\n"
            "The mode is the most frequently occurring value.\n"
            "\n"
            "For:\n"
            "\n"
            "```text\n"
            "40, 45, 23, 39, 39\n"
            "```\n"
            "\n"
            "`39` appears twice while the others appear once.\n"
            "\n"
            "So:\n"
            "\n"
            "```text\n"
            "mode = 39\n"
            "```\n"
            "\n"
            "Pandas:\n"
            "\n"
            "```python\n"
            "data['communication_skill_score'].mode()\n"
            "```\n"
            "\n"
            "Mode is especially useful for categorical variables.\n"
            "\n"
            "Example:\n"
            "\n"
            "```text\n"
            "PaymentMethod:\n"
            "Card\n"
            "Cash\n"
            "Card\n"
            "Wallet\n"
            "Card\n"
            "```\n"
            "\n"
            "Mode:\n"
            "\n"
            "```text\n"
            "Card\n"
            "```\n"
            "\n"
            "A dataset may have:\n"
            "\n"
            "- one mode,\n"
            "- multiple modes,\n"
            "- or no repeated mode.\n"
            "\n"
            "---\n"
            "\n"
            "### 3.4 Median\n"
            "\n"
            "The median is the middle value after sorting.\n"
            "\n"
            "Sort the communication scores:\n"
            "\n"
            "```text\n"
            "23, 39, 39, 40, 45\n"
            "```\n"
            "\n"
            "The middle value is:\n"
            "\n"
            "```text\n"
            "39\n"
            "```\n"
            "\n"
            "So:\n"
            "\n"
            "```text\n"
            "median = 39\n"
            "```\n"
            "\n"
            "Pandas:\n"
            "\n"
            "```python\n"
            "data['communication_skill_score'].median()\n"
            "```\n"
            "\n"
            "The median is also called the 50th percentile.\n"
            "\n"
            "### Why the median is robust\n"
            "\n"
            "Consider incomes:\n"
            "\n"
            "```text\n"
            "5000\n"
            "5200\n"
            "5400\n"
            "5600\n"
            "100000\n"
            "```\n"
            "\n"
            "The extreme last value can pull the mean upward dramatically.\n"
            "\n"
            "The median remains the middle position.\n"
            "\n"
            "This is why the chapter emphasizes that the median is less affected by outliers than the mean.\n"
            "\n"
            "---\n"
            "\n"
            "### 3.5 Mean versus median versus mode\n"
            "\n"
            "| Measure | Best mental model | Sensitive to outliers? | Works naturally with categories? |\n"
            "|---|---|---:|---:|\n"
            "| Mean | arithmetic balance point | Yes | No |\n"
            "| Median | middle ordered value | Less | Ordinal can use it |\n"
            "| Mode | most frequent value | No direct arithmetic effect | Yes |\n"
