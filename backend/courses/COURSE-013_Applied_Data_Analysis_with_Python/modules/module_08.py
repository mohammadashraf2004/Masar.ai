            "## 14. Stationarity\n"
            "\n"
            "Stationarity is one of the chapter's most important forecasting concepts.\n"
            "\n"
            "The source defines stationarity as having statistical properties that remain stable over time.\n"
            "\n"
            "For weak stationarity, this includes:\n"
            "\n"
            "- mean,\n"
            "- variance,\n"
            "- autocovariance depending on lag rather than absolute time.\n"
            "\n"
            "---\n"
            "\n"
            "### 14.1 Strict stationarity\n"
            "\n"
            "The entire probability distribution is unchanged over time.\n"
            "\n"
            "The chapter describes this as a very strong condition.\n"
            "\n"
            "---\n"
            "\n"
            "### 14.2 Weak stationarity\n"
            "\n"
