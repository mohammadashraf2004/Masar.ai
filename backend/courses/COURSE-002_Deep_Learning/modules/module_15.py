            # ----------------------------------------------------------------
            # Section 1
            # ----------------------------------------------------------------

            "## 1. Getting More Performance from Your Models\n"
            "\n"
            "Once you know how to train a model that works, the next question is:\n"
            "\n"
            "> How do you systematically make it better?\n"
            "\n"
            "Real machine learning engineering involves much more than writing "
            "one architecture and training it once.\n"
            "\n"
            "You repeatedly make choices such as:\n"
            "\n"
            "```text\n"
            "How many layers?\n"
            "How many units?\n"
            "Which optimizer?\n"
            "What learning rate?\n"
            "How much dropout?\n"
            "Should BatchNormalization be used?\n"
            "Which architecture family?\n"
            "```\n"
            "\n"
            "These choices are **hyperparameters**.\n"
            "\n"
            "### Parameters versus hyperparameters\n"
            "\n"
            "A **parameter** is learned by gradient descent.\n"
            "\n"
            "Examples:\n"
            "\n"
            "```text\n"
            "Dense layer weights\n"
            "convolution kernels\n"
            "bias vectors\n"
            "embedding vectors\n"
            "```\n"
            "\n"
            "A **hyperparameter** is chosen outside the normal backpropagation "
            "process.\n"
            "\n"
            "Examples:\n"
            "\n"
            "```text\n"
            "number of units\n"
            "number of layers\n"
            "optimizer choice\n"
            "dropout rate\n"
            "learning rate\n"
            "```\n"
            "\n"
            "Think of it this way:\n"
            "\n"
            "```text\n"
            "BACKPROPAGATION\n"
            "→ learns weights\n"
            "\n"
            "HYPERPARAMETER SEARCH\n"
            "→ chooses how the model itself should be configured\n"
            "```\n"
            "\n"
            "### Why can't gradient descent optimize everything?\n"
            "\n"
            "Many hyperparameter choices are discrete.\n"
            "\n"
            "For example:\n"
            "\n"
            "```text\n"
            "optimizer = Adam OR RMSprop\n"
            "\n"
            "units = 32 OR 64 OR 128\n"
            "\n"
            "use BatchNorm = True OR False\n"
            "```\n"
            "\n"
            "These choices do not form a smooth differentiable space in the "
            "same way neural-network weights do.\n"
            "\n"
            "Therefore hyperparameter optimization usually relies on "
            "gradient-free search strategies such as:\n"
            "\n"
            "```text\n"
            "random search\n"
            "Bayesian optimization\n"
            "genetic algorithms\n"
            "```\n"
            "\n"
            "### The hyperparameter tuning loop\n"
            "\n"
            "The process is:\n"
            "\n"
            "```text\n"
            "Choose configuration\n"
            "       ↓\n"
            "Build model\n"
            "       ↓\n"
            "Train model\n"
            "       ↓\n"
            "Evaluate on validation data\n"
            "       ↓\n"
            "Use result to choose next configuration\n"
            "       ↓\n"
            "Repeat\n"
            "```\n"
            "\n"
            "Only after the search and final model selection should the "
            "untouched test set be used for final evaluation.\n"
            "\n"
            "### Why tuning is expensive\n"
            "\n"
            "When ordinary training updates model weights, each update only "
            "needs a mini-batch forward and backward pass.\n"
            "\n"
            "Hyperparameter optimization is much more expensive because one "
            "evaluation may require training an entirely new model.\n"
            "\n"
            "```text\n"
            "one hyperparameter trial\n"
            "=\n"
            "build model\n"
            "+\n"
            "train from scratch\n"
            "+\n"
            "evaluate\n"
            "```\n"
            "\n"
            "If you test 100 configurations, that could mean 100 substantial "
            "training runs.\n"
            "\n"
            "### Training noise\n"
            "\n"
            "Two identical architectures can produce slightly different results "
            "because of:\n"
            "\n"
            "- random initialization,\n"
            "- mini-batch ordering,\n"
            "- stochastic regularization,\n"
            "- and other randomness.\n"
            "\n"
            "So a configuration that scores 0.2% better once may not actually "
            "be better.\n"
            "\n"
            "Repeating a trial multiple times and averaging performance can "
            "reduce this uncertainty.\n"
            "\n"
            "### KerasTuner\n"
            "\n"
            "KerasTuner allows hardcoded choices to become searchable ranges.\n"
            "\n"
            "Instead of:\n"
            "\n"
            "```python\n"
            "layers.Dense(32, activation=\"relu\")\n"
            "```\n"
            "\n"
            "we can define:\n"
            "\n"
            "```python\n"
            "units = hp.Int(\n"
            "    name=\"units\",\n"
            "    min_value=16,\n"
            "    max_value=64,\n"
            "    step=16,\n"
            ")\n"
            "```\n"
            "\n"
            "Now possible values are:\n"
            "\n"
            "```text\n"
            "16\n"
            "32\n"
            "48\n"
            "64\n"
            "```\n"
            "\n"
            "Optimizer choice can also be searched:\n"
            "\n"
            "```python\n"
            "optimizer = hp.Choice(\n"
            "    name=\"optimizer\",\n"
            "    values=[\"rmsprop\", \"adam\"],\n"
            ")\n"
            "```\n"
            "\n"
            "### Search space\n"
            "\n"
            "The complete collection of possibilities is the **search space**.\n"
            "\n"
            "For example:\n"
            "\n"
            "```text\n"
            "units:\n"
            "16, 32, 48, 64\n"
            "\n"
            "optimizer:\n"
            "RMSprop, Adam\n"
            "```\n"
            "\n"
            "Even this tiny search space already contains:\n"
            "\n"
            "```text\n"
            "4 × 2 = 8 configurations\n"
            "```\n"
            "\n"
            "Search spaces can grow combinatorially, so they must be designed "
            "carefully.\n"
            "\n"
            "### Defining the model-building function\n"
            "\n"
            "A tuner needs a function that accepts hyperparameters and returns "
            "a compiled model.\n"
            "\n"
            "```python\n"
            "def build_model(hp):\n"
            "    units = hp.Int(\n"
            "        \"units\",\n"
            "        min_value=16,\n"
            "        max_value=64,\n"
            "        step=16,\n"
            "    )\n"
            "\n"
            "    model = keras.Sequential([\n"
            "        layers.Dense(units, activation=\"relu\"),\n"
            "        layers.Dense(10, activation=\"softmax\"),\n"
            "    ])\n"
            "\n"
            "    optimizer = hp.Choice(\n"
            "        \"optimizer\",\n"
            "        [\"rmsprop\", \"adam\"],\n"
            "    )\n"
            "\n"
            "    model.compile(\n"
            "        optimizer=optimizer,\n"
            "        loss=\"sparse_categorical_crossentropy\",\n"
            "        metrics=[\"accuracy\"],\n"
            "    )\n"
            "\n"
            "    return model\n"
            "```\n"
            "\n"
            "### Choosing a tuner\n"
            "\n"
            "The source mentions several KerasTuner strategies:\n"
            "\n"
            "```text\n"
            "RandomSearch\n"
            "BayesianOptimization\n"
            "Hyperband\n"
            "```\n"
            "\n"
            "Bayesian optimization attempts to use results from previous trials "
            "to choose promising future configurations.\n"
            "\n"
            "For example:\n"
            "\n"
            "```python\n"
            "tuner = kt.BayesianOptimization(\n"
            "    build_model,\n"
            "    objective=\"val_accuracy\",\n"
            "    max_trials=20,\n"
            "    executions_per_trial=2,\n"
            ")\n"
            "```\n"
            "\n"
            "`max_trials=20` means at most 20 different configurations are tested.\n"
            "\n"
            "`executions_per_trial=2` means each configuration is trained twice, "
            "helping reduce the effect of random training variation.\n"
            "\n"
            "### Optimize validation metrics\n"
            "\n"
            "The tuner should optimize a validation metric:\n"
            "\n"
            "```text\n"
            "val_accuracy\n"
            "val_loss\n"
            "```\n"
            "\n"
            "not test performance.\n"
            "\n"
            "Why?\n"
            "\n"
            "Because tuning itself is a learning process.\n"
            "\n"
            "If you repeatedly choose hyperparameters based on test results, "
            "the test set becomes part of your optimization process.\n"
            "\n"
            "Its final score would no longer be trustworthy.\n"
            "\n"
            "### Early stopping during tuning\n"
            "\n"
            "Different model configurations may require different numbers of "
            "epochs.\n"
            "\n"
            "Instead of guessing one fixed epoch count, you can train for a "
            "large maximum and stop when validation performance stops improving.\n"
            "\n"
            "```python\n"
            "keras.callbacks.EarlyStopping(\n"
            "    monitor=\"val_loss\",\n"
            "    patience=5,\n"
            ")\n"
            "```\n"
            "\n"
            "This saves significant search time.\n"
            "\n"
            "### Validation-set overfitting\n"
            "\n"
            "There is a subtle danger.\n"
            "\n"
            "Suppose you run:\n"
            "\n"
            "```text\n"
            "10 trials\n"
            "100 trials\n"
            "1,000 trials\n"
            "10,000 trials\n"
            "```\n"
            "\n"
            "and every decision is based on the same validation set.\n"
            "\n"
            "Eventually, your hyperparameter search begins adapting to random "
            "quirks of that validation set.\n"
            "\n"
            "This is **validation-set overfitting**.\n"
            "\n"
            "Therefore:\n"
            "\n"
            "```text\n"
            "training set\n"
            "→ learn weights\n"
            "\n"
            "validation set\n"
            "→ choose architecture + hyperparameters\n"
            "\n"
            "test set\n"
            "→ final independent evaluation\n"
            "```\n"
            "\n"
            "### Search-space design still requires expertise\n"
            "\n"
            "Hyperparameter optimization is automation, not magic.\n"
            "\n"
            "Searching everything would be too expensive.\n"
            "\n"
            "You still need architectural knowledge to choose promising ranges.\n"
            "\n"
            "A good engineer moves from questions such as:\n"
            "\n"
            "```text\n"
            "\"Should this layer have 128 or 192 units?\"\n"
            "```\n"
            "\n"
            "toward higher-level decisions such as:\n"
            "\n"
            "```text\n"
            "\"Should this architecture use residual blocks?\"\n"
            "\"Should normalization be included?\"\n"
            "```\n"
            "\n"
            "### Model ensembling\n"
            "\n"
            "Hyperparameter tuning tries to find one strong model.\n"
            "\n"
            "Ensembling asks another question:\n"
            "\n"
            "> What if several strong models are combined?\n"
            "\n"
            "Suppose four classifiers produce probabilities:\n"
            "\n"
            "```python\n"
            "pred_a = model_a.predict(x)\n"
            "pred_b = model_b.predict(x)\n"
            "pred_c = model_c.predict(x)\n"
            "pred_d = model_d.predict(x)\n"
            "```\n"
            "\n"
            "A simple ensemble averages them:\n"
            "\n"
            "```python\n"
            "final_pred = 0.25 * (\n"
            "    pred_a + pred_b + pred_c + pred_d\n"
            ")\n"
            "```\n"
            "\n"
            "### Why ensembling works\n"
            "\n"
            "Different models can make different errors.\n"
            "\n"
            "For example:\n"
            "\n"
            "```text\n"
            "Model A\n"
            "→ excellent at pattern type 1\n"
            "→ weaker at pattern type 2\n"
            "\n"
            "Model B\n"
            "→ weaker at pattern type 1\n"
            "→ excellent at pattern type 2\n"
            "```\n"
            "\n"
            "Combining them can produce a better overall system.\n"
            "\n"
            "### Weighted averaging\n"
            "\n"
            "If models have different quality, equal averaging may not be best.\n"
            "\n"
            "For example:\n"
            "\n"
            "```python\n"
            "final_pred = (\n"
            "    0.50 * pred_a\n"
            "    + 0.25 * pred_b\n"
            "    + 0.10 * pred_c\n"
            "    + 0.15 * pred_d\n"
            ")\n"
            "```\n"
            "\n"
            "The weights can be tuned using validation data.\n"
            "\n"
            "### Diversity matters more than repetition\n"
            "\n"
            "The main principle of ensembling is:\n"
            "\n"
            "> Strong models should ideally make different kinds of mistakes.\n"
            "\n"
            "Ensembling several nearly identical models trained from different "
            "random initializations may produce only a small improvement.\n"
            "\n"
            "Greater diversity may come from combining:\n"
            "\n"
            "```text\n"
            "different architectures\n"
            "different feature representations\n"
            "different model families\n"
            "```\n"
            "\n"
            "The source even discusses combining tree-based methods and neural "
            "networks because their different biases can make the ensemble stronger.\n"
