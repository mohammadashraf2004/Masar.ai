            "\n"
            "---\n"
            "\n"
            "### 33.1 MAPE limitation\n"
            "\n"
            "MAPE can behave badly when actual values are very small or zero.\n"
            "\n"
            "The source's Python function explicitly masks zero values:\n"
            "\n"
            "```python\n"
            "def mean_absolute_percentage_error(\n"
            "    y_true,\n"
            "    y_pred\n"
            "):\n"
            "    y_true = np.array(\n"
            "        y_true\n"
            "    )\n"
            "\n"
            "    y_pred = np.array(\n"
            "        y_pred\n"
            "    )\n"
            "\n"
            "    mask = (\n"
            "        y_true != 0\n"
            "    )\n"
            "\n"
            "    return (\n"
            "        np.mean(\n"
            "            np.abs(\n"
            "                (\n"
            "                    y_true[mask]\n"
            "                    -\n"
            "                    y_pred[mask]\n"
            "                )\n"
            "                /\n"
            "                y_true[mask]\n"
            "            )\n"
            "        )\n"
            "        * 100\n"
            "    )\n"
            "```\n"
            "\n"
            "This is a practical example of guarding against division by zero.\n"
