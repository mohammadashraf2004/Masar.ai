            "## 2. Bias and variance\n"
            "\n"
            "The chapter motivates ensembles through the bias–variance trade-off.\n"
            "\n"
            "---\n"
            "\n"
            "### 2.1 Bias\n"
            "\n"
            "Bias is systematic error caused by a model that is too restrictive or mismatched to the true pattern.\n"
            "\n"
            "Example:\n"
            "\n"
            "```text\n"
            "true relationship\n"
            "→ curved\n"
            "\n"
            "model\n"
            "→ straight line\n"
            "```\n"
            "\n"
            "A straight line repeatedly misses the curvature.\n"
            "\n"
            "This is:\n"
            "\n"
            "```text\n"
            "high bias\n"
            "```\n"
            "\n"
            "and often corresponds to:\n"
            "\n"
            "```text\n"
            "underfitting\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 2.2 Variance\n"
            "\n"
            "Variance describes how much a fitted model could change if the training data changed.\n"
            "\n"
            "A very flexible model may fit one training sample extremely closely but shift dramatically when trained on a slightly different sample.\n"
            "\n"
            "This is:\n"
            "\n"
            "```text\n"
            "high variance\n"
            "```\n"
            "\n"
            "and often corresponds to:\n"
            "\n"
            "```text\n"
            "overfitting\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 2.3 Source wording note\n"
            "\n"
            "The source initially describes high variance as occurring because a model “generalized too well.”\n"
            "\n"
            "That wording conflicts with the chapter's later explanation.\n"
            "\n"
            "The intended idea is:\n"
            "\n"
            "```text\n"
            "overfitting\n"
            "→ model fits training data too specifically\n"
            "→ poor stability/generalization on new samples\n"
            "→ high variance\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "## 3. The bias–variance trade-off\n"
            "\n"
