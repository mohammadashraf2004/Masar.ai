            "## 3. Lag and autocorrelation\n"
            "\n"
            "The chronological structure creates a special concept:\n"
            "\n"
            "```text\n"
            "autocorrelation\n"
            "```\n"
            "\n"
            "Also called:\n"
            "\n"
            "```text\n"
            "serial correlation\n"
            "```\n"
            "\n"
            "Autocorrelation measures the relationship between a series and a delayed version of itself.\n"
            "\n"
            "---\n"
            "\n"
            "### 3.1 What is a lag?\n"
            "\n"
            "A lag is a time delay.\n"
            "\n"
            "Example:\n"
            "\n"
            "```text\n"
            "lag 1\n"
            "→ compare today's value\n"
            "   with yesterday's value\n"
            "```\n"
            "\n"
            "For daily sales:\n"
            "\n"
            "```text\n"
            "Revenue_t\n"
            "versus\n"
            "Revenue_(t-1)\n"
            "```\n"
            "\n"
            "Lag 3 means comparing with:\n"
            "\n"
            "```text\n"
            "three time steps earlier\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 3.2 Create lag features\n"
            "\n"
            "Source code:\n"
            "\n"
            "```python\n"
            "sales_lag = (\n"
            "    sales.copy()\n"
            ")\n"
            "\n"
            "sales_lag[\n"
            "    'Date'\n"
            "] = pd.to_datetime(\n"
            "    sales_lag[\n"
            "        'Date'\n"
            "    ]\n"
            ")\n"
            "\n"
            "sales_lag.set_index(\n"
            "    'Date',\n"
            "    inplace=True\n"
            ")\n"
            "```\n"
            "\n"
            "Create lags:\n"
            "\n"
            "```python\n"
            "sales_lag[\n"
            "    'Revenue_lag_1'\n"
            "] = (\n"
            "    sales_lag[\n"
            "        'Revenue'\n"
            "    ].shift(1)\n"
            ")\n"
            "\n"
            "sales_lag[\n"
            "    'Revenue_lag_3'\n"
            "] = (\n"
            "    sales_lag[\n"
            "        'Revenue'\n"
            "    ].shift(3)\n"
            ")\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 3.3 Why lagging creates missing values\n"
            "\n"
            "Suppose:\n"
            "\n"
            "```text\n"
            "t1 Revenue = 100\n"
            "t2 Revenue = 120\n"
            "```\n"
            "\n"
            "At `t1`, there is no previous value for lag 1.\n"
            "\n"
            "So:\n"
            "\n"
            "```text\n"
            "Revenue_lag_1 at t1 = NaN\n"
            "```\n"
            "\n"
            "For lag 3, the first three positions have no earlier observation.\n"
            "\n"
            "This is expected.\n"
            "\n"
            "---\n"
            "\n"
            "### 3.4 Calculate autocorrelation\n"
            "\n"
            "The source uses:\n"
            "\n"
            "```python\n"
            "sales[\n"
            "    'Revenue'\n"
            "].autocorr(\n"
            "    lag=1\n"
            ")\n"
            "```\n"
            "\n"
            "Output:\n"
            "\n"
            "```text\n"
            "≈ -0.0335\n"
            "```\n"
            "\n"
            "The chapter interprets this as:\n"
            "\n"
            "- slightly negative,\n"
            "- very close to zero.\n"
            "\n"
            "The important point is the magnitude:\n"
            "\n"
            "```text\n"
            "near +1 → strong positive autocorrelation\n"
            "near -1 → strong negative autocorrelation\n"
            "near 0  → weak linear autocorrelation at that lag\n"
            "```\n"
            "\n"
            "### Source interpretation caution\n"
            "\n"
            "The source says the negative value means high revenue is often followed by lower revenue and vice versa. Because the reported value is only about `-0.0335`, the relationship is extremely weak. The sign is negative, but the magnitude is near zero.\n"
            "\n"
            "[[IMAGE_NEEDED: Lag and autocorrelation intuition | Show a daily revenue sequence and a copy shifted by one day; connect today with yesterday and label lag=1 | Learner should see autocorrelation as comparing the series with a shifted version of itself]]\n"
            "\n"
