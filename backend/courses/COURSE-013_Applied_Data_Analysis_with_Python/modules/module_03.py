            "## 9. Hypothesis testing fundamentals\n"
            "\n"
            "Inferential statistics often begins with two competing statements.\n"
            "\n"
            "### Null hypothesis\n"
            "\n"
            "The chapter describes the null hypothesis as:\n"
            "\n"
            "```text\n"
            "no difference\n"
            "no effect\n"
            "no change\n"
            "```\n"
            "\n"
            "Notation:\n"
            "\n"
            "```text\n"
            "H₀\n"
            "```\n"
            "\n"
            "### Alternative hypothesis\n"
            "\n"
            "The alternative states that a meaningful difference, effect, or relationship exists.\n"
            "\n"
            "Notation:\n"
            "\n"
            "```text\n"
            "Hₐ\n"
            "```\n"
            "\n"
            "Example:\n"
            "\n"
            "```text\n"
            "H₀: mean student weight = 68 kg\n"
            "Hₐ: mean student weight ≠ 68 kg\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 9.1 Significance level\n"
            "\n"
            "The source examples commonly use:\n"
            "\n"
            "```text\n"
            "α = 0.05\n"
            "```\n"
            "\n"
            "or:\n"
            "\n"
            "```text\n"
            "α = 0.01\n"
            "```\n"
            "\n"
            "The decision logic used in the code is:\n"
            "\n"
            "```python\n"
            "if p_value < alpha:\n"
            "    reject H0\n"
            "else:\n"
            "    fail to reject H0\n"
            "```\n"
            "\n"
            "### Why “fail to reject” matters\n"
            "\n"
            "A large p-value does not prove the null hypothesis is true.\n"
            "\n"
            "It means the observed evidence was not strong enough—under the test setup—to reject it.\n"
            "\n"
            "The supplied chapter sometimes writes “accept the null hypothesis” after code that says “fail to reject.” In this lesson, we preserve the code's decision but use the more cautious phrase:\n"
            "\n"
            "```text\n"
            "fail to reject H₀\n"
            "```\n"
            "\n"
            "because that is what the test directly supports.\n"
            "\n"
