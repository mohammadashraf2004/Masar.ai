            "## 5. Ordinary Least Squares and SSE\n"
            "\n"
            "The chapter introduces Ordinary Least Squares (OLS) as the technique used to find a best-fitting linear relationship.\n"
            "\n"
            "Its objective is to minimize:\n"
            "\n"
            "```text\n"
            "Sum of Squared Errors\n"
            "```\n"
            "\n"
            "or:\n"
            "\n"
            "```text\n"
            "SSE\n"
            "```\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "SSE\n"
            "=\n"
            "Σ(actual - predicted)²\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 5.1 Why square the errors?\n"
            "\n"
            "Squaring does two things:\n"
            "\n"
            "```text\n"
            "negative and positive errors\n"
            "→ both become positive\n"
            "\n"
            "large errors\n"
            "→ receive much larger penalty\n"
            "```\n"
            "\n"
            "Example:\n"
            "\n"
            "```text\n"
            "error = 2\n"
            "squared error = 4\n"
            "\n"
            "error = 10\n"
            "squared error = 100\n"
            "```\n"
            "\n"
            "A large miss matters much more under SSE.\n"
            "\n"
            "---\n"
            "\n"
            "### 5.2 Best-fit line\n"
            "\n"
            "OLS chooses the coefficient values that minimize total squared residual error.\n"
            "\n"
            "Mental model:\n"
            "\n"
            "```text\n"
            "candidate line A → SSE 900\n"
            "candidate line B → SSE 450\n"
            "candidate line C → SSE 200\n"
            "```\n"
            "\n"
            "The line with the smallest SSE is preferred among those candidates.\n"
