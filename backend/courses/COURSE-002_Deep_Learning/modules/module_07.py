            "## 1. How Convolutional Neural Networks Understand Images\n"
            "\n"
            "Images have an important structure that ordinary tabular data "
            "does not have: nearby pixels are related to one another.\n"
            "\n"
            "A convolutional neural network, or **ConvNet**, takes advantage "
            "of this spatial structure.\n"
            "\n"
            "A basic image-classification pipeline looks like:\n"
            "\n"
            "```text\n"
            "Image\n"
            "  ↓\n"
            "Convolution\n"
            "  ↓\n"
            "Feature maps\n"
            "  ↓\n"
            "Pooling\n"
            "  ↓\n"
            "More convolution\n"
            "  ↓\n"
            "Higher-level features\n"
            "  ↓\n"
            "Global pooling\n"
            "  ↓\n"
            "Classifier\n"
            "  ↓\n"
            "Class probabilities\n"
            "```\n"
            "\n"
            "### A first ConvNet\n"
            "\n"
            "For MNIST digit classification, a simple network can look like:\n"
            "\n"
            "```python\n"
            "inputs = keras.Input(shape=(28, 28, 1))\n"
            "\n"
            "x = layers.Conv2D(64, 3, activation=\"relu\")(inputs)\n"
            "x = layers.MaxPooling2D(2)(x)\n"
            "\n"
            "x = layers.Conv2D(128, 3, activation=\"relu\")(x)\n"
            "x = layers.MaxPooling2D(2)(x)\n"
            "\n"
            "x = layers.Conv2D(256, 3, activation=\"relu\")(x)\n"
            "x = layers.GlobalAveragePooling2D()(x)\n"
            "\n"
            "outputs = layers.Dense(10, activation=\"softmax\")(x)\n"
            "\n"
            "model = keras.Model(inputs, outputs)\n"
            "```\n"
            "\n"
            "The input shape is:\n"
            "\n"
            "```text\n"
            "(height, width, channels)\n"
            "\n"
            "(28, 28, 1)\n"
            "```\n"
            "\n"
            "The final dimension is 1 because MNIST images are grayscale.\n"
            "\n"
            "For an RGB image, the channel dimension would normally be 3:\n"
            "\n"
            "```text\n"
            "(height, width, 3)\n"
            "```\n"
            "\n"
            "### Why convolution instead of only Dense layers?\n"
            "\n"
            "A Dense layer learns relationships across its entire input "
            "representation at once.\n"
            "\n"
            "A convolutional layer instead looks at small local regions.\n"
            "\n"
            "For example, a 3 × 3 convolution examines small image patches:\n"
            "\n"
            "```text\n"
            "Image\n"
            "\n"
            "┌─────────────────┐\n"
            "│                 │\n"
            "│    ┌─────┐      │\n"
            "│    │3 × 3│      │\n"
            "│    └─────┘      │\n"
            "│                 │\n"
            "└─────────────────┘\n"
            "```\n"
            "\n"
            "The same learned detector is reused at many locations throughout "
            "the image.\n"
            "\n"
            "This gives ConvNets two extremely useful properties.\n"
            "\n"
            "### Property 1: translation invariance\n"
            "\n"
            "Suppose the network learns a detector for a certain edge.\n"
            "\n"
            "That detector can recognize the edge whether it appears near the "
            "top-left, center, or bottom-right of the image.\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "learn pattern once\n"
            "      ↓\n"
            "reuse detector across image locations\n"
            "```\n"
            "\n"
            "This is much more data efficient than relearning the same visual "
            "pattern independently for every possible image position.\n"
            "\n"
            "### Property 2: spatial feature hierarchies\n"
            "\n"
            "Visual concepts naturally form hierarchies.\n"
            "\n"
            "For example:\n"
            "\n"
            "```text\n"
            "pixels\n"
            "  ↓\n"
            "edges and textures\n"
            "  ↓\n"
            "simple shapes\n"
            "  ↓\n"
            "eyes / ears / wheels\n"
            "  ↓\n"
            "faces / animals / objects\n"
            "```\n"
            "\n"
            "Earlier convolutional layers tend to represent simple local "
            "patterns.\n"
            "\n"
            "Deeper layers combine them into more abstract concepts.\n"
            "\n"
            "### Feature maps\n"
            "\n"
            "The output of a convolutional layer is called a **feature map**.\n"
            "\n"
            "A feature map normally has shape:\n"
            "\n"
            "```text\n"
            "(height, width, channels)\n"
            "```\n"
            "\n"
            "For example:\n"
            "\n"
            "```text\n"
            "(26, 26, 64)\n"
            "```\n"
            "\n"
            "means:\n"
            "\n"
            "```text\n"
            "26 positions vertically\n"
            "26 positions horizontally\n"
            "64 learned feature channels\n"
            "```\n"
            "\n"
            "The channels no longer mean RGB colors.\n"
            "\n"
            "Instead, each channel represents the response of a learned "
            "feature detector.\n"
            "\n"
            "One channel may respond strongly to one kind of texture, another "
            "to a particular edge orientation, and deeper channels may respond "
            "to more complicated structures.\n"
            "\n"
            "### What is a filter?\n"
            "\n"
            "A convolutional layer contains multiple learned filters.\n"
            "\n"
            "Each filter scans local patches and produces one output feature "
            "channel.\n"
            "\n"
            "So if a layer has:\n"
            "\n"
            "```python\n"
            "layers.Conv2D(filters=64, kernel_size=3)\n"
            "```\n"
            "\n"
            "then:\n"
            "\n"
            "```text\n"
            "kernel size = 3 × 3\n"
            "number of output feature channels = 64\n"
            "```\n"
            "\n"
            "### The convolution kernel is reused\n"
            "\n"
            "The same learned kernel is applied to every valid spatial patch.\n"
            "\n"
            "This parameter sharing is a major reason ConvNets can represent "
            "visual patterns efficiently.\n"
            "\n"
            "### Padding\n"
            "\n"
            "A convolution can shrink spatial dimensions because the kernel "
            "cannot be centered at every border pixel without going beyond "
            "the image.\n"
            "\n"
            "For example:\n"
            "\n"
            "```text\n"
            "5 × 5 input\n"
            "+ 3 × 3 convolution\n"
            "+ no padding\n"
            "→ 3 × 3 output\n"
            "```\n"
            "\n"
            "Two common padding modes are:\n"
            "\n"
            "```text\n"
            "padding=\"valid\"\n"
            "→ no padding\n"
            "→ spatial dimensions may shrink\n"
            "\n"
            "padding=\"same\"\n"
            "→ add border values\n"
            "→ preserve width and height when stride = 1\n"
            "```\n"
            "\n"
            "### Strides\n"
            "\n"
            "The **stride** controls how far the convolution window moves each "
            "time.\n"
            "\n"
            "With:\n"
            "\n"
            "```text\n"
            "stride = 1\n"
            "```\n"
            "\n"
            "the window moves one position at a time.\n"
            "\n"
            "With:\n"
            "\n"
            "```text\n"
            "stride = 2\n"
            "```\n"
            "\n"
            "it skips positions and therefore reduces the spatial size more "
            "aggressively.\n"
            "\n"
            "### Max pooling\n"
            "\n"
            "Image classifiers often downsample feature maps with max pooling.\n"
            "\n"
            "For example:\n"
            "\n"
            "```text\n"
            "26 × 26 feature map\n"
            "       ↓ 2 × 2 max pooling\n"
            "13 × 13 feature map\n"
            "```\n"
            "\n"
            "For every small region, max pooling keeps the largest activation.\n"
            "\n"
            "If a local patch contains:\n"
            "\n"
            "```text\n"
            "[1, 7]\n"
            "[2, 4]\n"
            "```\n"
            "\n"
            "max pooling outputs:\n"
            "\n"
            "```text\n"
            "7\n"
            "```\n"
            "\n"
            "The intuition is that a feature map often represents the presence "
            "of some pattern. Keeping the strongest local activation preserves "
            "evidence that the pattern was present while reducing spatial size.\n"
            "\n"
            "### Why reduce spatial dimensions?\n"
            "\n"
            "As the network gets deeper, we want higher-level feature detectors "
            "to see increasingly larger regions of the original image.\n"
            "\n"
            "A common ConvNet progression is therefore:\n"
            "\n"
            "```text\n"
            "spatial dimensions ↓\n"
            "channel depth      ↑\n"
            "```\n"
            "\n"
            "For example:\n"
            "\n"
            "```text\n"
            "180 × 180 × 3\n"
            "       ↓\n"
            "178 × 178 × 32\n"
            "       ↓\n"
            "89 × 89 × 32\n"
            "       ↓\n"
            "87 × 87 × 64\n"
            "       ↓\n"
            "...\n"
            "       ↓\n"
            "7 × 7 × 512\n"
            "```\n"
            "\n"
            "The model gradually converts detailed spatial information into "
            "richer semantic feature channels.\n"
            "\n"
            "### Global average pooling\n"
            "\n"
            "A Dense classifier expects a vector rather than a 3D feature map.\n"
            "\n"
            "`GlobalAveragePooling2D` averages each feature channel across "
            "its spatial positions.\n"
            "\n"
            "For example:\n"
            "\n"
            "```text\n"
            "(3, 3, 256)\n"
            "      ↓ GlobalAveragePooling2D\n"
            "(256,)\n"
            "```\n"
            "\n"
            "Each output value summarizes how strongly one learned feature "
            "was present across the image.\n"
            "\n"
            "---\n"
            "\n"

