                       '\n'
                       '## 40. Query rewriting: retrieve the evidence, not the instruction\n'
                       '\n'
                       "The query flow begins before vector search. A user's message may combine "
                       'the task they want performed with the evidence that should be retrieved.\n'
                       '\n'
                       'The chapter uses:\n'
                       '\n'
                       '> Write a poem based on my travels in 2025.\n'
                       '\n'
                       'This contains:\n'
                       '\n'
                       '```text\n'
                       'task:      write a poem\n'
                       'evidence:  my travels in 2025\n'
                       '```\n'
                       '\n'
                       'Searching with the entire request may retrieve poems simply because “write '
                       'a poem” dominates similarity. The retrieval query should instead focus on '
                       'the evidence need:\n'
                       '\n'
                       '```text\n'
                       'original user query:\n'
                       '"Write a poem based on my travels in 2025."\n'
                       '\n'
                       'retrieval query:\n'
                       '"my travels in 2025"\n'
                       '```\n'
                       '\n'
                       'After retrieval, the **original user query** is still useful for '
                       'generation because the LLM needs to know that the final output should be a '
                       'poem.\n'
                       '\n'
                       'This separation is fundamental:\n'
                       '\n'
                       '```text\n'
                       'rewrite for retrieval\n'
                       '→ optimize evidence discovery\n'
                       '\n'
                       'original request for generation\n'
                       '→ preserve user intent\n'
                       '```\n'
                       '\n'
