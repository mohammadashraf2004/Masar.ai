                       'A large chunk may discuss many topics. Its embedding must compress all of '
                       'them into one vector, so no single topic is represented as sharply. A '
                       'smaller, coherent chunk can focus its representation on one idea.\n'
                       '\n'
                       'That creates a trade-off:\n'
                       '\n'
                       '```text\n'
                       'too large\n'
                       '→ mixed topics\n'
                       '→ diluted representation\n'
                       '→ more irrelevant context\n'
                       '\n'
                       'too small\n'
                       '→ missing context\n'
                       '→ fragmented evidence\n'
                       '→ relationships may be lost\n'
                       '```\n'
                       '\n'
                       'The best chunk is not defined by an absolute token count. It is defined by '
                       'how well it serves the retrieval and generation tasks on the actual '
                       'dataset.\n'
                       '\n'
                       'The source also notes that long context can make generation harder: models '
                       'may be less effective at finding the needed evidence when it is buried '
                       'among large amounts of text. This connects chunking to the “lost in the '
                       'middle” problem discussed later in evaluation.\n'
                       '\n'
                       '{{exercise:M01.L02.EX07}}\n'
                       '\n'
                       '---\n'
                       '\n'
                       '## 18. Fixed-size chunking and overlap\n'
                       '\n'
                       'Fixed-size chunking cuts a document every fixed number of characters, '
                       'words, or tokens. Its strengths are simplicity, predictable sizes, '
                       'efficient batching, and easy implementation.\n'
                       '\n'
                       'Its weakness is equally simple: **text does not respect arbitrary '
                       'boundaries**.\n'
                       '\n'
                       'A boundary can split:\n'
                       '\n'
                       '- a word,\n'
                       '- a sentence,\n'
                       '- a paragraph,\n'
                       '- a code block,\n'
                       '- a logical argument.\n'
                       '\n'
                       'Overlap is commonly added so that the end of one chunk is repeated at the '
                       'beginning of the next:\n'
                       '\n'
                       '```text\n'
                       'chunk 1: [--------------------]\n'
                       'chunk 2:              [--------------------]\n'
                       '                     ^ repeated overlap\n'
                       '```\n'
                       '\n'
                       'Overlap preserves local context across boundaries but creates duplicated '
                       'text. More overlap means more vectors, more storage, and potentially more '
                       'redundant retrieval results.\n'
                       '\n'
                       'Fixed-size chunking is therefore attractive when speed and predictability '
                       'matter, but its parameters should be evaluated rather than accepted by '
                       'habit.\n'
                       '\n'
                       '---\n'
                       '\n'
                       '## 19. Sentence- and paragraph-aware chunking\n'
                       '\n'
                       'Content-aware chunking respects linguistic boundaries. Instead of cutting '
                       'after an arbitrary number of characters, it splits at sentences or '
                       'paragraphs and can merge adjacent units to reach a practical size.\n'
                       '\n'
                       'This usually produces cleaner semantic units, but sentence splitting has '
                       'edge cases:\n'
                       '\n'
                       '- abbreviations,\n'
                       '- titles containing periods,\n'
                       '- unusual punctuation,\n'
                       '- question marks or punctuation inside quoted material.\n'
                       '\n'
                       'Libraries such as spaCy, Stanza, and NLTK provide sentence segmentation '
                       'tools designed to handle these cases better than a naive '
                       '`text.split(".")`.\n'
                       '\n'
                       'A sentence-aware pipeline might be:\n'
                       '\n'
                       '```text\n'
                       'document\n'
                       '→ detect sentences\n'
                       '→ accumulate sentences until target size\n'
                       '→ optionally retain overlap\n'
                       '→ emit chunk\n'
                       '```\n'
                       '\n'
                       'The key improvement is that boundaries now reflect language structure '
                       'rather than only length.\n'
                       '\n'
                       '---\n'
                       '\n'
                       '## 20. Recursive chunking\n'
                       '\n'
                       'Recursive chunking uses a hierarchy of separators. It first tries a coarse '
                       'boundary such as paragraphs. If a segment is still too large, it falls '
                       'back to smaller boundaries such as sentences and then clauses or '
                       'characters.\n'
                       '\n'
                       'Conceptually:\n'
                       '\n'
                       '```text\n'
                       'paragraph boundary\n'
                       '    ↓ if still too large\n'
                       'sentence boundary\n'
                       '    ↓ if still too large\n'
                       'smaller delimiter\n'
                       '```\n'
                       '\n'
                       'This makes recursive chunking flexible: it attempts to preserve large '
                       'natural units while still enforcing a maximum size.\n'
                       '\n'
                       "LangChain's `RecursiveCharacterTextSplitter` is a representative "
                       'implementation.\n'
                       '\n'
                       'The method is still dependent on delimiter quality. A recursive splitter '
                       'knows structure only through the separators you give it; it does not '
                       'inherently understand topic boundaries.\n'
                       '\n'
                       '---\n'
                       '\n'
                       '## 21. Document-structure-aware chunking\n'
                       '\n'
                       'If a document exposes explicit hierarchy—Markdown headings, HTML sections, '
                       'document chapters—those boundaries can become part of the chunking '
                       'strategy.\n'
                       '\n'
                       'For Markdown:\n'
                       '\n'
                       '```text\n'
                       '# Chapter\n'
                       '## Section\n'
                       '### Subsection\n'
                       '```\n'
                       '\n'
                       'can be treated as a hierarchy rather than plain text.\n'
                       '\n'
                       'This preserves relationships that fixed-size splitting might erase. A '
                       'chunk from a subsection can retain metadata identifying its parent section '
                       'or chapter. That additional structure is useful for filtering, citations, '
                       'and context expansion.\n'
                       '\n'
                       'The limitation is that this strategy depends on trustworthy structure. '
                       'Poorly formatted or unstructured documents provide fewer usable '
                       'boundaries.\n'
                       '\n'
                       '---\n'
                       '\n'
                       '## 22. Semantic chunking\n'
                       '\n'
                       'Semantic chunking attempts to create boundaries based on meaning rather '
                       'than only syntax. One approach embeds sentences and groups nearby '
                       'sentences while their semantic similarity remains high, creating chunks '
                       'that correspond more closely to topic changes.\n'
                       '\n'
                       'Its appeal is clear: if retrieval itself is semantic, why not build '
                       'semantically coherent retrieval units?\n'
                       '\n'
                       'But semantic chunking introduces costs:\n'
                       '\n'
                       '- embedding work is required during chunk construction,\n'
                       '- chunk size becomes less predictable,\n'
                       '- implementation and tuning are more complex,\n'
                       '- debugging boundaries can be harder.\n'
                       '\n'
                       'The source highlights an important research result: on some benchmarks, '
                       'semantic chunking did not clearly outperform fixed-size chunking. That '
                       'finding should not be treated as universal because older benchmarks often '
                       'contain relatively short passages.\n'
                       '\n'
                       'The practical conclusion is **evaluate on your own corpus and queries** '
                       'rather than assuming the most sophisticated chunker must be the best.\n'
                       '\n'
