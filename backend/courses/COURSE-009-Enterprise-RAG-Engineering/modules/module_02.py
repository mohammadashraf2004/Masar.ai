                       '## Key terminology\n'
                       '\n'
                       '| Term | Meaning |\n'
                       '|---|---|\n'
                       '| RAG stack | The collection of ingestion, retrieval, ranking, prompting, '
                       'and generation components that together implement retrieval-augmented '
                       'generation. |\n'
                       '| Ingestion flow | The path that prepares new or changed source data for '
                       'later retrieval. |\n'
                       '| Query flow | The per-request path that rewrites, retrieves, selects, '
                       'prompts, and generates. |\n'
                       '| Parsing | Extracting useful knowledge and structure from source formats '
                       'while discarding irrelevant presentation artifacts. |\n'
                       '| OCR | Optical character recognition; converting text visible in scanned '
                       'images into machine-readable text. |\n'
                       '| Metadata | Structured attributes associated with content, such as '
                       'speaker, date, document ID, or permissions. |\n'
                       '| Chunk | A smaller unit of a document used for embedding, retrieval, and '
                       'context assembly. |\n'
                       '| Chunking | The process of dividing larger text into retrieval-sized '
                       'units. |\n'
                       '| Chunk overlap | Repeated content between adjacent chunks to preserve '
                       'context across boundaries. |\n'
                       '| Fixed-size chunking | Splitting by a predefined character, word, or '
                       'token count. |\n'
                       '| Sentence/paragraph chunking | Splitting according to linguistic '
                       'boundaries. |\n'
                       '| Recursive chunking | Splitting through a hierarchy of delimiters from '
                       'coarse to finer boundaries. |\n'
                       '| Document-structure chunking | Using headings or explicit hierarchy to '
                       'determine chunk boundaries. |\n'
                       '| Semantic chunking | Choosing boundaries according to semantic/topic '
                       'similarity. |\n'
                       '| Embedding | A numerical vector representation designed to encode '
                       'semantic properties of text. |\n'
                       '| Dense representation | A compact learned vector in which many dimensions '
                       'can carry semantic information. |\n'
                       '| Dense retrieval | Retrieval based on dense embedding similarity. |\n'
                       '| Sparse retrieval | Keyword/lexical retrieval using sparse term-oriented '
                       'representations or methods such as BM25. |\n'
                       '| Static embedding | A representation where a word has the same vector '
                       'regardless of context. |\n'
                       '| Contextualized embedding | A representation that changes according to '
                       'surrounding text. |\n'
                       '| Embedding dimension | The number of numeric components in an embedding '
                       'vector. |\n'
                       '| MTEB | Massive Text Embedding Benchmark, used to compare embedding '
                       'models across retrieval-related tasks. |\n'
                       '| MRL | Matryoshka Representation Learning, which trains embeddings so '
                       'useful information remains in truncated prefixes. |\n'
                       '| Dot product | A vector operation commonly used to score similarity. |\n'
                       '| Cosine similarity | A similarity measure based on the angle between '
                       'vectors; equivalent to dot product for unit-normalized vectors. |\n'
                       '| Vector distance | A numerical measure of dissimilarity between vectors. '
                       '|\n'
                       '| Exact nearest neighbor | Search that evaluates exact nearest results, '
                       'often through exhaustive comparison. |\n'
                       '| ANN | Approximate nearest neighbor search, which trades some exactness '
                       'for much faster retrieval. |\n'
                       '| HNSW | Hierarchical Navigable Small World, a multilayer graph algorithm '
                       'for approximate nearest-neighbor search. |\n'
                       '| FAISS | An open-source similarity-search library implementing ANN '
                       'methods including HNSW. |\n'
                       '| Vector database | A data system for storing, indexing, updating, '
                       'filtering, and searching embedding vectors. |\n'
                       '| pgvector | A PostgreSQL extension that adds vector types and similarity '
                       'search. |\n'
