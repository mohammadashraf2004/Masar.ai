                       '## Important misconceptions\n'
                       '\n'
                       '### Misconception\n'
                       '\n'
                       '> “If I use a powerful LLM, ingestion quality matters less.”\n'
                       '\n'
                       '### Why this is wrong\n'
                       '\n'
                       'The generator only sees what the upstream pipeline preserved and '
                       'retrieved. Corrupted parsing or lost chunks cannot be reliably '
                       'reconstructed by a stronger model.\n'
                       '\n'
                       '### Misconception\n'
                       '\n'
                       '> “A PDF already contains paragraphs in logical reading order.”\n'
                       '\n'
                       '### Why this is wrong\n'
                       '\n'
                       'PDF is primarily a visual-layout format. Text can be stored as positioned '
                       'characters, so reading order often has to be inferred.\n'
                       '\n'
                       '### Misconception\n'
                       '\n'
                       '> “Parsing means deleting all formatting and metadata.”\n'
                       '\n'
                       '### Why this is wrong\n'
                       '\n'
                       'Some structure—speaker, date, document section, security label, or other '
                       'attributes—may be essential for later filtering and interpretation.\n'
                       '\n'
                       '### Misconception\n'
                       '\n'
                       '> “Using a VLM automatically makes document parsing more accurate.”\n'
                       '\n'
                       '### Why this is wrong\n'
                       '\n'
                       'VLMs are flexible but generative. They can hallucinate, cost more, run '
                       'slower, and may still fail to reproduce document content exactly.\n'
                       '\n'
                       '### Misconception\n'
                       '\n'
                       '> “Huge LLM context windows eliminate the need for chunking.”\n'
                       '\n'
                       '### Why this is wrong\n'
                       '\n'
                       'Chunking also improves evidence selection, controls latency and cost, and '
                       "must respect the embedding model's own context limit.\n"
                       '\n'
                       '### Misconception\n'
                       '\n'
                       '> “Smaller chunks are always better.”\n'
                       '\n'
                       '### Why this is wrong\n'
                       '\n'
                       'Tiny chunks can lose surrounding context and relationships. Chunking is a '
                       'balance between focus and sufficient context.\n'
                       '\n'
                       '### Misconception\n'
                       '\n'
                       '> “Semantic chunking is automatically the best strategy.”\n'
                       '\n'
                       '### Why this is wrong\n'
                       '\n'
                       'The chapter cites benchmark evidence where semantic and fixed-size '
                       'chunking performed similarly. The right choice must be validated on the '
                       'target corpus.\n'
                       '\n'
                       '### Misconception\n'
                       '\n'
                       '> “Embeddings are only a synonym-matching trick.”\n'
                       '\n'
                       '### Why this is wrong\n'
                       '\n'
                       'Embeddings can represent broader semantic relationships, such as linking a '
                       'US query to a document about California.\n'
                       '\n'
                       '### Misconception\n'
                       '\n'
                       '> “More embedding dimensions are always better.”\n'
                       '\n'
                       '### Why this is wrong\n'
                       '\n'
                       'Higher dimensions can increase storage and compute. The best dimension is '
                       'a quality-efficiency trade-off.\n'
                       '\n'
                       '### Misconception\n'
                       '\n'
                       '> “ANN search returns the exact nearest vector.”\n'
                       '\n'
                       '### Why this is wrong\n'
                       '\n'
                       'Approximate nearest-neighbor methods deliberately trade exactness for '
                       'speed and may occasionally miss the mathematical nearest point.\n'
                       '\n'
                       '### Misconception\n'
                       '\n'
                       '> “A vector database is just a nearest-neighbor function.”\n'
                       '\n'
                       '### Why this is wrong\n'
                       '\n'
                       'A vector database also handles persistence, updates, deletes, metadata, '
                       'filtering, indexing, and operational integration.\n'
                       '\n'
                       '### Misconception\n'
                       '\n'
                       '> “The generator receives embedding vectors.”\n'
                       '\n'
                       '### Why this is wrong\n'
                       '\n'
                       'Embeddings select the records. The generator normally receives the '
                       'original text chunks plus the user request.\n'
                       '\n'
                       '### Misconception\n'
                       '\n'
                       '> “If retrieval returns relevant chunks, more chunks can only help.”\n'
                       '\n'
                       '### Why this is wrong\n'
                       '\n'
                       'A large k can introduce redundancy, irrelevant evidence, higher cost, and '
                       'a noisier prompt.\n'
                       '\n'
                       '### Misconception\n'
                       '\n'
                       "> “Query rewriting should replace the user's original request "
                       'everywhere.”\n'
                       '\n'
                       '### Why this is wrong\n'
                       '\n'
                       'The rewritten query is optimized for retrieval. The original query is '
                       'still needed during generation to preserve the requested task.\n'
                       '\n'
                       '### Misconception\n'
                       '\n'
                       '> “RAG quality can be judged only from the final answer.”\n'
                       '\n'
                       '### Why this is wrong\n'
                       '\n'
                       'A final error may originate in parsing, chunking, embeddings, filtering, '
                       'ranking, prompt assembly, or generation. Intermediate artifacts must be '
                       'inspected.\n'
