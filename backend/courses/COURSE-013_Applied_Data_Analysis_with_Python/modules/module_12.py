            "\n"
            "---\n"
            "\n"
            "## 43. Encoder, bottleneck, and decoder\n"
            "\n"
            "### Encoder\n"
            "\n"
            "Maps input into a compact representation.\n"
            "\n"
            "Goal:\n"
            "\n"
            "```text\n"
            "retain important structure\n"
            "while discarding unnecessary detail\n"
            "```\n"
            "\n"
            "### Bottleneck\n"
            "\n"
            "Small central representation.\n"
            "\n"
            "Also called:\n"
            "\n"
            "```text\n"
            "latent representation\n"
            "```\n"
            "\n"
            "This forces compression.\n"
            "\n"
            "### Decoder\n"
            "\n"
            "Reconstructs the input from the latent representation.\n"
            "\n"
            "Training tries to reduce:\n"
            "\n"
            "```text\n"
            "input\n"
            "vs\n"
            "reconstruction\n"
            "difference\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "## 44. Types of autoencoders\n"
            "\n"
            "### Vanilla autoencoder\n"
            "\n"
            "Basic dense encoder-decoder.\n"
            "\n"
            "### Convolutional autoencoder\n"
            "\n"
            "Uses convolutional layers.\n"
            "\n"
            "Well suited to:\n"
            "\n"
            "```text\n"
            "images\n"
            "spatial structure\n"
            "```\n"
            "\n"
            "### Denoising autoencoder\n"
            "\n"
            "Receives:\n"
            "\n"
            "```text\n"
            "corrupted/noisy input\n"
            "```\n"
            "\n"
            "and learns to output:\n"
            "\n"
            "```text\n"
            "clean target\n"
            "```\n"
            "\n"
            "### Variational Autoencoder (VAE)\n"
            "\n"
            "Learns a probabilistic latent representation and can generate new samples similar to training data.\n"
            "\n"
            "The source connects VAEs with Generative AI.\n"
            "\n"
            "### Sparse autoencoder\n"
            "\n"
            "Uses regularization so only a small number of latent neurons are active.\n"
            "\n"
            "Goal:\n"
            "\n"
            "```text\n"
            "specialized\n"
            "meaningful\n"
            "sparse representations\n"
