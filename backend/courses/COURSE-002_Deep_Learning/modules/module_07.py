            "## Key terminology\n"
            "\n"
            "| Term | Meaning |\n"
            "|---|---|\n"
            "| ConvNet / CNN | Neural network designed to exploit local spatial structure in image-like data |\n"
            "| Convolution | Applying a learned local transformation repeatedly across spatial positions |\n"
            "| Kernel | Learned weights used by a convolution to transform local patches |\n"
            "| Filter | Learned feature detector that produces an output feature channel |\n"
            "| Feature map | Spatial map containing activations of learned visual features |\n"
            "| Channel | Depth dimension of an image or intermediate feature map |\n"
            "| Translation invariance | Ability to recognize a learned pattern across different spatial locations |\n"
            "| Spatial hierarchy | Progression from simple local patterns to increasingly abstract visual concepts |\n"
            "| Padding | Adding border values so convolution can control output spatial size |\n"
            "| Stride | Number of positions a convolution window moves at each step |\n"
            "| Max pooling | Downsampling operation that keeps the strongest local activation |\n"
            "| Global average pooling | Averaging each feature map into one value |\n"
            "| Data augmentation | Random realistic transformations used to create training variations |\n"
            "| Backbone | Pretrained or trainable feature-extraction portion of a model |\n"
            "| Feature extraction | Reusing fixed pretrained representations with a new classifier |\n"
            "| Freezing | Preventing selected model parameters from being updated |\n"
            "| Fine-tuning | Carefully updating pretrained parameters for a new task |\n"
            "| Transfer learning | Reusing knowledge learned on one task to help another task |\n"
            "| Residual connection | Shortcut that adds an earlier representation back to a block output |\n"
            "| Vanishing gradient | Loss of useful gradient signal as it passes through a deep chain of operations |\n"
            "| Batch normalization | Layer that adaptively normalizes intermediate activations |\n"
            "| Depthwise convolution | Spatial convolution performed independently for each channel |\n"
            "| Pointwise convolution | 1 × 1 convolution commonly used to mix channels |\n"
            "| SeparableConv2D | Depthwise convolution followed by pointwise channel mixing |\n"
            "| MHR | Modularity, hierarchy, and reuse architecture principle |\n"
            "| Vision Transformer | Vision architecture that processes an image as a sequence of patches |\n"
