            "\n"
            "---\n"
            "\n"
            "### 7.4 Scalar multiplication\n"
            "\n"
            "```python\n"
            "arr1 * 3\n"
            "```\n"
            "\n"
            "Output:\n"
            "\n"
            "```text\n"
            "[[ 3  6]\n"
            " [ 9 12]]\n"
            "```\n"
            "\n"
            "This is the intuition behind broadcasting in the chapter:\n"
            "\n"
