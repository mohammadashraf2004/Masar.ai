            "## 25. Naive Bayes\n"
            "\n"
            "Naive Bayes is a probabilistic classification method based on Bayes' theorem.\n"
            "\n"
            "The chapter calls it:\n"
            "\n"
            "```text\n"
            "parametric\n"
            "model-based\n"
            "```\n"
            "\n"
            "and emphasizes its usefulness in:\n"
            "\n"
            "- document classification,\n"
            "- sentiment analysis,\n"
            "- spam detection.\n"
            "\n"
            "---\n"
            "\n"
            "### 25.1 Why “naive”?\n"
            "\n"
            "The model assumes features are conditionally independent given the class.\n"
            "\n"
            "Example:\n"
            "\n"
            "```text\n"
            "Age\n"
            "Income\n"
            "Product usage\n"
            "```\n"
            "\n"
            "may be correlated in reality.\n"
            "\n"
            "Naive Bayes simplifies the calculation by treating them as conditionally independent once the class is known.\n"
            "\n"
            "---\n"
            "\n"
            "## 26. Bayes' theorem\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "Posterior\n"
            "∝\n"
            "Likelihood\n"
            "×\n"
            "Prior\n"
            "```\n"
            "\n"
            "Full idea:\n"
            "\n"
            "```text\n"
            "P(C | X)\n"
            "=\n"
            "P(X | C) × P(C)\n"
            "/\n"
            "P(X)\n"
            "```\n"
            "\n"
            "Where:\n"
            "\n"
            "```text\n"
            "P(C)\n"
            "→ prior\n"
            "\n"
            "P(X | C)\n"
            "→ likelihood\n"
            "\n"
            "P(C | X)\n"
            "→ posterior\n"
            "\n"
            "P(X)\n"
            "→ evidence\n"
            "```\n"
            "\n"
            "The source uses a profession analogy:\n"
            "\n"
            "```text\n"
            "prior\n"
            "→ how common a profession is\n"
            "\n"
            "likelihood\n"
            "→ how likely observed clues are for that profession\n"
            "\n"
            "posterior\n"
            "→ updated belief after clues\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 26.1 Churn example\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "P(Churn | Urban)\n"
            "```\n"
            "\n"
            "depends on:\n"
            "\n"
            "```text\n"
            "P(Urban | Churn)\n"
            "P(Churn)\n"
            "P(Urban)\n"
            "```\n"
            "\n"
            "The posterior answers:\n"
            "\n"
            "> Given the observed evidence, how likely is the class?\n"
            "\n"
            "---\n"
            "\n"
            "## 27. Naive Bayes classification steps\n"
            "\n"
            "The chapter gives this sequence.\n"
            "\n"
            "### Step 1 — Prior\n"
            "\n"
            "Calculate:\n"
            "\n"
            "```text\n"
            "P(class)\n"
            "```\n"
            "\n"
            "from class frequency.\n"
            "\n"
            "---\n"
            "\n"
            "### Step 2 — Likelihood\n"
            "\n"
            "Calculate:\n"
            "\n"
            "```text\n"
            "P(feature | class)\n"
            "```\n"
            "\n"
            "The exact method depends on the Naive Bayes variant.\n"
            "\n"
            "The source discusses Gaussian Naive Bayes, which models numeric feature likelihoods using a normal distribution.\n"
            "\n"
            "---\n"
            "\n"
            "### Step 3 — Independence assumption\n"
            "\n"
            "Multiply feature likelihoods:\n"
            "\n"
            "```text\n"
            "P(X | class)\n"
            "≈\n"
            "P(x₁ | class)\n"
            "×\n"
            "P(x₂ | class)\n"
            "×\n"
            "...\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### Step 4 — Posterior\n"
            "\n"
            "Combine prior and likelihood.\n"
            "\n"
            "Because evidence is the same across classes when comparing them, the source works with proportional posterior scores.\n"
            "\n"
            "---\n"
            "\n"
            "### Step 5 — Choose class\n"
            "\n"
            "Predict the class with the highest posterior probability.\n"
            "\n"
            "---\n"
            "\n"
            "### 27.1 Source pipeline\n"
            "\n"
            "The source uses:\n"
            "\n"
            "```text\n"
            "categorical features\n"
            "→ OneHotEncoder\n"
            "\n"
            "numeric features\n"
            "→ StandardScaler\n"
            "\n"
            "classifier\n"
            "→ GaussianNB\n"
            "```\n"
            "\n"
            "It says standardizing numeric features is optional for Gaussian Naive Bayes in the shown workflow.\n"
            "\n"
