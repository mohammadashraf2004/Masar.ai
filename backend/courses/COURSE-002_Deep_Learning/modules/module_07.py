            "## 3. Reusing a Pretrained ConvNet\n"
            "\n"
            "When you only have a small dataset, training every visual feature "
            "detector from random initialization can be inefficient.\n"
            "\n"
            "A powerful alternative is **transfer learning**.\n"
            "\n"
            "The central idea is:\n"
            "\n"
            "> A network trained on a large image dataset may already have "
            "learned useful visual features that can be reused for your new task.\n"
            "\n"
            "### Why visual features can be reused\n"
            "\n"
            "Early convolutional layers often learn generic patterns such as:\n"
            "\n"
            "```text\n"
            "edges\n"
            "colors\n"
            "textures\n"
            "simple shapes\n"
            "```\n"
            "\n"
            "Higher layers learn more task-specific concepts such as:\n"
            "\n"
            "```text\n"
            "eyes\n"
            "ears\n"
            "fur patterns\n"
            "object parts\n"
            "```\n"
            "\n"
            "This means a network trained on one large image dataset can often "
            "provide useful features for another image task.\n"
            "\n"
            "### Backbone and classifier head\n"
            "\n"
            "An image classifier can be thought of as two parts:\n"
            "\n"
            "```text\n"
            "Image\n"
            "  ↓\n"
            "Pretrained backbone\n"
            "  ↓\n"
            "Feature representation\n"
            "  ↓\n"
            "Task-specific classifier\n"
            "```\n"
            "\n"
            "The **backbone** is the feature extractor.\n"
            "\n"
            "The classifier head converts those features into predictions for "
            "your specific classes.\n"
            "\n"
            "### Feature extraction\n"
            "\n"
            "Feature extraction means:\n"
            "\n"
            "1. Use the pretrained backbone to compute features.\n"
            "2. Keep the pretrained representation fixed.\n"
            "3. Train a new classifier using those features.\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "Pretrained network\n"
            "\n"
            "[generic visual feature extractor]\n"
            "              ↓\n"
            "         keep this\n"
            "\n"
            "[old classifier]\n"
            "              ↓\n"
            "         remove this\n"
            "\n"
            "add new task-specific classifier\n"
            "```\n"
            "\n"
            "### Why not normally reuse the old classifier?\n"
            "\n"
            "The old classifier is specialized for the classes of the original "
            "training task.\n"
            "\n"
            "The backbone is more reusable because it contains spatial visual "
            "representations rather than only final class decisions.\n"
            "\n"
            "### Fast feature extraction\n"
            "\n"
            "One approach is to run every image through the pretrained backbone "
            "once and save the resulting features.\n"
            "\n"
            "For example, your images may become feature tensors with shape:\n"
            "\n"
            "```text\n"
            "(samples, 6, 6, 2048)\n"
            "```\n"
            "\n"
            "Then train a small classifier:\n"
            "\n"
            "```python\n"
            "inputs = keras.Input(shape=(6, 6, 2048))\n"
            "x = layers.GlobalAveragePooling2D()(inputs)\n"
            "x = layers.Dense(256, activation=\"relu\")(x)\n"
            "x = layers.Dropout(0.25)(x)\n"
            "outputs = layers.Dense(1, activation=\"sigmoid\")(x)\n"
            "```\n"
            "\n"
            "This is computationally cheap because the expensive pretrained "
            "backbone is only executed once per image.\n"
            "\n"
            "The limitation is important:\n"
            "\n"
            "> You cannot naturally apply new random augmentation every epoch "
            "after the features have already been saved.\n"
            "\n"
            "### Feature extraction with augmentation\n"
            "\n"
            "The alternative is to keep the backbone inside the training model.\n"
            "\n"
            "Now each randomly augmented image passes through the backbone "
            "during training.\n"
            "\n"
            "This costs more computation, but allows augmentation.\n"
            "\n"
            "### Freezing the pretrained backbone\n"
            "\n"
            "Before training the newly added classifier, freeze the pretrained "
            "base:\n"
            "\n"
            "```python\n"
            "conv_base.trainable = False\n"
            "```\n"
            "\n"
            "Why?\n"
            "\n"
            "The new classifier begins with random parameters.\n"
            "\n"
            "Early training therefore produces large, noisy errors.\n"
            "\n"
            "If those updates immediately flow through the pretrained backbone, "
            "they can destroy useful visual representations that took large-scale "
            "training to learn.\n"
            "\n"
            "So initially:\n"
            "\n"
            "```text\n"
            "pretrained backbone\n"
            "→ FROZEN\n"
            "\n"
            "new classifier\n"
            "→ TRAINABLE\n"
            "```\n"
            "\n"
            "### Fine-tuning\n"
            "\n"
            "Once the new classifier has learned to use the pretrained "
            "features, you can carefully adapt the pretrained representation "
            "to the new problem.\n"
            "\n"
            "This is called **fine-tuning**.\n"
            "\n"
            "The correct sequence is important:\n"
            "\n"
            "```text\n"
            "1. Load pretrained backbone\n"
            "2. Add new classifier\n"
            "3. Freeze backbone\n"
            "4. Train new classifier\n"
            "5. Unfreeze some or all appropriate backbone layers\n"
            "6. Recompile the model\n"
            "7. Continue training with a very small learning rate\n"
            "```\n"
            "\n"
            "### Why use a small learning rate?\n"
            "\n"
            "Fine-tuning should **adjust** good pretrained features, not replace "
            "them with large random changes.\n"
            "\n"
            "For example:\n"
            "\n"
            "```python\n"
            "optimizer = keras.optimizers.Adam(learning_rate=1e-5)\n"
            "```\n"
            "\n"
            "A small learning rate makes changes to pretrained representations "
            "more gradual.\n"
            "\n"
            "### Partial fine-tuning\n"
            "\n"
            "You do not always need to unfreeze the entire backbone.\n"
            "\n"
            "A useful strategy is:\n"
            "\n"
            "```text\n"
            "early layers\n"
            "→ keep frozen\n"
            "→ generic edges / textures\n"
            "\n"
            "later layers\n"
            "→ fine-tune\n"
            "→ more task-specific visual concepts\n"
            "```\n"
            "\n"
            "For example:\n"
            "\n"
            "```python\n"
            "conv_base.trainable = True\n"
            "\n"
            "for layer in conv_base.layers[:-4]:\n"
            "    layer.trainable = False\n"
            "```\n"
            "\n"
            "This reduces the number of parameters being adjusted and can lower "
            "the risk of overfitting on a small dataset.\n"
            "\n"
            "### Batch normalization during fine-tuning\n"
            "\n"
            "A special caution applies to pretrained "
            "`BatchNormalization` layers.\n"
            "\n"
            "The source recommends leaving these layers frozen during "
            "fine-tuning so that their internal statistics are not destabilized "
            "by the small fine-tuning updates.\n"
            "\n"
            "### The practical small-data toolbox\n"
            "\n"
            "For a small image dataset, you now have three progressively more "
            "powerful strategies:\n"
            "\n"
            "```text\n"
            "1. Train a small ConvNet from scratch\n"
            "        ↓\n"
            "2. Use a pretrained backbone for feature extraction\n"
            "        ↓\n"
            "3. Fine-tune pretrained representations\n"
            "```\n"
            "\n"
            "The chapter's dogs-versus-cats experiments illustrate why "
            "pretrained visual features can dramatically outperform training "
            "from scratch when only a small amount of data is available.\n"
            "\n"
