            "## Important misconceptions\n"
            "\n"
            "### Misconception 1\n"
            "\n"
            "> Hyperparameters and model weights are learned in the same way.\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "Model weights are optimized with gradient descent. Hyperparameters "
            "such as model depth or optimizer choice are usually selected using "
            "a separate search procedure.\n"
            "\n"
            "### Misconception 2\n"
            "\n"
            "> The test set should be used as the objective during hyperparameter tuning.\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "Repeatedly choosing models based on test results effectively trains "
            "the development process on the test set. Validation data should "
            "guide tuning, while the test set remains reserved for final evaluation.\n"
            "\n"
            "### Misconception 3\n"
            "\n"
            "> An ensemble improves simply because it contains many models.\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "Diversity is critical. Many nearly identical models tend to make "
            "similar errors and provide less ensemble benefit.\n"
            "\n"
            "### Misconception 4\n"
            "\n"
            "> Data parallelism allows a model larger than one GPU's memory.\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "Every data-parallel worker stores a complete model replica. If the "
            "model cannot fit on one device, model parallelism or sharding is needed.\n"
            "\n"
            "### Misconception 5\n"
            "\n"
            "> Eight GPUs guarantee exactly eight times faster training.\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "Communication, synchronization, data loading, and insufficient "
            "device utilization introduce scaling overhead.\n"
            "\n"
            "### Misconception 6\n"
            "\n"
            "> Running every part of training in float16 is always safe.\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "Small gradients and some numerically sensitive operations require "
            "greater precision. Mixed precision keeps sensitive state and updates "
            "in float32.\n"
            "\n"
            "### Misconception 7\n"
            "\n"
            "> Quantization means simply casting float values directly to int8.\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "Values must first be scaled into the representable integer range. "
            "Naively casting small floating-point values would destroy information.\n"
            "\n"
            "### Misconception 8\n"
            "\n"
            "> Lower numerical precision always makes a model faster.\n"
            "\n"
            "### Why this is wrong\n"
            "\n"
            "Actual speed depends on hardware support, model size, implementation "
            "overhead, and whether the workload is large enough to benefit from "
            "specialized low-precision computation.\n"
