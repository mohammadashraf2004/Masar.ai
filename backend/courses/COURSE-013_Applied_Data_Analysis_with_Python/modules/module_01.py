            "### 3.3 CRISP-DM — Cross-Industry Process for Data Mining\n"
            "\n"
            "CRISP-DM is one of the most practical workflows in the chapter.\n"
            "\n"
            "It contains six stages:\n"
            "\n"
            "1. Business understanding\n"
            "2. Data understanding\n"
            "3. Data preparation\n"
            "4. Modeling\n"
