            '## Key terminology\n'
            '\n'
            '| Term | Meaning |\n'
            '|---|---|\n'
            '| Image classification | Assigning one or more labels to an entire image |\n'
            '| Image segmentation | Assigning labels at pixel level |\n'
            '| Object detection | Predicting object classes and bounding boxes |\n'
            '| Semantic segmentation | Pixel classification without separating instances of the same class |\n'
            '| Instance segmentation | Pixel-level segmentation that separates individual object instances |\n'
            '| Panoptic segmentation | Semantic class plus instance identity for pixels |\n'
            '| Segmentation mask | Pixel-level target or prediction aligned with an image |\n'
            '| Encoder | Network stage that compresses an image into learned features |\n'
            '| Decoder | Network stage that reconstructs spatial output from learned features |\n'
            '| Strided convolution | Convolution that also reduces spatial resolution |\n'
            '| Transposed convolution | Learnable operation commonly used to increase spatial resolution |\n'
            '| IoU | Intersection area divided by union area |\n'
            '| SAM | Promptable pretrained segmentation model |\n'
            '| Point prompt | A point indicating foreground or background for segmentation |\n'
            '| Box prompt | A rough box indicating the object to segment |\n'
            '| Bounding box | Rectangle describing approximate object location |\n'
            '| R-CNN | Two-stage detection family based on region proposals followed by classification |\n'
            '| Single-stage detector | Detector that predicts box and class information directly |\n'
            '| YOLO | Popular single-stage detection family |\n'
            '| Confidence score | Estimate of whether a prediction represents a valid object and/or how reliable the box is |\n'
            '| Backbone | Feature-extraction network used inside a larger vision system |\n'
            '| RetinaNet | Single-stage object detector |\n'
            '| Feature Pyramid Network | Multi-scale feature architecture combining semantic and spatial information |\n'
            '| COCO | Large annotated computer-vision dataset used for detection and segmentation research |\n'
