            '\n'
            '```text\n'
            '0 -> foreground\n'
            '1 -> background\n'
            '2 -> contour\n'
            '```\n'
            '\n'
            'The important concept is:\n'
            '\n'
            '> The mask is the target label, but the label exists at every pixel position.\n'
            '\n'
            '### Input and target shapes\n'
            '\n'
            'Suppose images are resized to:\n'
            '\n'
            '```text\n'
            '200 × 200\n'
