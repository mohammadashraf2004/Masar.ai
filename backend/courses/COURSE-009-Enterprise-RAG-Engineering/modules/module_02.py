                       '\n'
                       '## 25. Embeddings: representing meaning instead of spelling\n'
                       '\n'
                       'Keyword matching operates on surface form. That creates obvious misses:\n'
                       '\n'
                       '```text\n'
                       '"United States" ≠ "U.S." ≠ "America"\n'
                       '"two" ≠ "2"\n'
                       '```\n'
                       '\n'
                       'even though the terms can refer to closely related concepts.\n'
                       '\n'
                       'Embeddings map text to numerical vectors designed so that semantic '
                       'relationships are reflected by geometric relationships. Two texts with '
                       'different spelling can land near each other if they have similar meaning.\n'
                       '\n'
                       'This helps solve two opposite problems:\n'
                       '\n'
                       '- **surface dissimilarity, semantic similarity:** “Uncle Sam” and “US '
                       'Government” can be related.\n'
                       '- **surface similarity, semantic dissimilarity:** “cat” and “hat” look '
                       'alike but mean different things.\n'
                       '\n'
                       'The point is not merely synonym matching. A good embedding can capture '
                       'broader semantic associations. The chapter gives the example that a query '
                       'about cases in the US may retrieve a document about California while '
                       'rejecting one about Alberta, even if neither document literally says '
                       '“US.”\n'
                       '\n'
                       'This is why semantic retrieval is called **dense retrieval**: dense '
                       'numerical representations are used to compare meaning.\n'
                       '\n'
                       '{{exercise:M01.L02.EX10}}\n'
                       '\n'
                       '---\n'
                       '\n'
                       '## 26. What exactly is an embedding?\n'
                       '\n'
                       'An embedding model transforms an input text into a vector of '
                       'floating-point numbers:\n'
                       '\n'
                       '```text\n'
                       'text\n'
                       '→ embedding model\n'
                       '→ [0.021, -0.114, 0.337, ...]\n'
                       '```\n'
                       '\n'
                       'Each position is a dimension of the embedding space. Individual dimensions '
                       'usually do not have a simple human-readable label. The useful property is '
                       'the geometry of the full vector.\n'
                       '\n'
                       'If two vectors point in similar directions, their texts are usually '
                       'semantically related. This lets a RAG system compare a query vector with '
                       'stored chunk vectors using efficient numerical operations.\n'
                       '\n'
                       'A common RAG path is:\n'
                       '\n'
                       '```text\n'
                       'document chunk ──embed──> stored vector\n'
                       'user query     ──embed──> query vector\n'
                       '                           ↓\n'
                       '                    similarity search\n'
                       '```\n'
                       '\n'
                       'The vector is a search representation. It is not the text itself, and it '
                       'is not what the generative LLM ultimately reads. After retrieval, the '
                       'system returns to the original chunk text for generation.\n'
                       '\n'
                       '---\n'
                       '\n'
                       '## 27. From one-hot vectors to contextual embeddings\n'
                       '\n'
                       'The chapter briefly places modern embeddings in historical context.\n'
                       '\n'
                       'Early representations such as one-hot encoding assign each vocabulary item '
                       'its own position in a very large vector. Such a representation encodes '
                       'identity but not useful semantic closeness.\n'
                       '\n'
                       'Word2Vec changed the picture by learning vectors from surrounding-word '
                       'prediction. It produced famous geometric relationships between word '
                       'meanings, but its word embeddings are **static**: a word receives the same '
                       'vector regardless of context.\n'
                       '\n'
                       'BERT introduced contextualized representations, where the representation '
                       'of a token depends on the surrounding text.\n'
                       '\n'
                       'For RAG, the important progression is:\n'
                       '\n'
                       '```text\n'
                       'identity-based representation\n'
                       '→ learned semantic representation\n'
                       '→ context-sensitive semantic representation\n'
                       '```\n'
                       '\n'
                       'Modern sentence/document embedding models build on this idea to represent '
                       'whole queries and chunks in ways suitable for retrieval.\n'
                       '\n'
                       '---\n'
                       '\n'
                       '## 28. Selecting an embedding model\n'
                       '\n'
                       'Embedding model choice creates several trade-offs.\n'
                       '\n'
                       '### Model size and retrieval quality\n'
                       'Larger models may capture semantics more accurately but can require more '
                       'memory and more inference time. Benchmarks such as MTEB can help compare '
                       'candidate models, but application-specific evaluation is still necessary.\n'
                       '\n'
                       '### Embedding dimensionality\n'
                       'More dimensions can preserve more information, but they increase:\n'
                       '\n'
                       '- vector storage,\n'
                       '- memory bandwidth,\n'
                       '- index size,\n'
                       '- search cost.\n'
                       '\n'
                       '### Input context length\n'
                       'The model must accept the chosen chunk size. Otherwise data may be '
                       'truncated.\n'
                       '\n'
                       '### Deployment constraints\n'
                       'A production design may care about throughput, hardware, API cost, '
                       'supported languages, and database compatibility.\n'
                       '\n'
                       'The correct embedding model is therefore not automatically the one with '
                       'the highest benchmark score. It is the one that produces adequate '
                       'retrieval quality under your system constraints.\n'
                       '\n'
                       '---\n'
                       '\n'
                       '## 29. Matryoshka Representation Learning and dimension reduction\n'
                       '\n'
                       'Some embedding models are trained using **Matryoshka Representation '
                       'Learning (MRL)** so that useful semantic information is concentrated '
                       'toward earlier dimensions. This allows a full vector to be truncated while '
                       'retaining much of its retrieval capability.\n'
                       '\n'
                       'The motivation is operational:\n'
                       '\n'
                       '```text\n'
                       'fewer dimensions\n'
                       '→ smaller vectors\n'
                       '→ less storage\n'
                       '→ less memory traffic\n'
                       '→ faster search\n'
                       '```\n'
                       '\n'
                       'but aggressive reduction can reduce retrieval quality.\n'
                       '\n'
                       'The chapter notes that while MRL permits truncation, power-of-two '
                       'subdimensions are commonly used because training often optimizes '
                       'particular granularities.\n'
                       '\n'
                       'The engineering decision is another evaluation problem: reduce dimensions '
                       'until you reach a useful efficiency point **without crossing the quality '
                       'threshold your application requires**.\n'
                       '\n'
                       '{{exercise:M01.L02.EX11}}\n'
                       '\n'
                       '---\n'
                       '\n'
                       '## 30. Practical embedding constraints: truncation, precision, and '
                       'transport\n'
                       '\n'
                       'Three practical issues can quietly affect a RAG system.\n'
                       '\n'
                       '### 1. Silent input truncation\n'
                       "If a chunk exceeds an embedding model's context window, some serving "
                       'frameworks may truncate it. Always make chunk-size limits explicit and '
                       'test boundary cases.\n'
                       '\n'
                       '### 2. Vector precision\n'
                       'Storing 32-bit floating-point numbers is accurate but expensive. Lower '
                       'precision—such as 16-bit floats or 8-bit integers—can reduce storage and '
                       'computation, at the cost of possible quality loss.\n'
                       '\n'
                       '### 3. Transport representation\n'
                       'Embedding APIs may serialize arrays in JSON. JSON is convenient but '
                       'inefficient for numerical payloads and can create string-serialization '
                       'overhead. The chapter notes that some platforms support Base64-encoded '
                       'binary data, which preserves floating-point values more efficiently but '
                       'requires client-side decoding.\n'
                       '\n'
                       'These details do not change embedding theory, but at production scale they '
                       'affect bandwidth, storage, latency, and cost.\n'
                       '\n'
