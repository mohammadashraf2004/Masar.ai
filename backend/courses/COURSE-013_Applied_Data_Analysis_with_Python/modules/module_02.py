            "\n"
            "For NumPy arrays:\n"
            "\n"
            "```python\n"
            "np.array([1, 2]) + np.array([3, 4])\n"
            "```\n"
            "\n"
            "means numerical addition:\n"
            "\n"
            "```text\n"
            "[4, 6]\n"
            "```\n"
