            "\n"
            "### 3.1 KDD — Knowledge Discovery from Data\n"
            "\n"
            "**KDD** focuses on discovering meaningful patterns and knowledge from data.\n"
            "\n"
            "The chapter describes seven major phases.\n"
            "\n"
            "#### Stage 1 — Data cleaning\n"
            "\n"
            "The goal is to improve data quality.\n"
            "\n"
            "Typical problems include:\n"
            "\n"
            "- missing values,\n"
            "- duplicates,\n"
            "- noise,\n"
            "- outliers,\n"
            "- inconsistent values.\n"
            "\n"
            "If the data is poor, the final insight will also be unreliable.\n"
            "\n"
            "#### Stage 2 — Data integration\n"
            "\n"
            "Organizations often store information in different systems.\n"
            "\n"
            "For example:\n"
            "\n"
            "```text\n"
            "CRM system\n"
            "+\n"
            "payment database\n"
            "+\n"
            "website analytics\n"
            "+\n"
            "support records\n"
            "=\n"
            "integrated analytical dataset\n"
            "```\n"
            "\n"
            "The purpose of this stage is to bring relevant sources together.\n"
            "\n"
            "#### Stage 3 — Data selection\n"
            "\n"
            "Not every available column or record is useful.\n"
            "\n"
            "The analyst chooses:\n"
            "\n"
            "- relevant records,\n"
            "- relevant fields,\n"
            "- relevant periods,\n"
            "- relevant customer groups.\n"
            "\n"
            "This selection should be driven by the problem being solved.\n"
            "\n"
            "#### Stage 4 — Data transformation\n"
            "\n"
            "Raw data may need to be converted into a more useful analytical form.\n"
            "\n"
            "Examples:\n"
            "\n"
            "- converting text dates into timestamps,\n"
            "- normalizing numerical values,\n"
            "- encoding categories,\n"
            "- aggregating transactions,\n"
            "- creating derived variables.\n"
            "\n"
            "#### Stage 5 — Data mining\n"
            "\n"
            "This is where patterns are discovered.\n"
            "\n"
            "The source gives examples such as:\n"
            "\n"
            "- regression,\n"
            "- classification,\n"
            "- clustering,\n"
            "- anomaly detection,\n"
            "- association-rule mining,\n"
            "- recommender systems.\n"
            "\n"
            "#### Stage 6 — Pattern evaluation\n"
            "\n"
            "Not every pattern is useful.\n"
            "\n"
            "The team must ask:\n"
            "\n"
            "- Is the pattern reliable?\n"
            "- Is it meaningful?\n"
            "- Is it actionable?\n"
            "- Does it generalize?\n"
            "- Is it only random noise?\n"
            "\n"
            "#### Stage 7 — Knowledge presentation\n"
            "\n"
            "Useful patterns must be communicated.\n"
            "\n"
            "Possible formats include:\n"
            "\n"
            "- charts,\n"
            "- dashboards,\n"
            "- reports,\n"
            "- presentations,\n"
            "- written interpretations.\n"
            "\n"
