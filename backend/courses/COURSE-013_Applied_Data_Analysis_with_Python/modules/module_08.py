            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 8.1 Forward fill\n"
            "\n"
            "```python\n"
            "sales_filled = (\n"
            "    sales.ffill()\n"
            ")\n"
            "```\n"
            "\n"
            "A missing value is replaced with the last valid prior value.\n"
            "\n"
            "Conceptually:\n"
            "\n"
            "```text\n"
            "10\n"
            "NaN\n"
            "NaN\n"
            "13\n"
            "```\n"
            "\n"
            "becomes:\n"
            "\n"
            "```text\n"
            "10\n"
            "10\n"
            "10\n"
            "13\n"
            "```\n"
            "\n"
            "The source suggests uses such as:\n"
