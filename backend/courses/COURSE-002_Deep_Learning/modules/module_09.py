            '\n'
            '```text\n'
            'Classification\n'
            'Segmentation\n'
            'Detection\n'
            '```\n'
            '\n'
            'They answer different questions.\n'
            '\n'
            '### Image classification\n'
            '\n'
            'Classification asks:\n'
            '\n'
            '> What is in this image?\n'
            '\n'
            'Example:\n'
            '\n'
            '```text\n'
            'input: photo\n'
