            "## 33. Mean Absolute Percentage Error (MAPE)\n"
            "\n"
            "MAPE expresses average error as a percentage.\n"
            "\n"
            "Conceptual form:\n"
            "\n"
            "```text\n"
            "MAPE\n"
            "=\n"
            "average(\n"
            "    |actual - forecast|\n"
            "    /\n"
            "    |actual|\n"
            ") × 100\n"
            "```\n"
            "\n"
            "The source highlights:\n"
            "\n"
            "- scale-free interpretation,\n"
            "- intuitive percentage output.\n"
            "\n"
            "Source example:\n"
            "\n"
            "```text\n"
            "MAPE = 29%\n"
            "```\n"
            "\n"
            "Interpretation:\n"
            "\n"
