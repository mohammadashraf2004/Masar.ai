            "\n"
            "#### Stage 1 — Business understanding\n"
            "\n"
            "Before touching the data, understand:\n"
            "\n"
            "- the client's goal,\n"
            "- the problem statement,\n"
            "- the constraints,\n"
            "- what success looks like,\n"
            "- what decisions the solution should support.\n"
            "\n"
            "Example:\n"
            "\n"
            "```text\n"
            "Weak problem:\n"
            "\"Build a machine-learning model.\"\n"
            "\n"
            "Better problem:\n"
            "\"Reduce customer churn by identifying customers likely to leave early enough for the retention team to act.\"\n"
            "```\n"
            "\n"
            "#### Stage 2 — Data understanding\n"
            "\n"
            "Study the available data.\n"
            "\n"
            "Questions include:\n"
            "\n"
            "- What datasets exist?\n"
            "- What do the columns mean?\n"
            "- Is data missing?\n"
            "- Are values inconsistent?\n"
            "- Which variables appear related?\n"
            "- Are there obvious quality issues?\n"
            "\n"
            "#### Stage 3 — Data preparation\n"
            "\n"
            "Create analytics-ready data.\n"
            "\n"
            "The source mentions:\n"
            "\n"
            "- missing-value handling,\n"
            "- anomaly detection,\n"
            "- transformations,\n"
            "- scaling,\n"
            "- feature engineering.\n"
            "\n"
            "This stage often consumes a large amount of project time.\n"
            "\n"
            "#### Stage 4 — Modeling\n"
            "\n"
            "Choose and train an appropriate model.\n"
            "\n"
            "The method depends on the problem.\n"
            "\n"
            "For example:\n"
            "\n"
            "```text\n"
            "Predict a number       → regression\n"
