            "Pandas uses missing markers such as:\n"
            "\n"
            "```text\n"
            "NaN\n"
            "```\n"
            "\n"
            "for missing numerical/tabular values.\n"
            "\n"
            "---\n"
            "\n"
            "### 15.1 Detect missing values\n"
            "\n"
            "Two equivalent forms shown in the chapter are:\n"
            "\n"
