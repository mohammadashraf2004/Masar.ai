            "## 12. Weighted moving average\n"
            "\n"
            "A simple moving average gives equal weight to observations in the window.\n"
            "\n"
            "A weighted moving average (WMA) assigns different weights.\n"
            "\n"
            "The chapter uses increasing weights so more recent values matter more.\n"
            "\n"
            "```python\n"
            "import numpy as np\n"
            "\n"
            "weights = np.arange(\n"
            "    1,\n"
            "    8\n"
            ")\n"
            "```\n"
            "\n"
            "Apply:\n"
            "\n"
            "```python\n"
            "filtered_sales[\n"
            "    'WMA_7_Revenue'\n"
            "] = (\n"
            "    filtered_sales[\n"
            "        'Revenue'\n"
            "    ]\n"
            "    .rolling(\n"
            "        window=7\n"
            "    )\n"
            "    .apply(\n"
            "        lambda x:\n"
            "            np.dot(\n"
            "                x,\n"
            "                weights\n"
            "            )\n"
            "            /\n"
            "            weights.sum(),\n"
            "        raw=True\n"
            "    )\n"
            ")\n"
            "```\n"
            "\n"
            "Conceptual idea:\n"
            "\n"
            "```text\n"
            "older values\n"
            "→ lower weight\n"
            "\n"
            "newer values\n"
            "→ higher weight\n"
            "```\n"
            "\n"
            "This makes the smoothed series more responsive to recent movement than a simple average.\n"
            "\n"
