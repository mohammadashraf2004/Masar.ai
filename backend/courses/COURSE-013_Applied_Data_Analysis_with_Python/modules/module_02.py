            "\n"
            "Real datasets frequently come from multiple sources.\n"
            "\n"
            "Combining them correctly is essential.\n"
            "\n"
            "The chapter distinguishes two ideas:\n"
            "\n"
            "```text\n"
            "merge/join → combine using keys or indexes\n"
            "concat     → stack similar structures\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 14.1 Example tables\n"
            "\n"
            "Suppose one table contains driver destinations:\n"
            "\n"
            "```text\n"
            "dest\n"
            "EmpNr | Destination\n"
            "```\n"
            "\n"
            "and another contains tips:\n"
            "\n"
            "```text\n"
            "tips\n"
            "EmpNr | Amount\n"
            "```\n"
            "\n"
            "The shared key is:\n"
            "\n"
            "```text\n"
            "EmpNr\n"
            "```\n"
            "\n"
            "That key allows the records to be matched.\n"
            "\n"
            "---\n"
            "\n"
            "### 14.2 Inner join\n"
            "\n"
            "```python\n"
            "pd.merge(\n"
            "    dest,\n"
            "    tips,\n"
            "    on='EmpNr',\n"
            "    how='inner'\n"
            ")\n"
            "```\n"
            "\n"
            "An inner join keeps only matching keys present in both DataFrames.\n"
            "\n"
            "Think:\n"
            "\n"
            "```text\n"
            "left ∩ right\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 14.3 Full outer join\n"
            "\n"
            "```python\n"
            "pd.merge(\n"
            "    dest,\n"
            "    tips,\n"
            "    on='EmpNr',\n"
            "    how='outer'\n"
            ")\n"
            "```\n"
            "\n"
            "An outer join keeps all keys from both sides.\n"
            "\n"
            "Where no match exists, missing cells appear as `NaN`.\n"
            "\n"
            "Think:\n"
            "\n"
            "```text\n"
            "left ∪ right\n"
            "```\n"
            "\n"
            "---\n"
            "\n"
            "### 14.4 Right join\n"
            "\n"
            "```python\n"
            "pd.merge(\n"
            "    dest,\n"
            "    tips,\n"
            "    on='EmpNr',\n"
            "    how='right'\n"
            ")\n"
            "```\n"
            "\n"
            "Keep all rows from the right DataFrame.\n"
            "\n"
            "Unmatched left-side values become missing.\n"
            "\n"
            "---\n"
            "\n"
            "### 14.5 Left join\n"
            "\n"
            "```python\n"
            "pd.merge(\n"
            "    dest,\n"
            "    tips,\n"
            "    on='EmpNr',\n"
