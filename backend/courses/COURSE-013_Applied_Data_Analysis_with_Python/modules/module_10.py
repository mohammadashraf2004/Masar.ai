            "## 33. Isolation Forest\n"
            "\n"
            "Isolation Forest uses random partitioning.\n"
            "\n"
            "Core intuition:\n"
            "\n"
            "> An anomalous point is easier to isolate.\n"
            "\n"
            "The algorithm repeatedly:\n"
            "\n"
            "- selects a random feature,\n"
            "- selects a random split value,\n"
            "- partitions observations.\n"
            "\n"
            "Unlike a supervised decision tree:\n"
            "\n"
            "```text\n"
            "no Gini\n"
            "no entropy\n"
            "no class-purity optimization\n"
            "```\n"
            "\n"
            "The splits are intentionally random.\n"
            "\n"
            "---\n"
            "\n"
            "## 34. Isolation trees and path length\n"
            "\n"
            "Each tree is built on a sample of the data.\n"
            "\n"
            "For one point:\n"
            "\n"
            "```text\n"
            "path length\n"
            "=\n"
            "number of edges\n"
            "from root\n"
            "to isolating leaf\n"
            "```\n"
            "\n"
            "Interpretation:\n"
            "\n"
            "```text\n"
            "short path\n"
            "→ easy to isolate\n"
            "→ more anomalous\n"
            "\n"
            "long path\n"
            "→ located in dense/normal region\n"
            "→ less anomalous\n"
            "```\n"
            "\n"
            "The forest averages this behavior across many trees.\n"
            "\n"
