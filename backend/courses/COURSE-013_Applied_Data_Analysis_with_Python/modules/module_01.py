            "- handling missing values,\n"
            "- treating outliers,\n"
            "- transforming features,\n"
            "- creating new features.\n"
            "\n"
            "#### Model\n"
            "\n"
            "Train predictive models.\n"
            "\n"
            "The source lists examples such as:\n"
            "\n"
            "- decision trees,\n"
            "- K-nearest neighbors,\n"
            "- support vector machines,\n"
            "- logistic regression,\n"
            "- linear regression,\n"
            "- neural networks,\n"
