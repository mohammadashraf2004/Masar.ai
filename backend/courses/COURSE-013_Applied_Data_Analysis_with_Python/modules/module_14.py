            "\n"
            "---\n"
            "\n"
            "## 29. Controlled noise examples\n"
            "\n"
            "The chapter creates two synthetic noise types.\n"
            "\n"
            "### Gaussian noise\n"
            "\n"
            "Random zero-centered variations added to many pixels.\n"
            "\n"
            "### Salt-and-pepper noise\n"
            "\n"
            "A fraction of pixels replaced with:\n"
            "\n"
            "```text\n"
            "0\n"
            "→ black\n"
            "\n"
            "1\n"
            "→ white\n"
            "```\n"
            "\n"
            "Controlled noise makes filter behavior easier to compare.\n"
            "\n"
            "---\n"
            "\n"
            "## 30. Gaussian blur\n"
            "\n"
            "Gaussian blur replaces each pixel with a weighted neighborhood average.\n"
            "\n"
            "Closer pixels receive greater weight.\n"
            "\n"
            "Parameters in the source:\n"
            "\n"
            "### Kernel size\n"
            "\n"
            "Larger neighborhood:\n"
            "\n"
            "```text\n"
            "stronger smoothing\n"
            "more detail loss\n"
            "```\n"
            "\n"
            "### Sigma\n"
            "\n"
            "Controls how quickly weights fall with distance.\n"
            "\n"
            "Source example:\n"
            "\n"
            "```python\n"
            "g3 = cv2.GaussianBlur(\n"
            "    gauss,\n"
            "    (3, 3),\n"
            "    sigmaX=0.8\n"
            ")\n"
            "\n"
            "g7 = cv2.GaussianBlur(\n"
            "    gauss,\n"
            "    (7, 7),\n"
            "    sigmaX=2.0\n"
            ")\n"
            "```\n"
            "\n"
            "The larger configuration smooths more strongly but softens detail more.\n"
            "\n"
            "---\n"
            "\n"
            "## 31. Median filter\n"
            "\n"
            "Median filtering replaces the center pixel with the median neighborhood value.\n"
            "\n"
            "It is particularly useful for:\n"
            "\n"
            "```text\n"
            "salt-and-pepper noise\n"
            "```\n"
            "\n"
            "because isolated extreme values do not dominate the median.\n"
            "\n"
            "Source:\n"
            "\n"
            "```python\n"
            "m3 = cv2.medianBlur(\n"
            "    sp,\n"
            "    3\n"
            ")\n"
            "\n"
            "m5 = cv2.medianBlur(\n"
            "    sp,\n"
            "    5\n"
            ")\n"
            "```\n"
            "\n"
            "A larger neighborhood removes more impulse noise but can distort detail more strongly.\n"
            "\n"
            "---\n"
            "\n"
            "## 32. Bilateral filter\n"
            "\n"
            "Bilateral filtering considers two kinds of closeness:\n"
            "\n"
            "```text\n"
            "spatial closeness\n"
            "+\n"
            "intensity/color similarity\n"
            "```\n"
            "\n"
            "This lets it smooth flat regions while preserving strong boundaries better than ordinary blur in some cases.\n"
            "\n"
            "Source controls:\n"
            "\n"
            "```text\n"
            "d\n"
            "→ neighborhood diameter\n"
            "\n"
            "sigmaSpace\n"
            "→ spatial influence\n"
            "\n"
            "sigmaColor\n"
            "→ intensity/color similarity tolerance\n"
            "```\n"
            "\n"
            "Example:\n"
            "\n"
            "```python\n"
            "bilat = cv2.bilateralFilter(\n"
            "    gauss,\n"
            "    d=9,\n"
            "    sigmaColor=0.10,\n"
            "    sigmaSpace=9\n"
            ")\n"
            "```\n"
            "\n"
